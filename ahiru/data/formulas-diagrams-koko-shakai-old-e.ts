import type { DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, fresh, band } from './diagram-kit';

const K = {
  blue: [C.blue, FILL.blue],
  green: [C.green, FILL.green],
  red: [C.red, FILL.red],
  main: [C.main, FILL.warm],
  purple: [C.purple, FILL.purple],
  gray: [C.gray, FILL.gray],
} as const;
type Col = keyof typeof K;

// 1スライド = まっさらな図 + 下の帯のひとこと
const sl = (note: string, els: ReturnType<typeof bx>[], text: string, k: Col = 'blue') => {
  const n = text.split('\n').length;
  return {
    note,
    add: [...fresh(...els), ...band(148, bx(14, 158, 292, 26 + 15 * n, text, K[k][0], K[k][1], 13))],
  };
};
const B = (x: number, y: number, w: number, h: number, t: string, k: Col, size = 12) => bx(x, y, w, h, t, K[k][0], K[k][1], size);
const sea = (x: number, y: number, w: number, h: number, t = '海') => [bx(x, y, w, h, undefined, C.blue, FILL.blue), lb(x + w / 2, y + h / 2 + 4, t, 12, C.blue, 'middle', true)];
const land = (x: number, y: number, w: number, h: number, t: string) => [bx(x, y, w, h, undefined, C.gray, FILL.warm), lb(x + w / 2, y + h / 2 + 4, t, 12, C.ink, 'middle', true)];
const mtn = (x: number, y: number, w: number, h: number, t?: string) => [pg([[x, y + h], [x + w / 2, y], [x + w, y + h]], C.gray, FILL.gray), ...(t ? [lb(x + w / 2, y + h - 6, t, 10, C.ink, 'middle', true)] : [])];
const chain = (labels: string[], y: number, k: Col, h = 44, size = 12) => {
  const n = labels.length;
  const gap = 16;
  const w = (300 - gap * (n - 1)) / n;
  const out: ReturnType<typeof bx>[] = [];
  labels.forEach((t, i) => {
    const x = 10 + i * (w + gap);
    if (i > 0) out.push(ar(x - gap + 1, y + h / 2, x - 1, y + h / 2, K[k][0]));
    out.push(B(x, y, w, h, t, k, size));
  });
  return out;
};
const vchain = (labels: string[], x: number, w: number, y0: number, k: Col, h = 24, gap = 10, size = 12) => {
  const out: ReturnType<typeof bx>[] = [];
  labels.forEach((t, i) => {
    const y = y0 + i * (h + gap);
    if (i > 0) out.push(ar(x + w / 2, y - gap + 1, x + w / 2, y - 1, K[k][0]));
    out.push(B(x, y, w, h, t, k, size));
  });
  return out;
};
const bar = (x: number, base: number, w: number, h: number, k: Col, t?: string) => [
  bx(x, base - h, w, h, undefined, K[k][0], K[k][1]),
  ...(t ? [lb(x + w / 2, base + 12, t, 10, C.ink, 'middle')] : []),
];

