/** 横に並べた線分図の箱。parts＝[量, 文字, 色, ぬり, 文字サイズ]。scale＝1あたりの長さ(px)。 */
function seg(x: number, y: number, h: number, scale: number, parts: [number, string | undefined, string, string, number?][]): DiagramElement[] {
  const out: DiagramElement[] = [];
  let cx = x;
  for (const [v, t, c, f, s] of parts) {
    out.push(bx(cx, y, v * scale, h, t, c, f, s ?? 13));
    cx += v * scale;
  }
  return out;
}

