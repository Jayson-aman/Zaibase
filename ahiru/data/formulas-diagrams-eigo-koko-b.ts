import type { DiagramElement, DiagramFigure } from './figures';
import type { Slide } from './diagram-kit';
import { C, FILL, bx, lb, ar, ln, ci, show, fresh } from './diagram-kit';

type P = readonly [string, string];
const B: P = [C.blue, FILL.blue];
const G: P = [C.green, FILL.green];
const R: P = [C.red, FILL.red];
const V: P = [C.purple, FILL.purple];
const Y: P = [C.main, FILL.yellow];
const Gy: P = [C.gray, FILL.gray];

const k = (x: number, y: number, w: number, h: number, text: string | undefined, p: P, size = 12): DiagramElement => bx(x, y, w, h, text, p[0], p[1], size);
const S = (note: string, ...els: DiagramElement[]): Slide => ({ note, add: fresh(...els) });
const hd = (text: string, col: string = C.ink): DiagramElement => lb(160, 16, text, 14, col, 'middle', true);
const ft = (text: string, p: P = G, size = 13): DiagramElement => k(20, 198, 280, 30, text, p, size);

// 文を語ごとの箱に分けて横にならべる（幅は文字数に比例）。
const wlen = (t: string): number => [...t].reduce((a, c) => a + (c.charCodeAt(0) > 255 ? 1.8 : 1), 0) + 2;
const sent = (items: [string, P][], y: number, h = 30, size = 12, gap = 4, x0 = 8, total = 304): DiagramElement[] => {
  const tw = items.reduce((a, [t]) => a + wlen(t), 0);
  const avail = total - gap * (items.length - 1);
  let x = x0;
  return items.map(([t, p]) => {
    const w = (avail * wlen(t)) / tw;
    const e = k(x, y, w, h, t, p, size);
    x += w + gap;
    return e;
  });
};

// 時計（h時m分）。長針は赤、短針は黒。
const clock = (cx: number, cy: number, r: number, h: number, m: number): DiagramElement[] => {
  const a = (deg: number, L: number): [number, number] => [cx + Math.sin((deg * Math.PI) / 180) * L, cy - Math.cos((deg * Math.PI) / 180) * L];
  const mh = a(m * 6, r * 0.85);
  const hh = a((h % 12) * 30 + m * 0.5, r * 0.55);
  return [
    ci(cx, cy, r, undefined, C.gray, '#FFFFFF'),
    lb(cx, cy - r + 9, '12', 9, C.gray), lb(cx, cy + r - 9, '6', 9, C.gray), lb(cx + r - 9, cy, '3', 9, C.gray), lb(cx - r + 9, cy, '9', 9, C.gray),
    ln(cx, cy, hh[0], hh[1], C.ink, false, 4), ln(cx, cy, mh[0], mh[1], C.red, false, 2.5),
  ];
};

