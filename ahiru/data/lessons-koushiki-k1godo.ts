なぜ「3つの情報」がそろえば三角形の形がただ1つに決まるのか、実際に三角形を作図する場面を想像すると納得できます。

SSS（3辺）の場合：まず1つの辺の長さを直線上にとって固定します。残り2つの頂点は、それぞれの辺の長さを半径とするコンパスの弧として描けますが、2つの円（弧）が交わる点は、直線をはさんで上下に1点ずつしかありません。上側の点を選んでも下側の点を選んでも、できる三角形は裏返しただけの合同な三角形（鏡映）になるので、3辺の長さを決めた時点で三角形の形はただ1つに決まります。

SAS（2辺とその間の角）の場合：まず1つの頂点から、与えられた角度で2本の辺を引きます（分度器で角度を固定するイメージ）。それぞれの辺の長さも決まっているので、2本の辺の先端の位置がそれぞれ1点に決まり、残りの1辺（底辺）の長さと、残り2つの角の大きさもすべて自動的に1通りに決まります。

ASA（1辺とその両端の角）の場合：まず1つの辺の長さを直線上に固定します。その両端から、それぞれ与えられた角度で半直線を伸ばしていくと、2本の半直線は（平行でない限り）ただ1点で交わります。この交点が残りの頂点の位置になるので、三角形の形はただ1つに決まります。

一方、「2辺とその間ではない1つの角」（SSA）が等しいだけでは、三角形の形は1つに決まりません。角の頂点から1辺を固定して引いたあと、もう1辺の長さをコンパスの半径として弧を描くと、その弧が底辺（の延長）と2点で交わってしまう場合があるからです。この場合、条件を満たす三角形が2種類できてしまい、どちらが正しいか決まりません。これが「SSAは合同条件にならない」理由です。

