import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

const T = (i: number, text: string, color: string = C.ink): DiagramElement => lb(8, 160 + 16 * i, text, 13, color, 'start', true);
const ceil = (x: number, w: number): DiagramElement => bx(x, 6, w, 6, undefined, C.gray, FILL.gray);
const pul = (cx: number, cy: number, r = 10, fixed = false): DiagramElement => ci(cx, cy, r, undefined, C.gray, fixed ? FILL.gray : FILL.yellow);
const wt = (cx: number, y: number, w: number, h: number, text: string): DiagramElement[] => [ln(cx, y - 5, cx, y, C.gray), bx(cx - w / 2, y, w, h, text, C.blue, FILL.blue, 12)];
const rope = (x1: number, y1: number, x2: number, y2: number): DiagramElement => ln(x1, y1, x2, y2, C.main, false, 2);
const num = (x: number, y: number, n: number): DiagramElement => ci(x, y, 7, String(n), C.red, FILL.red, 10);
const spring = (x: number, y0: number, y1: number, n = 6, amp = 8, color: string = C.gray): DiagramElement[] => {
  const pts: [number, number][] = [[x, y0], [x, y0 + 4]];
  const seg = (y1 - y0 - 8) / n;
  for (let i = 0; i < n; i++) pts.push([x + (i % 2 === 0 ? -amp : amp), y0 + 4 + seg * (i + 0.5)]);
  pts.push([x, y1 - 4], [x, y1]);
  const out: DiagramElement[] = [];
  for (let i = 0; i < pts.length - 1; i++) out.push(ln(pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1], color, false, 2));
  return out;
};
const water = (x0: number, y0: number, x1: number, y1: number): DiagramElement => pg([[x0, y0], [x1, y0], [x1, y1], [x0, y1]], C.blue, FILL.blue);
const walls = (x0: number, x1: number, ytop: number, ybot: number): DiagramElement[] => [
  ln(x0, ytop, x0, ybot, C.gray, false, 2), ln(x0, ybot, x1, ybot, C.gray, false, 2), ln(x1, ybot, x1, ytop, C.gray, false, 2),
];
const tri = (x: number, y: number): DiagramElement => pg([[x, y], [x - 10, y + 18], [x + 10, y + 18]], C.gray, FILL.gray);

