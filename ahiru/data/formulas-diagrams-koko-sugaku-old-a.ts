// キーは項目の label（買い切りの識別キーと同じ）。「なぜそうなるの？」を根っこまでたどる形で、10枚以上で書く。
// 画面の上半分に図、下の帯（band）に、そのスライドの式やひとこと、という配置にそろえてある。
// 数値・式は本文（formula・example・quiz）と同じものを使い、すべて手で検算してある。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, stack, band, fresh } from './diagram-kit';

const FL: Record<string, string> = {
  [C.blue]: FILL.blue,
  [C.green]: FILL.green,
  [C.red]: FILL.red,
  [C.purple]: FILL.purple,
  [C.gray]: FILL.gray,
  [C.ink]: FILL.warm,
  [C.main]: FILL.warm,
};
/** 文字入りの色つき箱。 */
const k = (y: number, text: string, col: string = C.blue, size = 14, x = 20, w = 280, h = 30): DiagramElement =>
  bx(x, y, w, h, text, col, FL[col] ?? FILL.gray, size);
/** 図の上半分に4行まで積む（i = 0..3）。 */
const L = (i: number, text: string, col: string = C.blue, size = 13): DiagramElement => k(8 + i * 32, text, col, size, 20, 280, 26);
/** 下の帯（2行）。 */
const bd = (a: string, b?: string, ca: string = C.blue, cb: string = C.green): DiagramElement[] =>
  band(140, k(148, a, ca, 13), ...(b ? [k(188, b, cb, 13)] : []));
const T = (y: number, text: string, col: string = C.ink, size = 13): DiagramElement => lb(160, y, text, size, col, 'middle', true);
const fm = (v: number) => (v < 0 ? '−' + -v : String(v));
/** 数直線。y は線の高さ、lo〜hi は左端と右端の値。 */
const NL = (y: number, lo: number, hi: number) => {
  const x0 = 20;
  const x1 = 300;
  const px = (v: number) => x0 + ((v - lo) * (x1 - x0)) / (hi - lo);
  const base = (marks: number[]): DiagramElement[] => [
    ln(x0, y, x1, y, C.gray, false, 2),
    ...marks.flatMap((v) => [ln(px(v), y - 4, px(v), y + 4, C.gray), lb(px(v), y + 17, fm(v), 10, v === 0 ? C.ink : C.gray, 'middle', v === 0)]),
  ];
  return { px, base };
};
const range = (a: number, b: number) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const dotF = (x: number, y: number, col: string = C.blue) => ci(x, y, 5, undefined, col, col);
const dotO = (x: number, y: number, col: string = C.blue) => ci(x, y, 5, undefined, col, '#FFFFFF');
/** 2×2 の表（かけ算の表）。 */
const tbl = (c1: string, c2: string, r1: string, r2: string, cells: [string, string, string, string], cols: [string, string, string, string]): DiagramElement[] => [
  bx(120, 12, 80, 28, c1, C.gray, FILL.gray, 14),
  bx(200, 12, 80, 28, c2, C.gray, FILL.gray, 14),
  bx(40, 42, 80, 30, r1, C.gray, FILL.gray, 14),
  bx(40, 74, 80, 30, r2, C.gray, FILL.gray, 14),
  bx(120, 42, 80, 30, cells[0], cols[0], FL[cols[0]], 15),
  bx(200, 42, 80, 30, cells[1], cols[1], FL[cols[1]], 15),
  bx(120, 74, 80, 30, cells[2], cols[2], FL[cols[2]], 15),
  bx(200, 74, 80, 30, cells[3], cols[3], FL[cols[3]], 15),
];

