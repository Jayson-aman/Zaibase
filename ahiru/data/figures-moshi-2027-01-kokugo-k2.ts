// 月例模試 2027年1月号 国語（高校受験 k26〜k50）の動く図解。
// 解答・解説の流れ（状況→手がかり→理由→消去→答え→確かめ）に沿って、7枚で動く。
// 座標は 320×240。1枚ごとに画面をぬりつぶして（fresh）、上に箱の列、下に帯でひとことを出す。
import type { DiagramElement, Figure } from './figures';
import { C, FILL, bx, lb, ar, show, fresh, type Slide } from './diagram-kit';

type K = 'b' | 'g' | 'r' | 'p' | 'y' | 'k';
const P: Record<K, [string, string]> = {
  b: [C.blue, FILL.blue],
  g: [C.green, FILL.green],
  r: [C.red, FILL.red],
  p: [C.purple, FILL.purple],
  y: [C.main, FILL.yellow],
  k: [C.gray, FILL.gray],
};
/** [箱の文字, 色, 上の箱から来る矢印のそばの文字（chain のときだけ）] */
type R = [string, K?, string?];

/**
 * 1枚のスライド。rows は上から並べる箱（4つまで）。chain=true なら矢印でつなぐ。
 * big は下の帯（太字の結論）、small はその下の小さなひとこと。
 */
function sl(note: string, title: string, rows: R[], big?: string, small?: string | boolean, chain = false): Slide {
  if (typeof small === 'boolean') {
    chain = small;
    small = undefined;
  }
  const h = chain ? 22 : 26;
  const gap = chain ? 14 : 5;
  const els: DiagramElement[] = [lb(160, 18, title, 12, C.ink, 'middle', true)];
  rows.forEach(([t, k, a], i) => {
    const y = 30 + i * (h + gap);
    const [col, fill] = P[k ?? 'k'];
    if (chain && i > 0) {
      els.push(ar(160, y - gap + 1, 160, y - 1, C.gray));
      if (a) els.push(lb(170, y - gap / 2, a, 10, C.red, 'start', true));
    }
    els.push(bx(10, y, 300, h, t, col, fill, 12));
  });
  const by = chain ? 166 : 158;
  if (big) els.push(bx(20, by, 280, 28, big, C.green, FILL.green, 13));
  if (small) els.push(lb(160, by + 46, small, 11, C.gray, 'middle'));
  return { note, add: fresh(...els) };
}

