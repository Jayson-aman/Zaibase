import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

const E = (...a: DiagramElement[][]): DiagramElement[] => a.flat();
/** びん（外わく） */
const jar = (x: number, y: number, w: number, h: number): DiagramElement => bx(x, y, w, h, undefined, C.gray, '#FFFFFF');
/** ろうそく（lit＝火がついている） */
const candle = (cx: number, base: number, h: number, lit: boolean): DiagramElement[] => [
  bx(cx - 5, base - h, 10, h, undefined, C.main, FILL.warm),
  ...(lit ? [ci(cx, base - h - 7, 5, undefined, C.red, FILL.yellow)] : []),
];
/** 100こ並べた点の一部（空気の組成） */
const grid = (from: number, to: number, color: string, fill: string): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let i = from; i < to; i++) out.push(ci(24 + (i % 10) * 13, 30 + Math.floor(i / 10) * 13, 5, undefined, color, fill));
  return out;
};
/** 点を格子状にちらす */
const spread = (x0: number, y0: number, cols: number, rows: number, gx: number, gy: number, r: number, color: string, fill: string): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let j = 0; j < rows; j++) for (let i = 0; i < cols; i++) out.push(ci(x0 + i * gx, y0 + j * gy, r, undefined, color, fill));
  return out;
};

