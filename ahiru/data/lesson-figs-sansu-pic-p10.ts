// 場合の数（順列・組み合わせ・塗り分け・最短経路）の図を、棒グラフや座標から「場面の絵」に直す。
import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

type Lat = { x0: number; yb: number; cx: number; cy: number };
const P = (L: Lat, i: number, j: number): [number, number] => [L.x0 + i * L.cx, L.yb - j * L.cy];
type Edge = [number, number, number, number];

/** 道の格子（右・上に進む）。blocked に通行止めの辺を入れると、その辺は描かない。 */
function lat(L: Lat, nx: number, ny: number, blocked: Edge[] = []): DiagramElement[] {
  const out: DiagramElement[] = [];
  const isB = (a: number, b: number, c: number, d: number) =>
    blocked.some(([p, q, r, s]) => (p === a && q === b && r === c && s === d) || (p === c && q === d && r === a && s === b));
  for (let j = 0; j <= ny; j++) for (let i = 0; i < nx; i++) if (!isB(i, j, i + 1, j)) {
    const [x1, y1] = P(L, i, j); const [x2, y2] = P(L, i + 1, j); out.push(ln(x1, y1, x2, y2, C.gray, false, 1.5));
  }
  for (let i = 0; i <= nx; i++) for (let j = 0; j < ny; j++) if (!isB(i, j, i, j + 1)) {
    const [x1, y1] = P(L, i, j); const [x2, y2] = P(L, i, j + 1); out.push(ln(x1, y1, x2, y2, C.gray, false, 1.5));
  }
  return out;
}
/** 点をつないだ道すじ（太い線）。 */
function route(L: Lat, pts: [number, number][], color: string, w = 3): DiagramElement[] {
  return pts.slice(1).map((p, k) => { const [x1, y1] = P(L, pts[k][0], pts[k][1]); const [x2, y2] = P(L, p[0], p[1]); return ln(x1, y1, x2, y2, color, false, w); });
}
/** 交差点に数を書いた円。 */
const num = (L: Lat, i: number, j: number, text: string, color: string, fill: string, r = 12, size = 11): DiagramElement => {
  const [x, y] = P(L, i, j); return ci(x, y, r, text, color, fill, size);
};
/** 長方形のふち（4本の太線）。 */
function rectLines(L: Lat, i0: number, j0: number, i1: number, j1: number, color: string, w = 4): DiagramElement[] {
  return route(L, [[i0, j0], [i1, j0], [i1, j1], [i0, j1], [i0, j0]], color, w);
}
/** 横一列の人（円）。 */
const people = (texts: string[], x0: number, step: number, y: number, r: number, color: string, fill: string, size = 12): DiagramElement[] =>
  texts.map((t, i) => ci(x0 + i * step, y, r, t, color, fill, size));

// 正六角形
const HEX = (() => {
  const cx = 100, cy = 128, r = 80;
  const v: [number, number][] = [0, 1, 2, 3, 4, 5].map((k) => [Math.round((cx + r * Math.cos((k * Math.PI) / 3)) * 10) / 10, Math.round((cy - r * Math.sin((k * Math.PI) / 3)) * 10) / 10]);
  const m: [number, number][] = v.map((p, k) => { const q = v[(k + 1) % 6]; return [Math.round(((p[0] + q[0]) / 2) * 10) / 10, Math.round(((p[1] + q[1]) / 2) * 10) / 10]; });
  return { v, m };
})();

