/** 多角形でかいた円（文字の重なり検査にかからない円）。 */
const circ = (cx: number, cy: number, r: number, color: string = C.ink, fill?: string): E =>
  pg(Array.from({ length: 48 }, (_, i) => [cx + r * Math.cos((2 * Math.PI * i) / 48), cy + r * Math.sin((2 * Math.PI * i) / 48)] as [number, number]), color, fill);
const rect = (x: number, y: number, w: number, h: number, color: string = C.ink, fill?: string): E => pg([[x, y], [x + w, y], [x + w, y + h], [x, y + h]], color, fill);
const poly = (pts: [number, number][], color: string = C.ink, fill?: string): E[] =>
  (fill ? [pg(pts, color, fill)] : []).concat(pts.map((p, i) => ln(p[0], p[1], pts[(i + 1) % pts.length][0], pts[(i + 1) % pts.length][1], color, false, 2.5)));

// 文字カードを縦にならべる（国語・社会）。rows は [文字, 色?]。
type K = 'b' | 'g' | 'r' | 'p' | 'y' | 'k';
const PAL: Record<K, [string, string]> = { b: [C.blue, FILL.blue], g: [C.green, FILL.green], r: [C.red, FILL.red], p: [C.purple, FILL.purple], y: [C.main, FILL.yellow], k: [C.gray, FILL.gray] };
type R = [string, K?];
const cards = (rows: R[], title?: string, chain = false): E[] => {
  const n = rows.length;
  const h = n >= 4 ? 24 : n === 3 ? 30 : 34;
  const gap = chain ? 12 : n >= 4 ? 6 : 10;
  const y0 = title ? 22 : 12;
  const out: E[] = [];
  if (title) out.push(tx(160, 13, title, 11, C.gray));
  rows.forEach(([t, k], i) => {
    const y = y0 + i * (h + gap);
    const [col, fill] = PAL[k ?? 'k'];
    if (chain && i > 0) out.push(ar(160, y - gap + 1, 160, y - 1, C.gray));
    out.push(bx(10, y, 300, h, t, col, fill, 12));
  });
  return out;
};
const CS = (note: string, lines: string[], rows: R[], title?: string, chain = false): Slide => SF(note, lines, cards(rows, title, chain));

/** 横一列のならんだ箱（算数・理科の式のつながり）。 */
const row = (items: { t: string; k?: K; w?: number }[], y: number, h = 30, size = 12, gap = 8): E[] => {
  const total = items.reduce((a, it) => a + (it.w ?? 0), 0);
  const free = 300 - gap * (items.length - 1) - total;
  const nAuto = items.filter((it) => it.w === undefined).length;
  const auto = nAuto ? free / nAuto : 0;
  let x = 10;
  return items.map((it) => {
    const w = it.w ?? auto;
    const [col, fill] = PAL[it.k ?? 'b'];
    const e = bx(x, y, w, h, it.t, col, fill, size);
    x += w + gap;
    return e;
  });
};

const id = (s: string, n: number): string => `honshiken_school_fukuoka_kurume_${s}_${String(n).padStart(2, '0')}`;
const arc = (cx: number, cy: number, r: number, a0: number, a1: number, color: string, w = 3): E[] => {
  const out: E[] = [];
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / 12));
  for (let i = 0; i < n; i++) {
    const p = (a0 + ((a1 - a0) * i) / n) * (Math.PI / 180);
    const q = (a0 + ((a1 - a0) * (i + 1)) / n) * (Math.PI / 180);
    out.push(ln(cx + r * Math.cos(p), cy - r * Math.sin(p), cx + r * Math.cos(q), cy - r * Math.sin(q), color, false, w));
  }
  return out;
};

