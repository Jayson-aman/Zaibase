// 「なぜ？」の連鎖で、7枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, fresh, flow, stack } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=162 から）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 162, 292, 12 + 15 * n, t, c[0], c[1], size);
};

// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});

// 「なぜ？」の問い → 答え、の1組
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13, ah = 74): DiagramElement[] => [
  bx(12, 8, 296, 34, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 44, 160, 58, PURPLE[0]),
  bx(12, 60, 296, ah, a, c[0], c[1], aSize),
];

// 箱を矢印でつないだ横一列
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap: 14 }).flat();

// 縦に並べた箱
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 26, gap = 12): DiagramElement[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();

// 左右くらべ（見出し＋本文）
const cmp = (lh: string, lt: string, rh: string, rt: string, lc: Col = RED, rc: Col = GREEN, size = 11, bh = 100, y = 8): DiagramElement[] => [
  bx(10, y, 148, 28, lh, lc[0], lc[1], 12),
  bx(162, y, 148, 28, rh, rc[0], rc[1], 12),
  bx(10, y + 32, 148, bh, lt, lc[0], lc[1], size),
  bx(162, y + 32, 148, bh, rt, rc[0], rc[1], size),
];

// 棒グラフ（ラベルなしでもよい）
const bars = (x0: number, y0: number, w: number, h: number, vals: number[], max: number, opts?: { labels?: string[]; hi?: number[]; color?: string }): DiagramElement[] => {
  const n = vals.length;
  const cw = w / n;
  const bw = cw * 0.62;
  const out: DiagramElement[] = [ln(x0, y0 + h, x0 + w, y0 + h, C.gray)];
  vals.forEach((v, i) => {
    const bh = Math.max(2, (v / max) * h);
    const hi = opts?.hi?.includes(i);
    out.push(bx(x0 + i * cw + (cw - bw) / 2, y0 + h - bh, bw, bh, undefined, hi ? C.red : opts?.color ?? C.blue, hi ? FILL.red : FILL.blue));
    if (opts?.labels?.[i]) out.push(lb(x0 + i * cw + cw / 2, y0 + h + 10, opts.labels[i], 9, C.ink));
  });
  return out;
};

