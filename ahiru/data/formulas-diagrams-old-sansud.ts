// 立体（立方体）を斜めから見た絵
const cube = (x: number, y: number, s: number, color: string = C.main, fill: string = FILL.warm): DiagramElement[] => {
  const d = s * 0.4;
  return [
    pg([[x, y + d], [x + s, y + d], [x + s, y + d + s], [x, y + d + s]], color, fill),
    pg([[x, y + d], [x + d, y], [x + s + d, y], [x + s, y + d]], color, FILL.yellow),
    pg([[x + s, y + d], [x + s + d, y], [x + s + d, y + s], [x + s, y + d + s]], color, FILL.gray),
  ];
};
// n×n のます目
const grid = (x: number, y: number, n: number, s: number, color: string = C.main, fill: string = FILL.warm): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) out.push(bx(x + j * s, y + i * s, s, s, undefined, color, fill));
  return out;
};

