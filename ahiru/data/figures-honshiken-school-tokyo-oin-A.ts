const spiral = (n: number): Map<string, number> => {
  const m = new Map<string, number>();
  let x = 0, y = 0, v = 1, step = 1, d = 0;
  const dirs = [[1, 0], [0, 1], [-1, 0], [0, -1]];
  m.set('0,0', 1);
  const max = n * n;
  outer: while (true) {
    for (let r = 0; r < 2; r++) {
      for (let s = 0; s < step; s++) {
        x += dirs[d % 4][0]; y += dirs[d % 4][1]; v++;
        if (v > max) break outer;
        m.set(`${x},${y}`, v);
      }
      d++;
    }
    step++;
  }
  return m;
};
const sgrid = (n: number, x0: number, y0: number, cs: number): E[] => {
  const m = spiral(n); const h = (n - 1) / 2; const out: E[] = [];
  for (let j = -h; j <= h; j++) for (let i = -h; i <= h; i++) {
    const v = m.get(`${i},${j}`);
    if (v === undefined) continue;
    out.push(bx(x0 + (i + h) * cs, y0 + (h - j) * cs, cs, cs, String(v), C.blue, FILL.blue, 10));
  }
  return out;
};
const cellOf = (n: number, v: number, x0: number, y0: number, cs: number): E[] => {
  const m = spiral(n); const h = (n - 1) / 2;
  for (const [k, val] of m) if (val === v) { const [i, j] = k.split(',').map(Number); return rect(x0 + (i + h) * cs, y0 + (h - j) * cs, cs, cs, C.red, 3); }
  return [];
};
