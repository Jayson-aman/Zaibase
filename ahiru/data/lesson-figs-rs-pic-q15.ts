import type { Figure } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

/** 下の説明の1行（中央ぞろえ）。 */
const row = (y: number, text: string, color: string = C.ink, size = 13) => lb(160, y, text, size, color, 'middle', true);

/** 10円玉に見立てた円を、5個ずつ並べる。 */
function coins(n: number, x0: number, y0: number, color: string, fill: string) {
  const out = [];
  for (let i = 0; i < n; i++) out.push(ci(x0 + (i % 5) * 18, y0 + Math.floor(i / 5) * 18, 7, undefined, color, fill));
  return out;
}

/** 横向きの棒（人口の絵）。 */
function popBar(y: number, name: string, man: number, color: string, fill: string) {
  const w = Math.max(4, Math.round(man * 0.12));
  return [
    lb(8, y + 12, name, 12, C.ink, 'start', true),
    bx(56, y, w, 16, undefined, color, fill),
    lb(56 + w + 5, y + 12, `約${man}万人`, 11, color, 'start', true),
  ];
}

