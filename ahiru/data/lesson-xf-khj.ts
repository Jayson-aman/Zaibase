// 「なぜ？」の連鎖で、7枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, fresh, flow, stack } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
type El = DiagramElement;

const cap = (t: string, c: Col = BLUE, size = 12): El => {
  const n = t.split('\n').length;
  return bx(10, 164, 300, 14 + 15 * n, t, c[0], c[1], size);
};
// まっさらな図＋下の帯
const S = (note: string, top: El[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});
// 「なぜ？」の問い → 答え
const Q = (note: string, q: string, a: string, capText: string, c: Col = BLUE, aSize = 12) =>
  S(note, [
    bx(10, 6, 300, 34, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
    ar(160, 41, 160, 52, PURPLE[0]),
    bx(10, 54, 300, 98, a, c[0], c[1], aSize),
  ], capText, c);
// 横一列の箱（矢印つき）
const row = (labels: string[], y: number, c: Col = MAIN, size = 11, h = 50, gap = 14): El[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap }).flat();
// 縦に並べた箱（矢印つき）
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 11, h = 26, gap = 10): El[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();
// 年表（左に年、右に出来事）
const tl = (rows: [string, string][], y0 = 8, c: Col = MAIN, h = 24, gap = 4, size = 11): El[] =>
  rows.flatMap(([y, t], i) => [
    bx(10, y0 + i * (h + gap), 66, h, y, BLUE[0], BLUE[1], size),
    bx(80, y0 + i * (h + gap), 230, h, t, c[0], c[1], size),
  ]);
// 表（先頭行は見出し）
const tab = (rows: string[][], colW: number[], y0 = 8, h = 26, size = 11, hl: [number, number][] = []): El[] => {
  const tw = colW.reduce((a, b) => a + b, 0);
  const sx = (320 - tw) / 2;
  const out: El[] = [];
  rows.forEach((r, i) => {
    let x = sx;
    r.forEach((t, j) => {
      const on = hl.some(([a, b]) => a === i && b === j);
      const c: Col = i === 0 ? BLUE : on ? RED : MAIN;
      out.push(bx(x, y0 + i * h, colW[j], h, t, c[0], i === 0 ? FILL.blue : on ? FILL.red : FILL.warm, size));
      x += colW[j];
    });
  });
  return out;
};
// 左右ふたつの箱（見出し＋本文）
const two = (lt: string, lbody: string, rt: string, rbody: string, lc: Col = BLUE, rc: Col = GREEN, y = 6, h = 148, size = 12): El[] => [
  bx(10, y, 146, 24, lt, lc[0], lc[1], 12),
  bx(10, y + 28, 146, h - 28, lbody, lc[0], FILL.warm, size),
  bx(164, y, 146, 24, rt, rc[0], rc[1], 12),
  bx(164, y + 28, 146, h - 28, rbody, rc[0], FILL.warm, size),
];

// 問い＋横一列の流れ
