const half = (cx: number, by: number, rx: number, ry: number): [number, number][] => {
  const pts: [number, number][] = [];
  for (let a = 180; a >= 0; a -= 15) pts.push([cx + rx * Math.cos((a * Math.PI) / 180), by - ry * Math.sin((a * Math.PI) / 180)]);
  return pts;
};

