type Pt = [number, number];
const cap = (t: string, color: string = C.ink, size = 12) => band(150, lb(160, 190, t, size, color, 'middle', true));
const mv = (pts: Pt[], dx: number, dy: number): Pt[] => pts.map(([x, y]) => [x + dx, y + dy] as Pt);

/** なみ打つ地層（しゅう曲）。 */
const wave = (y: number, t: number, amp: number, color: string, fill: string, x0 = 30, x1 = 290, cycles = 2): DiagramElement => {
  const n = 40;
  const top: Pt[] = [];
  const bot: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const x = x0 + ((x1 - x0) * i) / n;
    const dy = amp * Math.sin((2 * Math.PI * cycles * i) / n);
    top.push([Math.round(x), Math.round(y + dy)]);
    bot.push([Math.round(x), Math.round(y + t + dy)]);
  }
  return pg([...top, ...bot.reverse()], color, fill);
};

/** 角ばった石（多角形）。 */
const rock = (cx: number, cy: number, r: number, color: string = C.gray, fill: string = FILL.gray): DiagramElement => {
  const k = [1, 0.7, 0.95, 0.75, 1, 0.72];
  const pts = k.map((m, i) => {
    const a = (i * Math.PI) / 3 + 0.3;
    return [Math.round(cx + r * m * Math.cos(a)), Math.round(cy + r * m * Math.sin(a))] as Pt;
  });
  return pg(pts, color, fill);
};

/** 火山（三角形）。 */
const volc = (x: number, baseY: number, w = 30, h = 20, color: string = C.red, fill: string = FILL.red): DiagramElement =>
  pg([[x - w / 2, baseY], [x, baseY - h], [x + w / 2, baseY]], color, fill);

