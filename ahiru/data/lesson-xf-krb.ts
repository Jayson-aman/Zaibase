// 棒磁石（左の極を指定）。N極は赤、S極は青。
const NC: Col = [C.red, FILL.red];
const SC: Col = [C.blue, FILL.blue];
const mag = (x: number, y: number, w: number, h: number, left: 'N' | 'S', size = 13): DiagramElement[] => {
  const right = left === 'N' ? 'S' : 'N';
  return [bx(x, y, w / 2, h, left, left === 'N' ? NC[0] : SC[0], left === 'N' ? NC[1] : SC[1], size), bx(x + w / 2, y, w / 2, h, right, right === 'N' ? NC[0] : SC[0], right === 'N' ? NC[1] : SC[1], size)];
};
// 紙面に垂直な向きの記号。dotc＝手前向き（丸に点）、crossc＝奥向き（丸にバツ）
const dotc = (x: number, y: number, r = 9, c: string = C.ink): DiagramElement[] => [ci(x, y, r, undefined, c, '#FFFFFF'), ci(x, y, 2.4, undefined, c, c)];
const crossc = (x: number, y: number, r = 9, c: string = C.ink): DiagramElement[] => {
  const d = r * 0.7;
  return [ci(x, y, r, undefined, c, '#FFFFFF'), ln(x - d, y - d, x + d, y + d, c, false, 1.8), ln(x - d, y + d, x + d, y - d, c, false, 1.8)];
};

