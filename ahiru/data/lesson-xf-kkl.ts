// 高校受験 国語（中2・中3 教科書単元 24 件）の「動く図解スライド」。
// 「なぜ？」の連鎖で、7枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, fresh } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=160 から）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 160, 292, 16 + 15 * n, t, c[0], c[1], size);
};

// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});

// 「なぜ？」の問い → 答え、の1組
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13): DiagramElement[] => [
  bx(12, 8, 296, 40, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 50, 160, 66, PURPLE[0]),
  bx(12, 68, 296, 74, a, c[0], c[1], aSize),
];

// 箱
const B = (t: string, x: number, y: number, w: number, h: number, c: Col = MAIN, size = 12): DiagramElement =>
  bx(x, y, w, h, t, c[0], c[1], size);
// 文字
const T = (t: string, x: number, y: number, size = 12, color: string = C.ink, bold = false, anchor: 'start' | 'middle' | 'end' = 'middle'): DiagramElement =>
  lb(x, y, t, size, color, anchor, bold);
// 矢印
const A = (x1: number, y1: number, x2: number, y2: number, c: string = C.main, dashed = false): DiagramElement => ar(x1, y1, x2, y2, c, dashed);

// 矢印でつないだ横一列
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44, gap = 14, pad = 8): DiagramElement[] => {
  const n = labels.length;
  const w = (320 - pad * 2 - gap * (n - 1)) / n;
  const out: DiagramElement[] = [];
  labels.forEach((t, i) => {
    const x = pad + i * (w + gap);
    if (i > 0) out.push(ar(x - gap + 1, y + h / 2, x - 1, y + h / 2, c[0]));
    out.push(bx(x, y, w, h, t, c[0], c[1], size));
  });
  return out;
};

// 色を１つずつ指定できる横一列（矢印なし）
const chunks = (items: [string, Col][], y: number, h = 40, size = 12, gap = 4, pad = 8): DiagramElement[] => {
  const n = items.length;
  const w = (320 - pad * 2 - gap * (n - 1)) / n;
  return items.map(([t, c], i) => bx(pad + i * (w + gap), y, w, h, t, c[0], c[1], size));
};

// 表（先頭行が見出し）
const tab = (rows: string[][], x: number, y: number, ws: number[], h: number, size = 12, hc: Col = MAIN, bc: Col = GRAY, fc?: Col): DiagramElement[] => {
  const out: DiagramElement[] = [];
  rows.forEach((r, i) => {
    let cx = x;
    r.forEach((t, j) => {
      const c = i === 0 ? hc : j === 0 && fc ? fc : bc;
      out.push(bx(cx, y + i * h, ws[j], h, t, c[0], c[1], size));
      cx += ws[j];
    });
  });
  return out;
};

