// 解説を「何を聞かれているか → なぜ → ステップ → 答え → 確かめ → まちがい」の型でそろえて組み立てる。
const E = (ask: string, why: string, steps: string[], ans: string, check: string, miss: string): string =>
  [
    '【何を聞かれているか】' + ask,
    '【なぜその考え方なのか】' + why,
    ...steps.map((s, i) => '【ステップ' + (i + 1) + '】' + s),
    '【答え】' + ans,
    '【確かめ】' + check,
    '【よくあるまちがい】' + miss,
  ].join('\n');

