type Subj = 'sansu' | 'kokugo' | 'rika' | 'shakai' | 'eigo';
type Diff = 'basic' | 'standard' | 'advanced';
type Spec = {
  id: string; subj: Subj; diff: Diff; q: string; passage?: string; choices?: string[];
  answer: string; hint: string; ask: string; why: string; steps: string[];
  check: string; mistake: string; pitfall: string; tip: string;
};
type Extra = { choices?: string[]; passage?: string };

function P(
  id: string, diff: Diff, q: string, answer: string | number, hint: string, ask: string, why: string,
  steps: string[], check: string, mistake: string, pitfall: string, tip: string, extra?: Extra,
): Spec {
  const subj = id.split('_')[1] as Subj;
  const ans = typeof answer === 'number' && extra?.choices ? extra.choices[answer] : String(answer);
  return { id, subj, diff, q, answer: ans, hint, ask, why, steps, check, mistake, pitfall, tip, choices: extra?.choices, passage: extra?.passage };
}

function mk(s: Spec): Question {
  const steps = s.steps.map((t, i) => '【ステップ' + (i + 1) + '】' + t).join('\n');
  const explanation =
    '【何を聞かれているか】' + s.ask + '\n' +
    '【なぜそうなるのか】' + s.why + '\n' +
    steps + '\n' +
    '【答え】' + s.answer + '\n' +
    '【たしかめ】' + s.check + '\n' +
    '【よくあるまちがい】' + s.mistake;
  const q: Question = {
    id: s.id, subject: s.subj, difficulty: s.diff, course: 'koko-kansai-daiichi', examType: 'koko',
    question: s.q, answer: s.answer, hint: s.hint, explanation, pitfall: s.pitfall, memoryTip: s.tip,
  };
  if (s.choices) q.choices = s.choices;
  if (s.passage) q.passage = s.passage;
  return q;
}

