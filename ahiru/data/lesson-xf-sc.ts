const polyTris = (pts: [number, number][]): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let i = 1; i < pts.length - 1; i++) out.push(pg([pts[0], pts[i], pts[i + 1]], C.main, TRI_FILLS[(i - 1) % TRI_FILLS.length]));
  for (let i = 2; i < pts.length - 1; i++) out.push(ln(pts[0][0], pts[0][1], pts[i][0], pts[i][1], C.gray, true));
  return out;
};
