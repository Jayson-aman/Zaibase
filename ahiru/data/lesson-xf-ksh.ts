// 放物線 y = a x^2 を折れ線で
const para = (a: number, x0: number, x1: number, ox: number, oy: number, sx: number, sy: number, color: string = C.blue): DiagramElement[] => {
  const out: DiagramElement[] = [];
  const st = 0.25;
  for (let x = x0; x < x1 - 1e-9; x += st) {
    const xa = x, xb = Math.min(x + st, x1);
    out.push(ln(ox + xa * sx, oy - a * xa * xa * sy, ox + xb * sx, oy - a * xb * xb * sy, color, false, 2));
  }
  return out;
};

