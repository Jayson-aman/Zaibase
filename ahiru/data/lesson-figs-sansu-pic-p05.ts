import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, C, FILL } from './diagram-kit';

type Kind = readonly [string, string];
const KB: Kind = [C.blue, FILL.blue];
const KG: Kind = [C.green, FILL.green];
const KR: Kind = [C.red, FILL.red];
const KO: Kind = [C.main, FILL.yellow];
const KN: Kind = [C.gray, FILL.gray];

/** 色つきの箱（線分図の1本・1こぶん）。 */
const u = (x: number, y: number, w: number, h: number, t: string | undefined, k: Kind, size = 12): DiagramElement => bx(x, y, w, h, t, k[0], k[1], size);
/** 同じ幅の箱を n 個ならべる（1こぶんずつ）。 */
const nx = (n: number, x: number, y: number, w: number, h: number, k: Kind, t?: string, size = 11): DiagramElement[] =>
  Array.from({ length: n }, (_, i) => u(x + w * i, y, w, h, t, k, size));

