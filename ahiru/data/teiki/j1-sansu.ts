// 立体の絵（3Dふうの多角形）
const ellPts = (cx: number, cy: number, rx: number, ry: number, n = 28): [number, number][] =>
  Array.from({ length: n }, (_, i) => [cx + rx * Math.cos((2 * Math.PI * i) / n), cy + ry * Math.sin((2 * Math.PI * i) / n)] as [number, number]);
/** 左→右へ、下側のふち（手前）の半楕円 */
const lowerArc = (cx: number, cy: number, rx: number, ry: number, n = 14): [number, number][] =>
  Array.from({ length: n + 1 }, (_, i) => [cx - rx * Math.cos((Math.PI * i) / n), cy + ry * Math.sin((Math.PI * i) / n)] as [number, number]);
/** 右→左へ、上側のふち（奥）の半楕円 */
const upperArc = (cx: number, cy: number, rx: number, ry: number, n = 14): [number, number][] =>
  Array.from({ length: n + 1 }, (_, i) => [cx + rx * Math.cos((Math.PI * i) / n), cy - ry * Math.sin((Math.PI * i) / n)] as [number, number]);
const box3d = (x: number, y: number, w: number, h: number, d: number, color: string = C.blue, fill: string = FILL.blue): DiagramElement[] => [
  pg([[x, y], [x + w, y], [x + w, y + h], [x, y + h]], color, fill),
  pg([[x, y], [x + d, y - d], [x + w + d, y - d], [x + w, y]], color, FILL.gray),
  pg([[x + w, y], [x + w + d, y - d], [x + w + d, y + h - d], [x + w, y + h]], color, FILL.yellow),
];
const cyl3d = (cx: number, top: number, rx: number, ry: number, h: number, color: string = C.blue, fill: string = FILL.blue): DiagramElement[] => [
  pg([...lowerArc(cx, top + h, rx, ry), ...upperArc(cx, top, rx, ry)], color, fill),
  pg(ellPts(cx, top, rx, ry), color, FILL.gray),
];
const cone3d = (cx: number, apex: number, base: number, rx: number, ry: number, color: string = C.blue, fill: string = FILL.blue): DiagramElement[] => [
  pg([[cx, apex], ...lowerArc(cx, base, rx, ry)], color, fill),
];
const pyr3d = (x: number, y: number, w: number, h: number, d: number, color: string = C.blue, fill: string = FILL.blue): DiagramElement[] => {
  const px = x + (w + d) / 2;
  const py = y - d / 2 - h;
  return [
    pg([[x, y], [x + w, y], [x + w + d, y - d], [x + d, y - d]], color, FILL.gray),
    pg([[px, py], [x, y], [x + w, y]], color, fill),
    pg([[px, py], [x + w, y], [x + w + d, y - d]], color, FILL.yellow),
  ];
};
const sphere = (cx: number, cy: number, r: number): DiagramElement[] => [
  disc(cx, cy, r, C.blue, FILL.blue),
  ...lowerArc(cx, cy, r, r * 0.3).slice(1).map((p, i, a) => ln(i === 0 ? cx - r : a[i - 1][0], i === 0 ? cy : a[i - 1][1], p[0], p[1], C.blue, false, 1)),
  ...upperArc(cx, cy, r, r * 0.3).slice(1).map((p, i, a) => ln(i === 0 ? cx + r : a[i - 1][0], i === 0 ? cy : a[i - 1][1], p[0], p[1], C.blue, true, 1)),
];

