const disc = (cx: number, cy: number, r: number, color: string = C.gray, fill: string = FILL.gray): DiagramElement =>
  sc(cx, cy, r, 0, 359.9, color, fill);
const pt = (cx: number, cy: number, r: number, deg: number): [number, number] => [cx + r * Math.cos((deg * Math.PI) / 180), cy - r * Math.sin((deg * Math.PI) / 180)];
const radius = (cx: number, cy: number, r: number, deg: number, color: string = C.ink): DiagramElement => {
  const [x, y] = pt(cx, cy, r, deg);
  return ln(cx, cy, x, y, color, false, 1.5);
};
