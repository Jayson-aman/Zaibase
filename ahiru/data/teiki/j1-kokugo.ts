const cap = (t: string, color: string = C.ink) => band(150, lb(160, 188, t, 12, color, 'middle', true));
/** 1枚のスライド：note・下の帯の一言・部品 */
const S = (note: string, c: string, color: string, ...els: DiagramElement[]) => ({ note, add: fresh(...els, ...cap(c, color)) });
/** 言葉を横一列の箱にする。gx は箱と箱のすき間の x 座標 */
const row = (ws: string[], y: number, color: string, fill: string, size = 14, h = 34, gap = 10) => {
  const w = ws.map((t) => [...t].length * size + 14);
  const total = w.reduce((a, b) => a + b, 0) + gap * (ws.length - 1);
  let x = (320 - total) / 2;
  const els: DiagramElement[] = [];
  const gx: number[] = [];
  ws.forEach((t, i) => {
    els.push(bx(x, y, w[i], h, t, color, fill, size));
    x += w[i];
    if (i < ws.length - 1) gx.push(x + gap / 2);
    x += gap;
  });
  return { els, gx };
};

