/** 下の帯：y0 から下を白でぬり、ひとこと（箱）と、あれば小さな補足を置く。 */
const say = (y0: number, t1: string, color: string = C.ink, fill: string = FILL.gray, t2?: string): DiagramElement[] =>
  band(y0, bx(10, y0 + 6, 300, 30, t1, color, fill, 13), ...(t2 ? [lb(160, y0 + 56, t2, 11, C.gray, 'middle')] : []));

const rect = (x: number, y: number, w: number, h: number, color: string): DiagramElement[] => [
  ln(x, y, x + w, y, color, true, 2), ln(x + w, y, x + w, y + h, color, true, 2), ln(x + w, y + h, x, y + h, color, true, 2), ln(x, y + h, x, y, color, true, 2),
];

const grid = (rows: number, cols: number, x0: number, y0: number, cs: number, color: string, fill: string): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let i = 0; i < rows; i++) for (let j = 0; j < cols; j++) out.push(bx(x0 + j * cs, y0 + i * cs, cs, cs, undefined, color, fill));
  return out;
};

