// 各図は 8 枚。「なぜ？→答え→では、なぜ？→答え…→確かめ」の連鎖で、結論だけを出して終わりにしない。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, ar, ln, ci, show, fresh, stack, flow } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];


// 文字だけの注記。lb だと、あとのスライドの白い下地（fresh）に重なると検査に引っかかるので、白い箱に入れた文字にする。
const tx = (x: number, y: number, text: string, size = 12, _color?: string, anchor: 'start' | 'middle' | 'end' = 'middle', _bold?: boolean): DiagramElement => {
  const lines = text.split('\n');
  const w = Math.max(...lines.map((l) => [...l].reduce((a, c) => a + (/[\x20-\x7e]/.test(c) ? 0.62 : 1) * size, 0))) + 14;
  const h = lines.length * size * 1.2 + 4;
  const x0 = anchor === 'start' ? x : anchor === 'end' ? x - w : x - w / 2;
  return bx(x0, y - size * 0.35 - h / 2, w, h, text, '#FFFFFF', '#FFFFFF', size);
};

// 下の帯（y=164 から）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(10, 164, 300, 14 + 15 * n, t, c[0], c[1], size);
};

// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});

// 「なぜ？」の問い → 答え
