import type { DiagramElement, Figure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, band, fresh, flow } from './diagram-kit';
import type { Slide } from './diagram-kit';

type E = DiagramElement;
const tx = (x: number, y: number, t: string, size = 12, color: string = C.ink, bold = true, anchor: 'start' | 'middle' | 'end' = 'middle'): E => lb(x, y, t, size, color, anchor, bold);

// 下の帯：lines の先頭文字で色が決まる（=緑 / ~赤 / *紫 / それ以外は青）。1行だけで先頭が「=答え」なら大きく出す。
const tone = (s: string): [string, string, string] => {
  const c = s[0];
  if (c === '=') return [s.slice(1), C.green, FILL.green];
  if (c === '~') return [s.slice(1), C.red, FILL.red];
  if (c === '*') return [s.slice(1), C.purple, FILL.purple];
  return [s, C.blue, FILL.blue];
};
const B = (lines: string[]): E[] => {
  if (lines.length === 1) {
    const [t, col, fill] = tone(lines[0]);
    const big = t.startsWith('答え');
    return band(146, bx(20, big ? 158 : 166, 280, big ? 42 : 36, t, col, fill, big ? 18 : 15));
  }
  const h = lines.length === 2 ? 36 : 27;
  const gap = lines.length === 2 ? 40 : 30;
  const y0 = lines.length === 2 ? 154 : 150;
  return band(146, ...lines.map((s, i) => {
    const [t, col, fill] = tone(s);
    return bx(20, y0 + i * gap, 280, h, t, col, fill, lines.length === 2 ? 14 : 13);
  }));
};
/** いまの画面に足す */
const S = (note: string, lines: string[], add: E[] = []): Slide => ({ note, add: [...add, ...B(lines)] });
/** 画面をぬりつぶして、新しい図から始める */
const SF = (note: string, lines: string[], draw: E[]): Slide => ({ note, add: [...fresh(...draw), ...B(lines)] });

const rect = (x: number, y: number, w: number, h: number, color?: string, fill?: string): E => pg([[x, y], [x + w, y], [x + w, y + h], [x, y + h]], color, fill);
const disc = (cx: number, cy: number, r: number, color?: string, fill?: string): E =>
  pg(Array.from({ length: 28 }, (_, i) => [cx + r * Math.cos((i / 28) * 2 * Math.PI), cy + r * Math.sin((i / 28) * 2 * Math.PI)] as [number, number]), color, fill);
/** 文字を縦にならべる（中央ぞろえ） */
const L = (lines: string[], y0 = 26, dy = 24, size = 13, color: string = C.ink): E[] => lines.map((t, i) => tx(160, y0 + i * dy, t, size, color));
/** 同じ幅の箱を横に並べる */
const bxs = (labels: string[], y: number, h = 34, size = 11, color: string = C.blue, fill: string = FILL.blue, pad = 10, gap = 8): E[] => {
  const n = labels.length;
  const w = (320 - pad * 2 - gap * (n - 1)) / n;
  return labels.map((t, i) => bx(pad + i * (w + gap), y, w, h, t, color, fill, size));
};
/** 点列を折れ線で結ぶ */
const poly = (pts: [number, number][], color: string = C.ink, width = 2, dashed = false): E[] =>
  pts.slice(1).map((p, i) => ln(pts[i][0], pts[i][1], p[0], p[1], color, dashed, width));

