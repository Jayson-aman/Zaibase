// ════════════ 国語 ════════════
// 1枚ごとに画面をぬりつぶして（fresh）、上に箱の列、下に帯でひとことを出す。
type K = 'b' | 'g' | 'r' | 'p' | 'y' | 'k';
const P: Record<K, [string, string]> = {
  b: [C.blue, FILL.blue],
  g: [C.green, FILL.green],
  r: [C.red, FILL.red],
  p: [C.purple, FILL.purple],
  y: [C.main, FILL.yellow],
  k: [C.gray, FILL.gray],
};
/** [箱の文字, 色, 上の箱から来る矢印のそばの文字（chain のときだけ）] */
type R = [string, K?, string?];
/** 1枚のスライド。rows は上から並べる箱（4つまで）。chain=true なら矢印でつなぐ。big は下の帯（太字の結論）。 */
function sl(note: string, title: string, rows: R[], big?: string, chain = false): Slide {
  const h = chain ? 22 : 26;
  const gap = chain ? 14 : 5;
  const els: E[] = [lb(160, 18, title, 12, C.ink, 'middle', true)];
  rows.forEach(([t, k, a], i) => {
    const y = 30 + i * (h + gap);
    const [col, fill] = P[k ?? 'k'];
    if (chain && i > 0) {
      els.push(ar(160, y - gap + 1, 160, y - 1, C.gray));
      if (a) els.push(lb(170, y - gap / 2, a, 10, C.red, 'start', true));
    }
    els.push(bx(10, y, 300, h, t, col, fill, 12));
  });
  const by = chain ? 168 : 160;
  if (big) els.push(bx(20, by, 280, 30, big, C.green, FILL.green, 14));
  return { note, add: fresh(...els) };
}

