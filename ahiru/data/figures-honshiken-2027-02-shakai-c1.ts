// 問題の場面 → 手がかり → 理由（なぜ？） → 答え → 確かめ の順に、7枚で動かす。
// 座標は 320×240。下の帯（y=160 から）にそのスライドのひとことを出す。
import type { DiagramElement, Figure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, fresh, flow } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const YELLOW: Col = [C.main, FILL.yellow];

const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 160, 292, 16 + 15 * n, t, c[0], c[1], size);
};
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});
/** 「なぜ？」→ 答え の2段の箱。pre で先頭の語を変えられる。 */
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13, pre = 'なぜ？ '): DiagramElement[] => [
  bx(12, 8, 296, 40, pre + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 50, 160, 66, PURPLE[0]),
  bx(12, 68, 296, 74, a, c[0], c[1], aSize),
];
const wrong3 = (a: string, b: string, c: string, size = 11): DiagramElement[] => [
  bx(14, 8, 292, 36, a, C.red, FILL.red, size),
  bx(14, 50, 292, 36, b, C.red, FILL.red, size),
  bx(14, 92, 292, 36, c, C.red, FILL.red, size),
];
const ans = (t: string, c: Col = GREEN, h = 60, size = 13): DiagramElement[] => [bx(14, 14, 292, h, t, c[0], c[1], size)];
const list = (title: string, body: string, c: Col = BLUE, h = 92, size = 12): DiagramElement[] => [
  bx(14, 8, 292, 28, title, c[0], c[1], 12),
  bx(14, 42, 292, h, body, c[0], c[1], size),
];
const pair = (l: string, r: string, cl: Col = BLUE, cr: Col = MAIN, y = 14, h = 62, size = 12): DiagramElement[] => [
  bx(10, y, 130, h, l, cl[0], cl[1], size),
  ar(143, y + h / 2, 177, y + h / 2, C.ink),
  bx(180, y, 130, h, r, cr[0], cr[1], size),
];
/** 2×2 のカード。n 枚目までを描く。 */
const cards = (texts: string[], n: number, hi: number[] = [], size = 12): DiagramElement[] =>
  texts.slice(0, n).map((t, i) => {
    const c = hi.includes(i) ? GREEN : i % 2 === 0 ? BLUE : MAIN;
    return bx(10 + (i % 2) * 154, 10 + Math.floor(i / 2) * 70, 146, 60, t, c[0], c[1], size);
  });
/** 横棒グラフ。items = [名前, 値, 値の表示, 色]。棒は x=84 から最大 maxW。 */
const hbars = (items: [string, number, string, Col][], y0: number, max: number, maxW = 120, h = 24, gap = 10): DiagramElement[] => {
  const out: DiagramElement[] = [];
  items.forEach(([name, v, txt, c], i) => {
    const y = y0 + i * (h + gap);
    const w = Math.max(4, (v / max) * maxW);
    out.push(lb(10, y + h / 2 + 4, name, 11, C.ink, 'start', true));
    out.push(bx(84, y, w, h, undefined, c[0], c[1]));
    out.push(lb(84 + w + 5, y + h / 2 + 4, txt, 10, C.ink, 'start'));
  });
  return out;
};
/** 3列×最大3行の箱（上の行から順に）。 */
const g3 = (rows: string[][], size = 12): DiagramElement[] =>
  rows.flatMap((r, ri) => {
    const c = [MAIN, BLUE, GREEN][ri % 3];
    return r.map((t, k) => bx(10 + k * 104, 12 + ri * 44, 92, 36, t, c[0], c[1], size));
  });
/** 5列×最大4行の小さな名前札。hi の名前は緑で強調。 */
const tags = (names: string[], n: number, hi: string[] = []): DiagramElement[] =>
  names.slice(0, n).map((t, i) => {
    const c = hi.includes(t) ? GREEN : BLUE;
    return bx(10 + (i % 5) * 60, 10 + Math.floor(i / 5) * 32, 56, 26, t, c[0], c[1], 10);
  });


const Q = (note: string, body: string, capT: string, c: Col = PURPLE) => S(note, qa('', body, c, 13, 'なぜ？'), capT, c);
const L = (note: string, title: string, body: string, capT: string, c: Col = BLUE, h = 78) => S(note, list(title, body, c, h), capT, c);
const A = (note: string, text: string, capT: string) => S(note, ans(text, GREEN, 64), capT, GREEN);
const W = (note: string, a: string, b: string, c: string, capT: string) => S(note, wrong3(a, b, c), capT, RED);
const K = (note: string, body: string, capT: string) => S(note, list('確かめ', body, GREEN, 78), capT, GREEN);
const mk = (s: ReturnType<typeof S>[]) => show(s);

