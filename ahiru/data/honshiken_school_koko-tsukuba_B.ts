const ex = (o: Opt) =>
  `【何を聞かれているか】\n${o.ask}\n\n【なぜそうなるのか】\n${o.why}\n\n` +
  o.steps.map((s, i) => `【ステップ${i + 1}】\n${s}`).join('\n\n') +
  `\n\n【答え】\n${o.a}\n\n【確かめ】\n${o.chk}\n\n【よくあるまちがい】\n${o.mis}`;
const mk = (subject: 'rika' | 'shakai', n: number, difficulty: 'standard' | 'advanced', o: Opt): Question => {
  const base: Question = {
    id: `honshiken_school_koko_tsukuba_${subject}_${String(n).padStart(2, '0')}`,
    subject,
    examType: 'koko',
    course: 'koko-tsukuba',
    difficulty,
    question: o.q,
    answer: o.a,
    hint: o.hint,
    explanation: ex(o),
    pitfall: o.pit,
    memoryTip: o.tip,
  };
  if (o.choices) base.choices = o.choices;
  if (o.fd) base.figureDescription = o.fd;
  if (o.written) { base.isWritten = true; base.rubricPoints = o.rubric; }
  return base;
};
