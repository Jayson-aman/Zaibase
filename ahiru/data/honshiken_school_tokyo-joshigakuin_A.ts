const ex = (o: Src): string =>
  '【何を聞かれているか】\n' + o.ask +
  '\n\n【なぜそうなるのか】\n' + o.why +
  o.steps.map((s, i) => '\n\n【ステップ' + (i + 1) + '】\n' + s).join('') +
  '\n\n【答え】\n' + o.answer +
  '\n\n【確かめ】\n' + o.check +
  '\n\n【よくあるまちがい】\n' + o.miss;

