type Ex = { what: string; why: string; steps: string[]; ans: string; check: string; mistake: string };
const ex = (e: Ex): string =>
  `【何を聞かれているか】${e.what}\n【なぜそうなるのか】${e.why}\n` +
  e.steps.map((s, i) => `【ステップ${i + 1}】${s}`).join('\n') +
  `\n【答え】${e.ans}\n【確かめ】${e.check}\n【よくあるまちがい】${e.mistake}`;

