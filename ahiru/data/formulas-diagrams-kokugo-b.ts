import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, band, fresh, cover } from './diagram-kit';

type Sp = { t: string; w: number; c?: string; f?: string };
type Row = { x: number[]; w: number[]; cx: number[]; y: number; h: number; sp: Sp[]; size: number };

/** 文節などを横一列の箱にならべる（中央そろえ）。 */
const rowAt = (y: number, sp: Sp[], h = 30, gap = 4, size = 14): Row => {
  const total = sp.reduce((a, s) => a + s.w, 0) + gap * (sp.length - 1);
  let x = (320 - total) / 2;
  const xs: number[] = [];
  for (const s of sp) {
    xs.push(x);
    x += s.w + gap;
  }
  return { x: xs, w: sp.map((s) => s.w), cx: sp.map((s, i) => xs[i] + s.w / 2), y, h, sp, size };
};
/** i番目の箱を（色を指定して）描く。 */
const bxi = (r: Row, i: number, c?: string, f?: string): DiagramElement =>
  bx(r.x[i], r.y, r.w[i], r.h, r.sp[i].t, c ?? r.sp[i].c ?? C.gray, f ?? r.sp[i].f ?? FILL.gray, r.size);
const rowEls = (r: Row): DiagramElement[] => r.sp.map((_, i) => bxi(r, i));

/** 上側の「かぎ形の矢印」：i番目の箱の上から出て、j番目の箱の上へ。lift は上にあげる高さ。 */
const arcUp = (r: Row, i: number, j: number, lift: number, color: string): DiagramElement[] => [
  ln(r.cx[i], r.y, r.cx[i], r.y - lift, color, false, 2),
  ln(r.cx[i], r.y - lift, r.cx[j], r.y - lift, color, false, 2),
  ar(r.cx[j], r.y - lift, r.cx[j], r.y - 1, color),
];
/** 下側の「かぎ形の矢印」。 */
const arcDown = (r: Row, i: number, j: number, drop: number, color: string): DiagramElement[] => {
  const yb = r.y + r.h;
  return [
    ln(r.cx[i], yb, r.cx[i], yb + drop, color, false, 2),
    ln(r.cx[i], yb + drop, r.cx[j], yb + drop, color, false, 2),
    ar(r.cx[j], yb + drop, r.cx[j], yb + 1, color),
  ];
};

/** 1文字ずつの升目（字数を数える図）。hl は {番号: [線色, 塗り色]}。perRow をこえたら次の段へ。 */
const cells = (text: string, y: number, cw: number, h: number, hl?: Record<number, [string, string]>, size = 13, perRow = 99): DiagramElement[] => {
  const chars = [...text];
  return chars.map((ch, i) => {
    const row = Math.floor(i / perRow);
    const inRow = Math.min(perRow, chars.length - row * perRow);
    const x0 = (320 - inRow * cw) / 2;
    return bx(x0 + (i % perRow) * cw, y + row * (h + 4), cw, h, ch, hl?.[i]?.[0] ?? C.gray, hl?.[i]?.[1] ?? FILL.warm, size);
  });
};

/** 下の帯：1行目（大きめ）と2行目（小さめ）。 */
const bt = (l1: string, l2?: string, col: string = C.ink): DiagramElement[] =>
  band(150, lb(160, 172, l1, 13, col, 'middle', true), ...(l2 ? [lb(160, 200, l2, 11.5, C.gray)] : []));

