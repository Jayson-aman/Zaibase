import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

type E = DiagramElement;
const T = (y: number, s: string, color: string = C.ink): E => lb(160, y, s, 13, color, 'middle', true);
const L = (x: number, y: number, s: string, color: string = C.ink, size = 12, anchor: 'start' | 'middle' | 'end' = 'middle'): E => lb(x, y, s, size, color, anchor, true);
const water = (x0: number, x1: number, top: number, bot: number): E => pg([[x0, top], [x1, top], [x1, bot], [x0, bot]], C.blue, FILL.blue);
const cup = (x0: number, x1: number, top: number, bot: number): E[] => [
  ln(x0, top, x0, bot, C.gray, false, 3), ln(x0, bot, x1, bot, C.gray, false, 3), ln(x1, top, x1, bot, C.gray, false, 3),
];
/** ばねばかり。y から y+32 までが本体。つるす糸は rope で足す。 */
const hook = (cx: number, y: number, text?: string): E[] => [ln(cx, y, cx, y + 6, C.gray, false, 2), bx(cx - 21, y + 6, 42, 26, text, C.main, FILL.warm, 12)];
const rope = (cx: number, y1: number, y2: number): E => ln(cx, y1, cx, y2, C.gray, false, 1.5);
const CLAY = '#E8C9A0';

/** 波（cos は山から、sin は 0 から始まる）。 */
function wave(x0: number, x1: number, y: number, amp: number, cycles: number, color: string, kind: 'cos' | 'sin' = 'cos', width = 2): E[] {
  const n = Math.round(cycles * 12);
  const f = (i: number) => (kind === 'cos' ? y - amp * Math.cos((2 * Math.PI * cycles * i) / n) : y - amp * Math.sin((2 * Math.PI * cycles * i) / n));
  const out: E[] = [];
  for (let i = 1; i <= n; i++) out.push(ln(x0 + ((x1 - x0) * (i - 1)) / n, f(i - 1), x0 + ((x1 - x0) * i) / n, f(i), color, false, width));
  return out;
}
/** 弦のふるえ（1つの山）。 */
function arch(x0: number, x1: number, y: number, amp: number, color: string): E[] {
  const n = 12, out: E[] = [];
  for (let i = 1; i <= n; i++) out.push(ln(x0 + ((x1 - x0) * (i - 1)) / n, y - amp * Math.sin((Math.PI * (i - 1)) / n), x0 + ((x1 - x0) * i) / n, y - amp * Math.sin((Math.PI * i) / n), color, false, 2));
  return out;
}

// ---- 電気の回路の部品 ----
const BRIGHT = '#FDE047';
const MID = '#FEF08A';
const DIM = '#FEF9C3';
const OFF = '#D6D3D1';
const wire = (x1: number, y1: number, x2: number, y2: number): E => ln(x1, y1, x2, y2, C.gray, false, 2);
const bulb = (x: number, y: number, fill: string = BRIGHT): E => ci(x, y, 8, undefined, C.main, fill);
const batt = (x: number, y: number): E => bx(x - 13, y - 8, 26, 16, '電池', C.blue, FILL.blue, 10);
const cut = (x: number, y: number): E[] => [ln(x - 7, y - 7, x + 7, y + 7, C.red, false, 2.5), ln(x - 7, y + 7, x + 7, y - 7, C.red, false, 2.5)];
const XL = 58;
/** 直列の回路。nb 個の豆電球（xs の位置）、電池は左（2個目は右）。 */
function series(y0: number, xs: number[], fills: string[], xr: number, twoBatt = false): E[] {
  const H = 32, m = y0 + H / 2;
  const out: E[] = [wire(XL, y0, xr, y0), wire(XL, y0 + H, xr, y0 + H), wire(XL, y0, XL, y0 + 8), wire(XL, y0 + H - 8, XL, y0 + H)];
  if (!twoBatt) out.push(wire(xr, y0, xr, y0 + H));
  else { out.push(wire(xr, y0, xr, y0 + 8), wire(xr, y0 + H - 8, xr, y0 + H), batt(xr, m)); }
  out.push(batt(XL, m));
  xs.forEach((x, i) => out.push(bulb(x, y0, fills[i])));
  return out;
}
/** 並列の枝の回路。bxs＝枝の位置、fills＝枝ごとの豆電球の色。mixA があれば、上の導線に直列の豆電球を1つ置く。 */
function branches(y0: number, bxs: number[], fills: string[], mixA?: { x: number; fill: string }): E[] {
  const H = 32, m = y0 + H / 2, xe = bxs[bxs.length - 1];
  const out: E[] = [wire(XL, y0, xe, y0), wire(XL, y0 + H, xe, y0 + H), wire(XL, y0, XL, y0 + 8), wire(XL, y0 + H - 8, XL, y0 + H)];
  bxs.forEach((x) => out.push(wire(x, y0, x, y0 + H)));
  out.push(batt(XL, m));
  bxs.forEach((x, i) => out.push(bulb(x, m, fills[i])));
  if (mixA) out.push(bulb(mixA.x, y0, mixA.fill));
  return out;
}

