// 溶解度の計算（ビーカーの絵）と、太陽・月・星・惑星の動き（位置関係の絵）。座標は 320×240。
import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, sc, C, FILL } from './diagram-kit';

const OR = '#F59E0B';
const rn = (v: number) => Math.round(v * 10) / 10;
const pt = (cx: number, cy: number, r: number, deg: number): [number, number] => [rn(cx + r * Math.cos((deg * Math.PI) / 180)), rn(cy - r * Math.sin((deg * Math.PI) / 180))];

/** ビーカー（口が開いたガラス）。 */
const glass = (x: number, w: number, topY = 30, bot = 134): DiagramElement[] => [
  ln(x, topY, x, bot, C.gray, false, 2.5),
  ln(x, bot, x + w, bot, C.gray, false, 2.5),
  ln(x + w, topY, x + w, bot, C.gray, false, 2.5),
];
/** 水（文字なし）。h＝水の高さ。 */
const wat = (x: number, w: number, h: number, bot = 134): DiagramElement => bx(x + 1, bot - h, w - 2, h - 1, undefined, C.blue, FILL.blue);
/** ビーカーの下の見出し。 */
const cap = (x: number, text: string, color?: string): DiagramElement => lb(x, 148, text, 12, color ?? C.gray, 'middle');
/** ビーカーの上の見出し。 */
const hd = (x: number, text: string, color?: string): DiagramElement => lb(x, 22, text, 12, color ?? C.ink, 'middle', true);
const RY = [166, 182, 198, 214, 230];
/** 下の式の行（i＝0〜4）。 */
const row = (i: number, text: string, color: string = C.ink): DiagramElement => lb(160, RY[i], text, 13, color, 'middle', true);
/** 円（輪）を細い線でえがく。fill のある円だと文字が乗れないので、線分でつくる。 */
const ring = (cx: number, cy: number, r: number, color = '#94A3B8', n = 48): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let i = 0; i < n; i++) {
    const a = pt(cx, cy, r, (360 / n) * i);
    const b = pt(cx, cy, r, (360 / n) * (i + 1));
    out.push(ln(a[0], a[1], b[0], b[1], color, false, 1.4));
  }
  return out;
};
/** 円弧（from〜to 度）を線分でえがく。 */
const arc = (cx: number, cy: number, r: number, from: number, to: number, color = '#94A3B8', dashed = false, n = 36): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let i = 0; i < n; i++) {
    const a = pt(cx, cy, r, from + ((to - from) / n) * i);
    const b = pt(cx, cy, r, from + ((to - from) / n) * (i + 1));
    out.push(ln(a[0], a[1], b[0], b[1], color, dashed && i % 2 === 1, 1.6));
  }
  return out;
};
/** 蒸発（水蒸気）の上向き矢印。 */
const steam = (xs: number[], y1: number, y2: number): DiagramElement[] => xs.map((x) => ar(x, y1, x, y2, C.blue, true));
const sun = (x: number, y: number, r = 9): DiagramElement => ci(x, y, r, undefined, OR, FILL.yellow);

