import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

type Pred = (i: number, j: number) => boolean;

/** 人（円）を nx×ny の格子に並べる。pred が true の位置だけ描く。 */
function people(nx: number, ny: number, gx: number, gy: number, step: number, r: number, pred: Pred, color: string, fill: string): DiagramElement[] {
  const out: DiagramElement[] = [];
  for (let j = 0; j < ny; j++) for (let i = 0; i < nx; i++) if (pred(i, j)) out.push(ci(gx + i * step, gy + j * step, r, undefined, color, fill));
  return out;
}
const rimOf = (nx: number, ny: number): Pred => (i, j) => i === 0 || i === nx - 1 || j === 0 || j === ny - 1;
const innerOf = (nx: number, ny: number): Pred => (i, j) => i > 0 && i < nx - 1 && j > 0 && j < ny - 1;
const cornerOf = (nx: number, ny: number): Pred => (i, j) => (i === 0 || i === nx - 1) && (j === 0 || j === ny - 1);
const all: Pred = () => true;
const sideTop = (nx: number): Pred => (i, j) => j === 0 && i <= nx - 2;
const sideRight = (nx: number, ny: number): Pred => (i, j) => i === nx - 1 && j <= ny - 2;
const sideBottom = (nx: number, ny: number): Pred => (i, j) => j === ny - 1 && i >= 1;
const sideLeft = (ny: number): Pred => (i, j) => i === 0 && j >= 1 && j <= ny - 1;

/** 下の説明行。row=0〜5 を上から順に使い、スライドごとに別の行へ足していく。 */
const TY = [150, 166, 182, 198, 214, 230];
const ft = (row: number, text: string, color: string = C.ink, size = 13): DiagramElement => lb(160, TY[row], text, size, color, 'middle', true);

/** 食塩（黄）と水（青）の線分図。k＝1gあたりのpx。 */
function sw(x: number, y: number, h: number, salt: number, water: number, k: number, waterText?: string): DiagramElement[] {
  return [bx(x, y, salt * k, h, undefined, C.main, FILL.yellow), bx(x + salt * k, y, water * k, h, waterText, C.blue, FILL.blue, 12)];
}
const G = (x: number, y: number, h: number, w: number, t: string | undefined, c: string, f: string, s = 12) => bx(x, y, w, h, t, c, f, s);

