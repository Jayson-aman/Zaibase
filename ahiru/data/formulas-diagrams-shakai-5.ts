// 社会 第5批（formulas-shakai-tsuika5.ts）の動く図解スライド。
// キーは項目の label（買い切りの識別キーと同じ）。「なぜ？」をくり返して根っこまでたどる。
// 画面の上半分に図、下の帯（cap）に、そのスライドの式・ひとこと、という配置にそろえてある。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, sc, show, flow, band, fresh } from './diagram-kit';

const cap = (t: string, c: string = C.blue, f: string = FILL.blue): DiagramElement[] => band(150, bx(14, 160, 292, 56, t, c, f, 13));
const F = (a: DiagramElement[][]): DiagramElement[] => a.flat();
const row = (labels: string[], y: number, h = 44, c: string = C.main, f: string = FILL.warm, size = 12): DiagramElement[] =>
  F(flow(labels, y, { h, color: c, fill: f, size }));
/** 箱を等間隔に横ならべ（矢印なし） */
const boxes = (labels: string[], y: number, h: number, c: string, f: string, size = 12): DiagramElement[] => {
  const n = labels.length;
  const gap = 8;
  const w = (320 - 16 - gap * (n - 1)) / n;
  return labels.map((t, i) => bx(8 + i * (w + gap), y, w, h, t, c, f, size));
};

