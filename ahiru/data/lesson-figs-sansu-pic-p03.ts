type A = 'start' | 'middle' | 'end';
const t = (x: number, y: number, s: string, color: string = C.ink, size = 13, anchor: A = 'middle'): DiagramElement => lb(x, y, s, size, color, anchor, true);
const blue = (x: number, y: number, w: number, h: number, s?: string, size = 14) => bx(x, y, w, h, s, C.blue, FILL.blue, size);
const green = (x: number, y: number, w: number, h: number, s?: string, size = 14) => bx(x, y, w, h, s, C.green, FILL.green, size);
const red = (x: number, y: number, w: number, h: number, s?: string, size = 14) => bx(x, y, w, h, s, C.red, FILL.red, size);
const gray = (x: number, y: number, w: number, h: number, s?: string, size = 14) => bx(x, y, w, h, s, C.gray, FILL.gray, size);
const purple = (x: number, y: number, w: number, h: number, s?: string, size = 14) => bx(x, y, w, h, s, C.purple, FILL.purple, size);
const yellow = (x: number, y: number, w: number, h: number, s?: string, size = 14) => bx(x, y, w, h, s, C.main, FILL.yellow, size);
/** 文字のない枠線だけの強調 */
const ring = (x: number, y: number, w: number, h: number, color: string = C.red) => bx(x, y, w, h, undefined, color, 'none');

/** 約数の表（行＝3を使う個数、列＝2を使う個数）を描く部品群 */
function divGrid(x0: number, cw: number, cols: number[], rows: number[][], rowNames: string[], fillOf: (r: number) => string, colorOf: (r: number) => string) {
  const y0 = 74, ch = 40;
  const head = [t(x0 + (cw * cols.length) / 2, 48, '2を使う個数', C.blue, 12), t(24, 66, '3を使う', C.green, 10), ...cols.map((_, c) => t(x0 + c * cw + cw / 2, 66, `${c}こ`, C.blue, 12))];
  const rowLabel = (r: number) => t(24, y0 + r * ch + 25, rowNames[r], C.green, 12);
  const cells = (r: number) => rows[r].map((v, c) => bx(x0 + c * cw, y0 + r * ch, cw, ch, String(v), colorOf(r), fillOf(r), 16));
  return { head, rowLabel, cells, y0, ch };
}

