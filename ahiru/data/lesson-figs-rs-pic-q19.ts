// 画面の下に、スライドごとに1行ずつ足していく文字の高さ
const Y = [152, 167, 182, 197, 212, 227];
const note = (i: number, text: string, color: string = C.ink, bold = false): DiagramElement => lb(160, Y[i], text, 12, color, 'middle', bold);
const ring = (x: number, y: number, w: number, h: number): DiagramElement => bx(x, y, w, h, undefined, C.red, 'none');

// 2行・3列のへびのような工程図（上段は左から右、下段は右から左）
function snake(top: string[], bottom: string[], y1: number, y2: number, h: number, size: number, color: string, fill: string): DiagramElement[][] {
  const xs = [12, 120, 228];
  const out: DiagramElement[][] = [];
  top.forEach((t, i) => {
    const els: DiagramElement[] = [];
    if (i > 0) els.push(ar(xs[i - 1] + 82, y1 + h / 2, xs[i] - 2, y1 + h / 2, color));
    els.push(bx(xs[i], y1, 80, h, t, color, fill, size));
    out.push(els);
  });
  bottom.forEach((t, i) => {
    const x = xs[2 - i];
    const els: DiagramElement[] = [];
    if (i === 0) els.push(ar(268, y1 + h + 1, 268, y2 - 1, color));
    else els.push(ar(xs[2 - i + 1] - 2, y2 + h / 2, x + 82, y2 + h / 2, color));
    els.push(bx(x, y2, 80, h, t, color, fill, size));
    out.push(els);
  });
  return out;
}

