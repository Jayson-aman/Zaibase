const tx = (x: number, y: number, t: string, size = 12, color: string = C.ink, bold = true, anchor: 'start' | 'middle' | 'end' = 'middle'): E => lb(x, y, t, size, color, anchor, bold);

// 下の帯：lines の先頭文字で色が決まる（=緑 / ~赤 / *紫 / それ以外は青）。1行だけで先頭が「=答え」なら大きく出す。
const tone = (s: string): [string, string, string] => {
  const c = s[0];
  if (c === '=') return [s.slice(1), C.green, FILL.green];
  if (c === '~') return [s.slice(1), C.red, FILL.red];
  if (c === '*') return [s.slice(1), C.purple, FILL.purple];
  return [s, C.blue, FILL.blue];
};
const B = (lines: string[]): E[] => {
  if (lines.length === 1) {
    const [t, col, fill] = tone(lines[0]);
    const big = t.startsWith('答え');
    return band(146, bx(20, big ? 158 : 166, 280, big ? 42 : 36, t, col, fill, big ? 18 : 15));
  }
  const h = lines.length === 2 ? 36 : 27;
  const gap = lines.length === 2 ? 40 : 30;
  const y0 = lines.length === 2 ? 154 : 150;
  return band(146, ...lines.map((s, i) => {
    const [t, col, fill] = tone(s);
    return bx(20, y0 + i * gap, 280, h, t, col, fill, lines.length === 2 ? 14 : 13);
  }));
};
const S = (note: string, lines: string[], add: E[] = []): Slide => ({ note, add: [...add, ...B(lines)] });
const SF = (note: string, lines: string[], draw: E[]): Slide => ({ note, add: [...fresh(...draw), ...B(lines)] });

// 枠線だけの四角（中に文字を置いても「箱の上に乗る」と見なされないよう、線4本で描く）
const rect = (x: number, y: number, w: number, h: number, color: string = C.ink, width = 1.5, dashed = false): E[] => [
  ln(x, y, x + w, y, color, dashed, width), ln(x + w, y, x + w, y + h, color, dashed, width),
  ln(x + w, y + h, x, y + h, color, dashed, width), ln(x, y + h, x, y, color, dashed, width),
];
// 円（多角形で近似。文字を中に置いてよい）
const circ = (cx: number, cy: number, r: number, color: string = C.ink, fill?: string): E => {
  const pts: [number, number][] = [];
  for (let i = 0; i < 48; i++) { const a = (i / 48) * Math.PI * 2; pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]); }
  return pg(pts, color, fill);
};
// 弧（角度は数学の向き：右が0度、上が90度）。線分でつなぐ。
const arc = (cx: number, cy: number, r: number, a0: number, a1: number, color: string = C.ink, width = 2): E[] => {
  const out: E[] = [];
  const n = 18;
  for (let i = 0; i < n; i++) {
    const t0 = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    const t1 = ((a0 + ((a1 - a0) * (i + 1)) / n) * Math.PI) / 180;
    out.push(ln(cx + r * Math.cos(t0), cy - r * Math.sin(t0), cx + r * Math.cos(t1), cy - r * Math.sin(t1), color, false, width));
  }
  return out;
};
const arcPts = (cx: number, cy: number, r: number, a0: number, a1: number, n = 18): [number, number][] => {
  const out: [number, number][] = [];
  for (let i = 0; i <= n; i++) { const t = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180; out.push([cx + r * Math.cos(t), cy - r * Math.sin(t)]); }
  return out;
};

