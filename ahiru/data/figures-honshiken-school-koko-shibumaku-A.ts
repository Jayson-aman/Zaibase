type E = DiagramElement;
type Pt = [number, number];
const tx = (x: number, y: number, t: string, size = 12, color: string = C.ink, bold = true, anchor: 'start' | 'middle' | 'end' = 'middle'): E => lb(x, y, t, size, color, anchor, bold);

// 下の帯：lines の先頭文字で色が決まる（=緑 / ~赤 / *紫 / それ以外は青）。1行だけで先頭が「=答え」なら大きく出す。
const tone = (s: string): [string, string, string] => {
  const c = s[0];
  if (c === '=') return [s.slice(1), C.green, FILL.green];
  if (c === '~') return [s.slice(1), C.red, FILL.red];
  if (c === '*') return [s.slice(1), C.purple, FILL.purple];
  return [s, C.blue, FILL.blue];
};
const B = (lines: string[]): E[] => {
  if (lines.length === 1) {
    const [t, col, fill] = tone(lines[0]);
    const big = t.startsWith('答え');
    return band(146, bx(20, big ? 158 : 166, 280, big ? 42 : 36, t, col, fill, big ? 18 : 15));
  }
  const h = lines.length === 2 ? 36 : 27;
  const gap = lines.length === 2 ? 40 : 30;
  const y0 = lines.length === 2 ? 154 : 150;
  return band(146, ...lines.map((s, i) => {
    const [t, col, fill] = tone(s);
    return bx(20, y0 + i * gap, 280, h, t, col, fill, lines.length === 2 ? 14 : 13);
  }));
};
const S = (note: string, lines: string[], add: E[] = []): Slide => ({ note, add: [...add, ...B(lines)] });
const SF = (note: string, lines: string[], draw: E[]): Slide => ({ note, add: [...fresh(...draw), ...B(lines)] });

// ── 座標平面の道具 ──
type Tr = (x: number, y: number) => Pt;
const pl = (ox: number, oy: number, s: number): Tr => (x, y) => [ox + x * s, oy - y * s];
const seg = (t: Tr, a: Pt, b: Pt, color: string = C.ink, dashed = false, w?: number): E => {
  const [x1, y1] = t(a[0], a[1]); const [x2, y2] = t(b[0], b[1]);
  return ln(x1, y1, x2, y2, color, dashed, w);
};
const dot = (t: Tr, p: Pt, color: string = C.ink, r = 3): E => { const [x, y] = t(p[0], p[1]); return ci(x, y, r, undefined, color, color); };
const nm = (t: Tr, p: Pt, text: string, dx: number, dy: number, color: string = C.ink, size = 12): E => {
  const [x, y] = t(p[0], p[1]); return tx(x + dx, y + dy, text, size, color);
};
const poly = (t: Tr, pts: Pt[], color: string, fill: string): E => pg(pts.map((p) => t(p[0], p[1])), color, fill);
const axes = (t: Tr, x0: number, x1: number, y0: number, y1: number): E[] => {
  const [ox, oy] = t(0, 0);
  return [seg(t, [x0, 0], [x1, 0], C.gray), seg(t, [0, y0], [0, y1], C.gray), tx(ox - 9, oy + 12, 'O', 11, C.gray), nm(t, [x1, 0], 'x', 0, 13, C.gray, 11), nm(t, [0, y1], 'y', 10, 4, C.gray, 11)];
};
const curve = (t: Tr, f: (x: number) => number, x0: number, x1: number, n = 24, color: string = C.purple): E[] => {
  const out: E[] = [];
  for (let i = 0; i < n; i++) {
    const a = x0 + ((x1 - x0) * i) / n; const b = x0 + ((x1 - x0) * (i + 1)) / n;
    out.push(seg(t, [a, f(a)], [b, f(b)], color, false, 1.8));
  }
  return out;
};

