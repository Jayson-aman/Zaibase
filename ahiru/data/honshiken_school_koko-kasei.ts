const ex = (p: { what: string; why: string; steps: string[]; ans: string; check: string; mis: string }): string =>
  `【何を聞かれているか】${p.what}\n【なぜそうなるのか】${p.why}\n` +
  p.steps.map((s, i) => `【ステップ${i + 1}】${s}`).join('\n') +
  `\n【答え】${p.ans}\n【確かめ】${p.check}\n【よくあるまちがい】${p.mis}`;

