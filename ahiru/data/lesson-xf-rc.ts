import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, sc, show, band, fresh, cover, flow, stack } from './diagram-kit';

const r1 = (n: number) => Math.round(n * 10) / 10;
const rad = (d: number) => (d * Math.PI) / 180;
const sinD = (d: number) => Math.sin(rad(d));
const cosD = (d: number) => Math.cos(rad(d));
const asinD = (x: number) => (Math.asin(x) * 180) / Math.PI;
/** 数学の向き（右が0°、反時計まわり）で、中心から len だけ進んだ点。 */
const polar = (cx: number, cy: number, len: number, deg: number): [number, number] => [r1(cx + len * cosD(deg)), r1(cy - len * sinD(deg))];

/** 下の帯にひとこと（改行可）。 */
const cap = (t: string, color: string = C.ink, size = 12) => band(150, lb(160, 192, t, size, color, 'middle', true));
/** 楕円（点を結んだ多角形）。 */
const ell = (cx: number, cy: number, rx: number, ry: number, color?: string, fill?: string): DiagramElement => {
  const pts: [number, number][] = [];
  for (let i = 0; i < 28; i++) {
    const a = (i / 28) * Math.PI * 2;
    pts.push([r1(cx + rx * Math.cos(a)), r1(cy + ry * Math.sin(a))]);
  }
  return pg(pts, color, fill);
};

