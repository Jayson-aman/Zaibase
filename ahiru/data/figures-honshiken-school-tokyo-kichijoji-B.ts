// 座標は 320×240。上（y<142）に図・箱、下の帯（y≧146）に答え・ひとこと。
import type { DiagramElement, Figure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, band, fresh } from './diagram-kit';
import type { Slide } from './diagram-kit';

type E = DiagramElement;
type Sl = [note: string, boxes: string[], band: string];
type Spec = { pics?: (() => E[])[]; s: Sl[]; cap: string };

// 文字が箱に収まるまで、文字の大きさを小さくする箱
const cw = (c: string, s: number) => (/[\x20-\x7e]/.test(c) ? (c === ' ' ? 0.3 : /[0-9]/.test(c) ? 0.58 : /[A-Z]/.test(c) ? 0.66 : 0.52) * s : s);
const tw = (t: string, s: number) => Math.max(...t.split('\n').map((l) => [...l].reduce((a, c) => a + cw(c, s), 0)));
const fb = (x: number, y: number, w: number, h: number, t: string, col: string, fill: string, size = 13): E => {
  let s = size;
  while (s > 7 && (tw(t, s) > w - 5 || t.split('\n').length * s * 1.2 > h - 2)) s -= 0.5;
  return bx(x, y, w, h, t, col, fill, s);
};
// 先頭文字で色（=緑 / ~赤 / *紫 / それ以外は青）
const tone = (s: string): [string, string, string] => {
  const c = s[0];
  if (c === '=') return [s.slice(1), C.green, FILL.green];
  if (c === '~') return [s.slice(1), C.red, FILL.red];
  if (c === '*') return [s.slice(1), C.purple, FILL.purple];
  return [s, C.blue, FILL.blue];
};
const boxes = (lines: string[]): E[] => {
  const n = lines.length;
  const h = n === 1 ? 64 : n === 2 ? 54 : 38;
  const gap = n === 1 ? 0 : n === 2 ? 12 : 6;
  const y0 = n === 1 ? 38 : n === 2 ? 10 : 8;
  return lines.map((s, i) => {
    const [t, col, fill] = tone(s);
    return fb(20, y0 + i * (h + gap), 280, h, t, col, fill, n === 1 ? 15 : 13);
  });
};
const bandOf = (s: string): E[] => {
  const [t, col, fill] = tone(s);
  const big = t.startsWith('答え');
  return band(146, fb(20, big ? 158 : 166, 280, big ? 42 : 36, t, col, fill, big ? 18 : 14));
};

// ---- 絵の部品 ----
const rect = (x: number, y: number, w: number, h: number, color: string = C.ink, fill: string = FILL.gray): E => pg([[x, y], [x + w, y], [x + w, y + h], [x, y + h]], color, fill);
const disc = (cx: number, cy: number, r: number, color: string = C.ink, fill: string = FILL.gray): E =>
  pg(Array.from({ length: 28 }, (_, i) => [cx + r * Math.cos((i / 28) * 2 * Math.PI), cy + r * Math.sin((i / 28) * 2 * Math.PI)] as [number, number]), color, fill);
const tx = (x: number, y: number, t: string, size = 11, color: string = C.ink, anchor: 'start' | 'middle' | 'end' = 'middle'): E => lb(x, y, t, size, color, anchor, true);
/** 表。cols = 列の幅、rows[0] は見出し。 */
const tbl = (x: number, y: number, cols: number[], rowH: number, rows: string[][], size = 11): E[] => {
  const out: E[] = [];
  rows.forEach((r, i) => {
    let cx = x;
    r.forEach((t, j) => {
      const head = i === 0;
      out.push(fb(cx, y + i * rowH, cols[j], rowH, t, head ? C.main : C.blue, head ? FILL.warm : FILL.blue, size));
      cx += cols[j];
    });
  });
  return out;
};
/** 折れ線グラフの軸（左下が原点）。 */
const axes = (x0: number, y0: number, w: number, h: number): E[] => [ln(x0, y0, x0 + w, y0, C.ink, false, 2), ln(x0, y0, x0, y0 - h, C.ink, false, 2)];

const build = (v: Spec): Figure => {
  const slides: Slide[] = v.s.map(([note, bs, bd]) => {
    const top: E[] = [];
    const texts: string[] = [];
    for (const b of bs) {
      if (/^@\d$/.test(b)) top.push(...v.pics![Number(b[1])]());
      else texts.push(b);
    }
    if (texts.length) top.push(...boxes(texts));
    return { note, add: fresh(...top, ...bandOf(bd)) };
  });
  return show(slides, v.cap);
};
/** 年表。ev = [年, 出来事]。上下に交互に文字を置く。 */
const tl = (ev: [string, string][]): E[] => {
  const n = ev.length;
  const x0 = 50, x1 = 270;
  const out: E[] = [ln(x0 - 20, 76, x1 + 20, 76, C.ink, false, 3)];
  ev.forEach(([y, t], i) => {
    const x = n === 1 ? 160 : x0 + (i * (x1 - x0)) / (n - 1);
    out.push(disc(x, 76, 5, C.main, FILL.warm));
    out.push(tx(x, i % 2 === 0 ? 62 : 96, y, 11, C.main));
    out.push(tx(x, i % 2 === 0 ? 46 : 112, t, 11, C.ink));
  });
  return out;
};

