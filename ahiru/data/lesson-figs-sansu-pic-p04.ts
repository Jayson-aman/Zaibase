// 周期算・倍数・約数・N進法／割合・歩合・比。座標は 320×240 の内部座標。
import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, C, FILL } from './diagram-kit';

type Anchor = 'start' | 'middle' | 'end';
/** 太字の文字。 */
const T = (x: number, y: number, text: string, color: string = C.ink, size = 13, anchor: Anchor = 'middle'): DiagramElement => lb(x, y, text, size, color, anchor, true);
/** 同じ大きさの箱を横に n 個ならべる。 */
const row = (n: number, x: number, y: number, w: number, h: number, color: string, fill: string, text?: string, size?: number): DiagramElement[] =>
  Array.from({ length: n }, (_, i) => bx(x + i * w, y, w, h, text, color, fill, size));
/** 線だけの四角（箱はぬりつぶされるので、わくだけ見せたいときに使う）。 */
const frame = (x: number, y: number, w: number, h: number, color: string): DiagramElement[] => [
  ln(x, y, x + w, y, color, false, 2.4), ln(x + w, y, x + w, y + h, color, false, 2.4), ln(x + w, y + h, x, y + h, color, false, 2.4), ln(x, y + h, x, y, color, false, 2.4),
];

/** 比の絵：前の数（青）と後ろの数（赤）を、同じ大きさの単位の箱でならべる。 */
const ratioBlock = (x: number, y: number, a: number, b: number, u: number, h = 18, gap = 2): DiagramElement[] => [
  ...row(a, x, y, u, h, C.blue, FILL.blue),
  ...row(b, x, y + h + gap, u, h, C.red, FILL.red),
];

