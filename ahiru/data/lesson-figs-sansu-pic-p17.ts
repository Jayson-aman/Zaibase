import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, C, FILL } from './diagram-kit';

/** 中央ぞろえの一行メッセージ。 */
const say = (y: number, text: string, color: string = C.ink, size = 13, x = 160): DiagramElement => lb(x, y, text, size, color, 'middle', true);
/** 人の名前などの短いラベル。 */
const nm = (x: number, y: number, text: string, color: string = C.ink): DiagramElement => lb(x, y, text, 15, color, 'middle', true);
/** かっこ（横）：x1〜x2 の下側に ┗━┛ をかく。 */
const brace = (x1: number, x2: number, y: number, color: string = C.red): DiagramElement[] => [ln(x1, y, x1, y + 8, color), ln(x2, y, x2, y + 8, color), ln(x1, y + 8, x2, y + 8, color)];

// ---------- 逆算の「くさり」：□ → ×3 → −8 → 25 のように、箱を矢印でつないだ図 ----------
type Chain = { n: number; w: number; y: number; h: number; x: (i: number) => number };
function chainGeo(n: number): Chain {
  const w = n === 3 ? 64 : 54;
  const gap = n === 3 ? 50 : 30;
  const x0 = (320 - (n * w + (n - 1) * gap)) / 2;
  return { n, w, y: 46, h: 40, x: (i) => x0 + i * (w + gap) };
}
const cBox = (g: Chain, i: number, text: string, color: string = C.blue, fill: string = FILL.blue, size = 15): DiagramElement => bx(g.x(i), g.y, g.w, g.h, text, color, fill, size);
/** まだ分からない箱：中は空で、名前は箱の上に書く（あとで答えを入れても字が重ならない）。 */
const cUnk = (g: Chain, i: number, name: string, color: string = C.main): DiagramElement[] => [bx(g.x(i), g.y, g.w, g.h, undefined, color, FILL.gray), lb(g.x(i) + g.w / 2, g.y - 7, name, 13, color, 'middle', true)];
const cFwd = (g: Chain, i: number, op: string): DiagramElement[] => [
  ar(g.x(i) + g.w + 2, g.y + 24, g.x(i + 1) - 2, g.y + 24, C.blue),
  lb((g.x(i) + g.w + g.x(i + 1)) / 2, g.y + 14, op, 13, C.blue, 'middle', true),
];
const cBack = (g: Chain, i: number, op: string): DiagramElement[] => [
  ar(g.x(i + 1) + g.w / 2 - 3, g.y + g.h + 14, g.x(i) + g.w / 2 + 3, g.y + g.h + 14, C.green),
  lb((g.x(i) + g.x(i + 1) + g.w) / 2, g.y + g.h + 32, op, 13, C.green, 'middle', true),
];
const cSet = (g: Chain, i: number, text: string): DiagramElement[] => [bx(g.x(i), g.y, g.w, g.h, undefined, '#FFFFFF', '#FFFFFF'), cBox(g, i, text, C.green, FILL.green, 15)];

// ---------- やりとり算の表：A・B・C の持ち金の変化 ----------
const MX = [46, 114, 182, 250]; // 4つの時点の列（左から「はじめ」「①のあと」「②のあと」「最後」）
const MW = 62;
const MY = [52, 90, 128];
const mHead = (): DiagramElement[] => ['はじめ', '①のあと', '②のあと', '最後'].map((t, i) => lb(MX[i] + MW / 2, 42, t, 11, C.gray, 'middle', true));
const mNames = (): DiagramElement[] => ['A', 'B', 'C'].map((t, j) => ci(24, MY[j] + 16, 13, t, C.main, FILL.warm, 14));
const mCol = (col: number, vals: number[], hot: number[] = []): DiagramElement[] =>
  vals.map((v, j) => bx(MX[col], MY[j], MW, 32, `${v}円`, hot.includes(j) ? C.red : C.blue, hot.includes(j) ? FILL.red : FILL.blue, 14));

// ---------- つるかめ（3種類）の面積図：たて＝ねだん、よこ＝個数 ----------
const TX = 50, TB = 190, TK = 9, TH = 0.6; // 9px=1個、0.6px=1円、底の線は y=190
const tBox = (n0: number, n1: number, price: number, text: string | undefined, color: string, fill: string, size = 12): DiagramElement =>
  bx(TX + n0 * TK, TB - price * TH, (n1 - n0) * TK, price * TH, text, color, fill, size);

