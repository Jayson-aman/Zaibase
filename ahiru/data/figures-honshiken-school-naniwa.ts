// 先頭の記号で色が決まる：= 緑 / ~ 赤 / * 紫 / ! 茶（黄） / . 灰 / それ以外は青
const tone = (s: string): [string, string, string] => {
  const c = s[0];
  if (c === '=') return [s.slice(1), C.green, FILL.green];
  if (c === '~') return [s.slice(1), C.red, FILL.red];
  if (c === '*') return [s.slice(1), C.purple, FILL.purple];
  if (c === '!') return [s.slice(1), C.main, FILL.yellow];
  if (c === '.') return [s.slice(1), C.gray, FILL.gray];
  return [s, C.blue, FILL.blue];
};
const BIG_Y = 164;
const bigBox = (s: string): E => { const [t, col, fill] = tone(s.startsWith('=') || s.startsWith('~') || s.startsWith('*') || s.startsWith('!') || s.startsWith('.') ? s : '=' + s); return bx(20, BIG_Y, 280, 30, t, col, fill, 14); };

/** 箱の列だけのスライド：title は上の見出し、rows は上から並べる箱（4つまで）、big は下の結論。 */
const R = (note: string, title: string, rows: string[], big?: string, draw: E[] = []): Slide => {
  const n = rows.length;
  const h = n >= 4 ? 26 : 28;
  const gap = n >= 4 ? 6 : 8;
  const els: E[] = [tx(160, 18, title, 12, C.ink)];
  rows.forEach((s, i) => { const [t, col, fill] = tone(s); els.push(bx(10, 30 + i * (h + gap), 300, h, t, col, fill, 12)); });
  els.push(...draw);
  if (big) els.push(bigBox(big));
  return { note, add: fresh(...els) };
};
/** 図を描くスライド：title・図（draw）・下の結論（big）。 */
const D = (note: string, title: string, draw: E[], big?: string): Slide => {
  const els: E[] = [tx(160, 18, title, 12, C.ink), ...draw];
  if (big) els.push(bigBox(big));
  return { note, add: fresh(...els) };
};
