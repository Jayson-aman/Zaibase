type Col = [string, string];

// 文字の長さ（全角＝1、半角＝0.55）。箱のはばに合わせて、自動で改行を入れる。
const uw = (s: string) => [...s].reduce((u, ch) => u + (ch.charCodeAt(0) < 256 ? 0.55 : 1), 0);
const wrap = (t: string, w: number, size: number): string => {
  const max = Math.max(4, (w - 10) / size);
  return t
    .split('\n')
    .map((line) => {
      if (uw(line) <= max) return line;
      const out: string[] = [];
      let cur = '';
      for (const ch of line) {
        if (uw(cur + ch) > max && !'、。」）』・'.includes(ch)) {
          out.push(cur);
          cur = ch;
        } else cur += ch;
      }
      out.push(cur);
      return out.join('\n');
    })
    .join('\n');
};
const bx = (x: number, y: number, w: number, h: number, text?: string, color?: string, fill?: string, size?: number): DiagramElement =>
  bx0(x, y, w, h, text == null ? text : wrap(text, w, size ?? 12), color, fill, size);
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
