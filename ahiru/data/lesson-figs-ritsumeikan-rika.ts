import type { DiagramElement, Figure } from './figures';
import { C, FILL, bx, lb, ln, ar, ci, show, fresh, band, flow, type Slide } from './diagram-kit';

const K = {
  blue: [C.blue, FILL.blue],
  green: [C.green, FILL.green],
  red: [C.red, FILL.red],
  purple: [C.purple, FILL.purple],
  yellow: [C.ink, FILL.yellow],
  warm: [C.main, FILL.warm],
} as const;
type Tone = keyof typeof K;
type Row = [string | string[], (Tone | string)?];

/** 行（箱）を上から積む。1行の箱は文字の行数に応じた高さ。 */
function rows(list: Row[], y0 = 34): DiagramElement[] {
  const out: DiagramElement[] = [];
  let y = y0;
  for (const [t, t2] of list) {
    // 2つ目が色名でなければ、次の行の文字とみなす（['1行目','2行目'] の書き方も許す）
    const isTone = typeof t2 === 'string' && t2 in K;
    const tone = isTone ? (t2 as Tone) : undefined;
    const ls = [...(Array.isArray(t) ? t : [t]), ...(typeof t2 === 'string' && !isTone ? [t2] : [])];
    const h = ls.length * 15 + 10;
    const [col, fill] = K[tone ?? 'blue'];
    out.push(bx(12, y, 296, h, ls.join('\n'), col, fill, 12));
    y += h + 6;
  }
  return out;
}

/** 見出しつきの1枚（まっさらにして行を積む） */
function card(note: string, head: string, list: Row[]): Slide {
  return { note, add: fresh(lb(12, 20, head, 12, C.blue, 'start', true), ...rows(list)) };
}

/** 下の帯（y から下）に、文字の行を書きかえる */
function foot(y: number, lines: string[], color: string = C.ink): DiagramElement[] {
  return band(y, ...lines.map((t, i) => lb(160, y + 16 + i * 17, t, 12, color, 'middle', i === 0)));
}

