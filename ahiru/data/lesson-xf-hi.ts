// 「なぜ？」の連鎖で、7枚以上。上半分に図、下の帯（band）にそのスライドのひとこと。
import type { DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, flow, stack, band, fresh } from './diagram-kit';

const cap = (t: string, color: string = C.ink, size = 12) => band(150, lb(160, 190, t, size, color, 'middle', true));
const PAL: [string, string][] = [[C.blue, FILL.blue], [C.main, FILL.warm], [C.green, FILL.green], [C.red, FILL.red], [C.purple, FILL.purple]];
/** 横長の箱を縦にならべる（矢印なし） */
const rows = (items: string[], y0 = 10, h = 30, gap = 8, size = 12, x = 15, w = 290) =>
  items.map((t, i) => bx(x, y0 + i * (h + gap), w, h, t, PAL[i % 5][0], PAL[i % 5][1], size));
/** 木（三角＋みき）。x=中心、by=根もとのy、s=大きさ */
const tree = (x: number, by: number, s: number, color: string = C.green, fill: string = FILL.green) => [
  ln(x, by, x, by + s * 0.5, C.main, false, 2),
  pg([[x, by - s * 1.6], [x - s * 0.6, by], [x + s * 0.6, by]], color, fill),
];
const chain = (items: string[], x: number, w: number, y0: number, h: number, gap: number, size = 11) =>
  stack(items, x, w, y0, { h, gap, size }).flat();

