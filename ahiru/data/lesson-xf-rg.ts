// 「なぜ？」の連鎖で、1単元7枚以上。上半分に図、下の帯（band）にそのスライドのひとこと。
import type { DiagramElement, DiagramFigure } from './figures';
import { show, bx, lb, ar, ln, ci, pg, band, fresh as freshKit, cover, C, FILL } from './diagram-kit';
import type { Slide } from './diagram-kit';

const fresh = (...els: (DiagramElement | DiagramElement[])[]) => freshKit(...els.flat());
const S = (note: string, ...p: (DiagramElement | DiagramElement[])[]): Slide => ({ note, add: p.flat() });
const cap = (t: string, color: string = C.ink, size = 12) => band(150, lb(160, 190, t, size, color, 'middle', true));
const cap2 = (t1: string, t2: string, color: string = C.ink) =>
  band(150, lb(160, 172, t1, 11, C.gray, 'middle'), lb(160, 200, t2, 12, color, 'middle', true));
const pivot = (px: number, by: number) => pg([[px, by + 10], [px - 9, by + 26], [px + 9, by + 26]], C.gray, FILL.gray);
const zig = (x: number, y1: number, y2: number, color: string = C.gray): DiagramElement[] => {
  const n = 6, w = 9, a = y1 + 5, b = y2 - 5, h = (b - a) / n;
  const out: DiagramElement[] = [ln(x, y1, x, a, color, false, 2)];
  let px = x, py = a;
  for (let i = 1; i <= n; i++) {
    const nx = i === n ? x : x + (i % 2 ? w : -w);
    const ny = a + h * i;
    out.push(ln(px, py, nx, ny, color, false, 2));
    px = nx; py = ny;
  }
  out.push(ln(x, b, x, y2, color, false, 2));
  return out;
};
const sum4 = (a: string, b: string, c: string, d: string | null, colors: string[], fills: string[], size = 11): DiagramElement[] => {
  const t = [a, b, c, d].filter((x): x is string => !!x);
  const h = t.length === 4 ? 28 : 36;
  const gap = t.length === 4 ? 6 : 10;
  return t.map((s, i) => bx(10, 8 + i * (h + gap), 300, h, s, colors[i], fills[i], size));
};

