// 行の先頭文字で色が決まる（=緑 / ~赤 / *紫 / +黄 / -灰 / それ以外は青）
const tone = (s: string): [string, string, string] => {
  const c = s[0];
  if (c === '=') return [s.slice(1), C.green, FILL.green];
  if (c === '~') return [s.slice(1), C.red, FILL.red];
  if (c === '*') return [s.slice(1), C.purple, FILL.purple];
  if (c === '+') return [s.slice(1), C.main, FILL.yellow];
  if (c === '-') return [s.slice(1), C.gray, FILL.gray];
  return [s, C.blue, FILL.blue];
};

/** 1枚のスライド。draw があれば上に図を置き、下の帯に式。なければ箱を上から並べる。 */
const S = (note: string, title: string, rows: string[], draw?: E[]): Slide => {
  const els: E[] = [];
  if (draw) {
    els.push(lb(8, 16, title, 11, C.ink, 'start', true), ...draw);
    rows.forEach((s, i) => {
      const [t, col, fill] = tone(s);
      els.push(bx(10, 148 + i * 28, 300, 24, t, col, fill, 12));
    });
  } else if (rows.length === 1 && rows[0][0] === '=') {
    const [t, col, fill] = tone(rows[0]);
    const size = t.length <= 12 ? 20 : t.length <= 16 ? 16 : 13;
    els.push(lb(160, 18, title, 12, C.ink, 'middle', true), bx(20, 80, 280, 56, t, col, fill, size));
  } else {
    els.push(lb(160, 18, title, 12, C.ink, 'middle', true));
    rows.forEach((s, i) => {
      const [t, col, fill] = tone(s);
      els.push(bx(10, 30 + i * 32, 300, 26, t, col, fill, 12));
    });
  }
  return { note, add: fresh(...els) };
};

