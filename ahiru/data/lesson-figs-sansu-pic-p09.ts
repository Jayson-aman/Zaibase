import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

const T = (x: number, y: number, t: string, color: string = C.ink, size = 12, anchor: 'start' | 'middle' | 'end' = 'start'): DiagramElement => lb(x, y, t, size, color, anchor, true);
const walls = (x1: number, x2: number, yt: number, yb: number): DiagramElement[] => [ln(x1, yt, x1, yb, C.gray, false, 3), ln(x1, yb, x2, yb, C.gray, false, 3), ln(x2, yb, x2, yt, C.gray, false, 3)];
const wat = (x: number, y: number, w: number, h: number): DiagramElement => bx(x, y, w, h, undefined, C.blue, FILL.blue);
const lay = (x: number, y: number, w: number, h: number): DiagramElement => bx(x, y, w, h, undefined, C.main, FILL.yellow);

/** 仕切りのある水そう（左20cm²・右30cm²。縦は1cm＝6px。底y=200） */
const partTank = (): DiagramElement[] => [...walls(20, 170, 100, 200), bx(78, 128, 4, 72, undefined, C.gray, FILL.gray), ar(48, 46, 48, 96, C.blue)];

/** 段差のある水そう（下30cm²・上50cm²。縦は1cm＝6px。底y=200、段差y=140、上のふちy=80） */
const stepTank = (): DiagramElement[] => [
  ln(32, 200, 32, 140, C.gray, false, 3), ln(32, 140, 14, 140, C.gray, false, 3), ln(14, 140, 14, 80, C.gray, false, 3),
  ln(32, 200, 86, 200, C.gray, false, 3),
  ln(86, 200, 86, 140, C.gray, false, 3), ln(86, 140, 104, 140, C.gray, false, 3), ln(104, 140, 104, 80, C.gray, false, 3),
  ar(59, 36, 59, 76, C.blue),
];

/** 街灯と人（棒）の影の絵。x0＝街灯の位置、gy＝地面のy、sx・sy＝1mあたりのpx、H＝街灯の高さ(m)、dx＝人の位置(m)、h＝人の高さ(m)、tip＝影の先(m) */
function lamp(o: { x0: number; gy: number; sx: number; sy: number; H: number; dx: number; h: number; tip: number; person: string }): DiagramElement[] {
  const top = o.gy - o.H * o.sy;
  const px = o.x0 + o.dx * o.sx;
  const ph = o.gy - o.h * o.sy;
  return [
    ln(10, o.gy, 312, o.gy, C.gray, false, 3),
    ln(o.x0, o.gy, o.x0, top, C.ink, false, 4), ci(o.x0, top - 5, 5, undefined, C.main, FILL.yellow),
    ln(o.x0, top, o.x0 + o.tip * o.sx, o.gy, C.main, true, 1.6),
    ln(px, o.gy, px, ph, C.blue, false, 4), ci(px, ph - 6, 6, undefined, C.blue, FILL.blue),
  ];
}

