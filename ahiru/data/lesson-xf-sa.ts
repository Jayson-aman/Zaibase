import type { DiagramFigure, DiagramElement } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, flow, band, fresh } from './diagram-kit';

/** 下の帯にひとこと（改行可）。 */
const cap = (t: string, color: string = C.ink, size = 12) => band(150, lb(160, 190, t, size, color, 'middle', true));

/** 百・十・一の位の3つの枠。 */
type Slot = { t: string; u?: string; c?: string; f?: string; s?: number };
const slots = (items: Slot[], labels: string[] = ['百の位', '十の位', '一の位'], y = 40): DiagramElement[] => {
  const out: DiagramElement[] = [];
  items.forEach((it, i) => {
    const cx = 65 + i * 95;
    out.push(lb(cx, y - 10, labels[i], 11, C.gray, 'middle'));
    out.push(bx(cx - 35, y, 70, 44, it.t, it.c ?? C.main, it.f ?? FILL.warm, it.s ?? 16));
    if (it.u) out.push(lb(cx, y + 62, it.u, 10, it.c ?? C.main, 'middle'));
  });
  return out;
};

/** 3つの箇条（まとめ用）。 */
const rows3 = (a: string, b: string, c: string): DiagramElement[] => [
  bx(15, 14, 290, 34, a, C.blue, FILL.blue, 12),
  bx(15, 56, 290, 34, b, C.green, FILL.green, 12),
  bx(15, 98, 290, 34, c, C.red, FILL.red, 12),
];

/** 分数（上に分子、下に分母）。 */
const frac = (cx: number, cy: number, n: string, d: string, size = 16, color: string = C.ink): DiagramElement[] => [
  lb(cx, cy - 10, n, size, color, 'middle', true),
  ln(cx - size * 0.7, cy, cx + size * 0.7, cy, color, false, 2),
  lb(cx, cy + 11, d, size, color, 'middle', true),
];

/** てんびん図。xl・xr は両はしの位置、xf は支点の位置。 */
const beam = (o: { xl: number; xr: number; xf: number; wl: string; wr: string; cl: string; cr: string; cf: string; y?: number }): DiagramElement[] => {
  const y = o.y ?? 100;
  const out: DiagramElement[] = [
    ln(o.xl, y, o.xr, y, C.ink, false, 3),
    ln(o.xl, y - 16, o.xl, y, C.gray),
    ln(o.xr, y - 16, o.xr, y, C.gray),
    bx(o.xl - 28, y - 44, 56, 28, o.wl, C.blue, FILL.blue, 11),
    bx(o.xr - 28, y - 44, 56, 28, o.wr, C.green, FILL.green, 11),
    pg([[o.xf, y + 2], [o.xf - 9, y + 20], [o.xf + 9, y + 20]], C.red, FILL.red),
  ];
  if (o.cl) out.push(lb(o.xl, y + 14, o.cl, 12, C.blue, 'middle', true));
  if (o.cr) out.push(lb(o.xr, y + 14, o.cr, 12, C.green, 'middle', true));
  if (o.cf) out.push(lb(o.xf, y + 32, o.cf, 12, C.red, 'middle', true));
  return out;
};

