// 社会（中学受験・歴史 近代〜現代・古代の年号）の動く図解スライド。
// キーは項目の label（買い切りの識別キーと同じ）。「なぜ？」の連鎖で、年表・略図・関係図・因果の矢印で描く。
// 画面の上半分に図、下の帯（cap）にそのスライドのひとこと、という配置にそろえてある。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, band, fresh } from './diagram-kit';

type K = 'm' | 'b' | 'g' | 'r' | 'p' | 'y' | 'k';
const PAL: Record<K, [string, string]> = {
  m: [C.main, FILL.warm],
  b: [C.blue, FILL.blue],
  g: [C.green, FILL.green],
  r: [C.red, FILL.red],
  p: [C.purple, FILL.purple],
  y: [C.main, FILL.yellow],
  k: [C.gray, FILL.gray],
};
/** 色つきの箱。 */
const bb = (k: K, x: number, y: number, w: number, h: number, t: string, s?: number): DiagramElement =>
  bx(x, y, w, h, t, PAL[k][0], PAL[k][1], s);
/** 下の帯：ひとこと（1行目は太字、2行目・3行目は灰色）。 */
const cap = (t1: string, t2?: string, k: K = 'b', t3?: string): DiagramElement[] =>
  band(
    150,
    lb(160, 172, t1, 13, PAL[k][0], 'middle', true),
    ...(t2 ? [lb(160, 194, t2, 11, C.gray, 'middle')] : []),
    ...(t3 ? [lb(160, 214, t3, 11, C.gray, 'middle')] : []),
  );
/** 帯の中に大きな箱を1つ出す。 */
const capBox = (t: string, k: K = 'g', sub?: string): DiagramElement[] =>
  band(150, bb(k, 30, 160, 260, 34, t, 14), ...(sub ? [lb(160, 216, sub, 11, C.gray, 'middle')] : []));
/** 年表の軸（横線）と、年ごとの点・年・ひとこと。 */
const axis = (y: number, xs: [number, string, string, K?][]): DiagramElement[] => [
  ln(14, y, 306, y, C.gray, false, 2),
  ...xs.flatMap(([x, yr, txt, k]) => [
    ci(x, y, 5, undefined, PAL[k ?? 'b'][0], PAL[k ?? 'b'][1]),
    lb(x, y - 12, yr, 11, PAL[k ?? 'b'][0], 'middle', true),
    lb(x, y + 18, txt, 10, C.ink, 'middle'),
  ]),
];

