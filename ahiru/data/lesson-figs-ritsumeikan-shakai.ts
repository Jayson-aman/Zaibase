// 立命館対策（高校受験 社会 12単元）の図解。キーは lessons-ritsumeikan-shakai.ts の figureId と対応。
// 画面は 320×240。各図は 状況→手がかり→理由→計算→答え→確かめ の順に8枚で見せる。
// 時事の数値：食料自給率＝2024年度カロリーベース38%・生産額ベース64%、世界遺産27件（文化22・自然5）、
// 令和7年国勢調査 総人口122,972,528人。予算・国債・最低賃金は依頼書の数値（出典の再確認は未了）。

const T = (x: number, y: number, text: string, size = 11, color: string = C.ink, anchor: 'start' | 'middle' | 'end' = 'middle', bold = false) =>
  lb(x, y, text, size, color, anchor, bold);

/** 見出し＋最大4行の文字の箱で、画面全体を組みなおす。 */
const card = (title: string, rows: string[], color: string = C.blue, fill: string = FILL.blue): DiagramElement[] =>
  fresh(
    bx(10, 8, 300, 28, title, color, fill, 13),
    ...rows.map((r, i) => bx(10, 46 + i * 46, 300, 40, r, color, FILL.warm, 11)),
  );

/** 横棒グラフ（最大5本）。label は7字まで、txt は6字まで。 */
const bars = (title: string, items: [string, number, string, string][], max: number): DiagramElement[] =>
  fresh(
    T(160, 24, title, 13, C.ink, 'middle', true),
    ...items.flatMap(([label, v, col, txt], i) => {
      const y = 46 + i * 36;
      const len = Math.max(4, Math.round((v / max) * 170));
      return [T(8, y + 14, label, 10, C.ink, 'start'), bx(84, y, len, 20, undefined, col, col), T(84 + len + 4, y + 14, txt, 10, C.ink, 'start')];
    }),
  );

/** 年表（最大6件）。名前は8字まで。下の帯（y176〜）は band() で自由に使える。 */
const tl = (title: string, events: [string, string][]): DiagramElement[] =>
  fresh(
    T(160, 22, title, 13, C.ink, 'middle', true),
    ln(14, 122, 306, 122, C.ink, false, 2),
    ...events.flatMap(([yr, nm], i) => {
      const x = Math.round(52 + i * (216 / (events.length - 1)));
      const up = i % 2 === 0;
      return [ci(x, 122, 5, undefined, C.main, C.main), T(x, up ? 106 : 146, yr, 10, C.blue, 'middle', true), T(x, up ? 93 : 159, nm, 9, C.ink, 'middle')];
    }),
  );

/** 下の帯に1つの箱を出して、前の帯を消す。 */
const note = (text: string, color: string = C.green, fill: string = FILL.green, size = 12): DiagramElement[] =>
  band(176, bx(10, 186, 300, 44, text, color, fill, size));

