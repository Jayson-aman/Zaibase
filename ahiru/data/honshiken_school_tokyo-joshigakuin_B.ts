const ex = (o: Src): string =>
  '【何を聞かれているか】\n' + o.ask +
  '\n\n【なぜそうなるのか】\n' + o.why +
  o.steps.map((s, i) => '\n\n【ステップ' + (i + 1) + '】\n' + s).join('') +
  '\n\n【答え】\n' + o.answer +
  '\n\n【確かめ】\n' + o.check +
  '\n\n【よくあるまちがい】\n' + o.miss;

const q = (subject: 'rika' | 'shakai', no: string, difficulty: 'basic' | 'standard' | 'advanced', o: Src): Question => ({
  id: 'honshiken_school_tokyo_joshigakuin_' + subject + '_' + no,
  subject,
  examType: 'chugaku',
  course: 'tokyo-joshigakuin',
  difficulty,
  ...(o.passage ? { passage: o.passage } : {}),
  question: o.question,
  ...(o.choices ? { choices: o.choices } : {}),
  answer: o.answer,
  hint: o.hint,
  explanation: ex(o),
  pitfall: o.pitfall,
  memoryTip: o.memoryTip,
  ...(o.written ? { isWritten: true, rubricPoints: o.written } : {}),
});

