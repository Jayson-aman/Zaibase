/** ビーカー。左上 (x, y)、幅 w、高さ h。液は vol(mL)×scale の高さ。ふちは上が開いた形。 */
function beaker(x: number, y: number, w: number, h: number, vol: number, scale: number, lq: readonly [string, string]): E[] {
  const lh = vol * scale;
  const out: E[] = [];
  if (lh > 0) out.push(pg([[x, y + h - lh], [x + w, y + h - lh], [x + w, y + h], [x, y + h]], lq[1], lq[0]));
  out.push(ln(x, y - 4, x, y + h, C.gray, false, 2), ln(x, y + h, x + w, y + h, C.gray, false, 2), ln(x + w, y + h, x + w, y - 4, C.gray, false, 2));
  return out;
}

/** ビーカーの液の一部（底から lo〜hi mL ぶん）を別の色で重ねる。 */
function layer(x: number, y: number, w: number, h: number, lo: number, hi: number, scale: number, lq: readonly [string, string]): E {
  const b = y + h;
  return pg([[x, b - hi * scale], [x + w, b - hi * scale], [x + w, b - lo * scale], [x, b - lo * scale]], lq[1], lq[0]);
}

/** 蒸発皿（中心 cx、上のふち y）。dots は下から順にならべる小さな粒（固体）。 */
function dish(cx: number, y: number, dots: { n: number; color: string; fill: string }[] = []): E[] {
  const out: E[] = [pg([[cx - 32, y], [cx + 32, y], [cx + 22, y + 24], [cx - 22, y + 24]], C.gray, FILL.gray), ln(cx - 12, y + 24, cx - 16, y + 32, C.gray, false, 2), ln(cx + 12, y + 24, cx + 16, y + 32, C.gray, false, 2)];
  let k = 0;
  for (const d of dots) {
    for (let i = 0; i < d.n; i++, k++) {
      const row = Math.floor(k / 5);
      const inRow = Math.min(5, dots.reduce((a, b) => a + b.n, 0) - row * 5);
      const col = k % 5;
      out.push(ci(cx + (col - (inRow - 1) / 2) * 8, y + 19 - row * 8, 3, undefined, d.color, d.fill));
    }
  }
  return out;
}

