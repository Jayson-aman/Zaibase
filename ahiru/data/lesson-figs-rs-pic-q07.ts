/** コイル（導線を巻いた形）。turns＝巻き数の見た目、core＝鉄しん。上端 y0、高さ 50。 */
function coil(x: number, y0: number, turns: number, core = false): E[] {
  const out: E[] = [];
  if (core) out.push(bx(x - 4, y0 - 6, 8, 62, undefined, C.gray, FILL.gray));
  const sp = 50 / turns;
  for (let i = 0; i < turns; i++) out.push(ln(x - 12, y0 + i * sp, x + 12, y0 + i * sp + sp * 0.7, C.main, false, 2));
  return out;
}

/** クリップ（● 1つ＝5個ぶん）を、コイルの下にぶら下げる。 */
function clips(x: number, y: number, n: number): E[] {
  const out: E[] = [];
  for (let i = 0; i < n; i++) out.push(ci(x - 12 + (i % 4) * 8, y + Math.floor(i / 4) * 7, 3, undefined, C.gray, FILL.gray));
  return out;
}

/** 豆電球（円＋×）。 */
function bulb(x: number, y: number, r = 9, color: string = C.main): E[] {
  const d = r * 0.7;
  return [ci(x, y, r, undefined, color, FILL.yellow), ln(x - d, y - d, x + d, y + d, color, false, 1.5), ln(x - d, y + d, x + d, y - d, color, false, 1.5)];
}

/** 電池1個（たて向きの導線の途中に置く記号）。長い線＋短い太い線。 */
function cellV(x: number, y: number): E[] {
  return [ln(x - 9, y - 3, x + 9, y - 3, C.ink, false, 1.5), ln(x - 5, y + 3, x + 5, y + 3, C.ink, false, 4)];
}

/** 電池を直列に n 個並べた、たて向きの導線（x、上 yTop〜下 yBot）。 */
function cellsSeries(x: number, yTop: number, yBot: number, n: number): E[] {
  const out: E[] = [];
  const mid = (yTop + yBot) / 2;
  const gap = 12;
  const ys = Array.from({ length: n }, (_, i) => mid + (i - (n - 1) / 2) * gap);
  let prev = yTop;
  for (const y of ys) {
    out.push(ln(x, prev, x, y - 3, C.ink));
    out.push(...cellV(x, y));
    prev = y + 3;
  }
  out.push(ln(x, prev, x, yBot, C.ink));
  return out;
}

/** 電池を並列に n 個（たて向きの導線を n 本ならべる）。x から右へ 14 ずつ。 */
function cellsParallel(x: number, yTop: number, yBot: number, n: number): E[] {
  const out: E[] = [];
  const mid = (yTop + yBot) / 2;
  for (let i = 0; i < n; i++) {
    const xx = x + i * 14;
    out.push(ln(xx, yTop, xx, mid - 3, C.ink), ...cellV(xx, mid), ln(xx, mid + 3, xx, yBot, C.ink));
  }
  return out;
}


/** 1つの輪になった回路。電池（直列 's'／並列 'p'）が左、はたらくもの（コイル・モーター）が上の導線の途中。 */
function loop(x0: number, y0: number, w: number, h: number, n: number, mode: 's' | 'p', load: string, loadW = 44, textSize = 11): E[] {
  const xr = x0 + w;
  const minX = x0 + (mode === 'p' ? (n - 1) * 14 : 0) + 6 + loadW / 2;
  const xc = Math.max(minX, x0 + w / 2);
  const out: E[] = mode === 's' ? cellsSeries(x0, y0, y0 + h, n) : cellsParallel(x0, y0, y0 + h, n);
  out.push(ln(x0, y0, xc - loadW / 2, y0, C.ink), ln(xc + loadW / 2, y0, xr, y0, C.ink), ln(xr, y0, xr, y0 + h, C.ink), ln(xr, y0 + h, x0, y0 + h, C.ink));
  out.push(bx(xc - loadW / 2, y0 - 8, loadW, 16, load, C.main, FILL.warm, textSize));
  return out;
}

