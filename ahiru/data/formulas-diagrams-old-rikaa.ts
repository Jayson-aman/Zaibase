const wave = (x0: number, x1: number, y: number, amp: number, periods: number, color: string): DiagramElement[] => {
  const out: DiagramElement[] = [];
  const n = Math.round(periods * 16);
  let px = x0, py = y;
  for (let i = 1; i <= n; i++) {
    const x = x0 + ((x1 - x0) * i) / n;
    const yy = y - amp * Math.sin((2 * Math.PI * periods * i) / n);
    out.push(ln(px, py, x, yy, color, false, 2));
    px = x; py = yy;
  }
  return out;
};
