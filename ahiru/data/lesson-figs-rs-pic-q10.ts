import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

type E = DiagramElement;

/** 下の説明の行（0〜4行目）。文字は前のスライドのものが消えないので、スライドごとに別の行へ足す。 */
const R = (i: number, text: string, color: string = C.ink, bold = false): E => lb(160, 160 + i * 17, text, 13, color, 'middle', bold);

/** 長方形（ぬりつぶし用。文字の検査の対象にならない）。 */
const rect = (x0: number, y0: number, x1: number, y1: number, color: string, fill: string): E =>
  pg([[x0, y0], [x1, y0], [x1, y1], [x0, y1]], color, fill);

/** ふちだけの円（まるい輪。文字をかさねても検査にかからない）。 */
const ring = (cx: number, cy: number, r: number, color: string, fill = 'none'): E => {
  const pts: [number, number][] = [];
  for (let i = 0; i < 28; i++) {
    const a = (i / 28) * Math.PI * 2;
    pts.push([Math.round((cx + r * Math.cos(a)) * 10) / 10, Math.round((cy + r * Math.sin(a)) * 10) / 10]);
  }
  return pg(pts, color, fill);
};

/** 雲（3つの丸）。 */
const cloud = (x: number, y: number, s: number, fill: string): E[] => [
  ci(x - 14 * s, y + 3 * s, 10 * s, undefined, fill, fill),
  ci(x, y - 4 * s, 13 * s, undefined, fill, fill),
  ci(x + 15 * s, y + 3 * s, 10 * s, undefined, fill, fill),
];

/** 家（地面の高さ y に立つ）。 */
