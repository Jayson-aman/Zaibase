import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

const BEAM = '#8B5A2B';
const ROWY = [160, 177, 194, 211, 228];
/** 下の文字の行（0〜4行目）。 */
const R = (i: number, text: string, color: string = C.ink): DiagramElement => lb(160, ROWY[i], text, 13, color, 'middle', true);

/** 支点（三角）と地面。 */
function pivot(px: number, y: number, hw = 11): DiagramElement[] {
  return [pg([[px - hw, y + 24], [px + hw, y + 24], [px, y + 3]], C.gray, FILL.gray), ln(px - hw - 17, y + 24, px + hw + 17, y + 24, C.gray, false, 2)];
}
/** ひもでぶらさげたおもり。 */
function weight(x: number, y: number, text: string, color: string, fill: string, w = 38, size = 12, drop = 16): DiagramElement[] {
  return [ln(x, y, x, y + drop, color), bx(x - w / 2, y + drop, w, 22, text, color, fill, size)];
}
/** 長さをあらわす線（両はしに目もり）。label は線の下（up なら上）。 */
function dim(xa: number, xb: number, y: number, text: string, color: string = C.gray, up = false): DiagramElement[] {
  return [ln(xa, y, xb, y, color), ln(xa, y - 4, xa, y + 4, color), ln(xb, y - 4, xb, y + 4, color), lb((xa + xb) / 2, up ? y - 6 : y + 14, text, 11, color, 'middle')];
}
/** 水平な棒。 */
const beam = (x0: number, x1: number, y: number): DiagramElement => ln(x0, y, x1, y, BEAM, false, 6);

/** 左はしが支点で、棒に重さがあるてこ（棒の重さ・おもり・右はしの力）。 */
function stick(L: number, stickG: string, wdCm: number, wgText: string, fText: string) {
  const k0 = 30, width = 240, by = 78;
  const k = width / L;
  const X = (cm: number) => k0 + cm * k;
  return {
    base: [beam(k0, k0 + width, by), ...pivot(k0, by, 10), lb(k0, by + 38, '支点', 11, C.gray, 'middle')],
    wt: weight(X(wdCm), by, wgText, C.blue, FILL.blue, 38, 12),
    sw: [ln(X(L / 2), by, X(L / 2), by + 42, C.purple), bx(X(L / 2) - 23, by + 42, 46, 22, `棒${stickG}`, C.purple, FILL.purple, 11)],
    f: [ar(X(L), by + 40, X(L), by + 4, C.red), bx(X(L) - 23, by + 42, 46, 22, fText, C.red, FILL.red, 11)],
    dAll: dim(X(0), X(L), 10, `${L}cm`, C.red),
    dMid: dim(X(0), X(L / 2), 30, `${L / 2}cm`, C.purple),
    dWt: dim(X(0), X(wdCm), 50, `${wdCm}cm`, C.blue),
  };
}

/** 輪軸（大きい輪と小さい輪）。 */
function wheel(cx: number, cy: number, Rr: number, r: number): DiagramElement[] {
  return [ci(cx, cy, Rr, undefined, C.main, FILL.warm), ci(cx, cy, r, undefined, C.gray, FILL.gray), ci(cx, cy, 2, undefined, C.ink, C.ink)];
}
/** 滑車の輪。 */
function pulleyRing(cx: number, cy: number, r: number, text?: string): DiagramElement[] {
  return text ? [ci(cx, cy, r, text, C.gray, FILL.gray)] : [ci(cx, cy, r, undefined, C.gray, FILL.gray), ci(cx, cy, 2, undefined, C.ink, C.ink)];
}

