// 高校受験 社会（歴史 現代・公民 憲法と人権 ほか 30 単元）の「動く図解スライド」。
// 「なぜ？」の連鎖で 7 枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, fresh, flow, stack } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=160 から）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 160, 292, 16 + 15 * n, t, c[0], c[1], size);
};
// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});
// 「なぜ？」の問い → 答え
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13): DiagramElement[] => [
  bx(12, 8, 296, 40, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 50, 160, 66, PURPLE[0]),
  bx(12, 68, 296, 80, a, c[0], c[1], aSize),
];
// 箱を矢印でつないだ横一列
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap: 14 }).flat();
// 縦に並べた箱
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 26, gap = 12): DiagramElement[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();
// 年表（横。年→出来事の箱）
const tl = (items: [string, string][], y = 24, c: Col = BLUE, h = 70, size = 10): DiagramElement[] => {
  const n = items.length;
  const w = 300 / n;
  const els: DiagramElement[] = [ln(10, y + 12, 310, y + 12, C.gray, false, 2)];
  items.forEach(([yr, t], i) => {
    const cx = 10 + w * i + w / 2;
    els.push(ci(cx, y + 12, 4, undefined, c[0], c[0]), lb(cx, y, yr, 11, c[0], 'middle', true), bx(10 + w * i + 2, y + 24, w - 4, h, t, c[0], c[1], size));
  });
  return els;
};
// 表（1行目は見出し）。colW は各列の幅。
const tbl = (rows: string[][], colW: number[], y0 = 10, h = 26, size = 11, head: Col = BLUE, body: Col = MAIN): DiagramElement[] => {
  const els: DiagramElement[] = [];
  rows.forEach((r, ri) => {
    let x = (320 - colW.reduce((a, b) => a + b, 0)) / 2;
    r.forEach((t, ci2) => {
      els.push(bx(x, y0 + ri * (h + 3), colW[ci2] - 3, h, t, ri === 0 ? head[0] : body[0], ri === 0 ? head[1] : (ci2 === 0 ? FILL.gray : body[1]), size));
      x += colW[ci2];
    });
  });
  return els;
};
// 東西・左右2つの箱を並べて見くらべる
const two = (l: string, r: string, y = 14, h = 84, lc: Col = BLUE, rc: Col = RED, size = 12): DiagramElement[] => [
  bx(10, y, 142, h, l, lc[0], lc[1], size), bx(168, y, 142, h, r, rc[0], rc[1], size),
];

