import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, band, fresh } from './diagram-kit';

type E = DiagramElement;
const eb = (y: number, t: string, color: string, fill: string, size = 14, h = 30, x = 20, w = 280): E => bx(x, y, w, h, t, color, fill, size);
const tx = (y: number, t: string, size = 12, color: string = C.gray, bold = false): E => lb(160, y, t, size, color, 'middle', bold);
const T = (top: E[], bottom: E[]): E[] => [...top, ...band(140, ...bottom)];
const F = (top: E[], bottom: E[]): E[] => fresh(...top, ...bottom);
const pr = (x: number, y: number, t: string, color: string = C.blue, fill: string = FILL.blue): E => ci(x, y, 15, t, color, fill, 13);
/** 数直線。ticks は [値, 表示] の並び。 */
const nl = (y: number, x0: number, x1: number, v0: number, v1: number, ticks: [number, string][], color: string = C.gray): E[] => {
  const px = (v: number) => x0 + ((v - v0) * (x1 - x0)) / (v1 - v0);
  return [ln(x0, y, x1, y, color, false, 2), ...ticks.flatMap(([v, t]) => [ln(px(v), y - 4, px(v), y + 4, color), lb(px(v), y + 16, t, 11, color, 'middle')])];
};
const dt = (x: number, y: number, filled: boolean, color: string = C.blue): E => ci(x, y, 5, undefined, color, filled ? color : '#FFFFFF');

