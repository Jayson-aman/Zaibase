// 「なぜ？」の連鎖で7枚以上。上に図、下の帯にそのスライドのひとこと。
import type { DiagramElement, DiagramFigure } from './figures';
import type { Slide } from './diagram-kit';
import { show, bx, lb, ar, ln, ci, pg, fresh, C, FILL } from './diagram-kit';

type K = 'b' | 'g' | 'r' | 'p' | 'y' | 'm' | 'k';
const COL: Record<K, [string, string]> = {
  b: [C.blue, FILL.blue], g: [C.green, FILL.green], r: [C.red, FILL.red], p: [C.purple, FILL.purple],
  y: [C.main, FILL.yellow], m: [C.main, FILL.warm], k: [C.gray, FILL.gray],
};
const TC: Record<K, string> = { b: C.blue, g: C.green, r: C.red, p: C.purple, y: C.main, m: C.main, k: C.gray };

/** 色つきの箱 */
const B = (x: number, y: number, w: number, h: number, t: string, k: K = 'm', size = 12): DiagramElement =>
  bx(x, y, w, h, t, COL[k][0], COL[k][1], size);
/** 文字 */
const L = (x: number, y: number, t: string, size = 12, k: K | 'ink' = 'ink', anchor: 'start' | 'middle' | 'end' = 'middle', bold = true): DiagramElement =>
  lb(x, y, t, size, k === 'ink' ? C.ink : TC[k], anchor, bold);
/** 矢印 */
const A = (x1: number, y1: number, x2: number, y2: number, k: K = 'm', dashed = false): DiagramElement =>
  ar(x1, y1, x2, y2, TC[k], dashed);
const LN = (x1: number, y1: number, x2: number, y2: number, k: K = 'k', dashed = false, w?: number): DiagramElement =>
  ln(x1, y1, x2, y2, TC[k], dashed, w);
/** 上の見出し */
const H = (t: string, k: K = 'k'): DiagramElement => L(160, 13, t, 12, k);

/** 1枚分のスライド。図をまっさらな画面に描き、下の帯にひとこと。 */
const S = (note: string, cap: string, ck: K, ...els: DiagramElement[]): Slide => ({
  note,
  add: fresh(...els, B(10, 196, 300, 36, cap, ck, 12)),
});

/** 文を、部分ごとの箱にして横にならべる（幅は字数で決め、はみ出すなら文字を小さくする）。 */
const sent = (parts: [string, K?][], y: number, size = 14, h = 28, x0 = 10, maxW = 300): DiagramElement[] => {
  const gap = 3;
  const n = parts.reduce((s, p) => s + p[0].length, 0);
  let sz = size;
  const total = () => n * sz + parts.length * 10 + (parts.length - 1) * gap;
  while (total() > maxW && sz > 9) sz -= 0.5;
  const scale = maxW / Math.max(total(), maxW);
  let x = x0 + (total() < maxW ? (maxW - total()) / 2 : 0);
  return parts.map(([t, k]) => {
    const w = (t.length * sz + 10) * scale;
    const el = B(x, y, w, h, t, k ?? 'k', sz);
    x += w + gap;
    return el;
  });
};

/** 横一列の箱を矢印でつなぐ */
const chain = (labels: string[], y: number, k: K = 'b', h = 34, size = 12, gap = 16, x0 = 8, x1 = 312): DiagramElement[] => {
  const n = labels.length;
  const w = (x1 - x0 - gap * (n - 1)) / n;
  return labels.flatMap((t, i) => {
    const x = x0 + i * (w + gap);
    const out: DiagramElement[] = [];
    if (i > 0) out.push(A(x - gap + 1, y + h / 2, x - 1, y + h / 2, k));
    out.push(B(x, y, w, h, t, k, size));
    return out;
  });
};

/** 縦にならべた箱を下向きの矢印でつなぐ */
const vstack = (labels: string[], y0: number, k: K = 'b', h = 28, gap = 10, size = 12, x = 10, w = 300): DiagramElement[] =>
  labels.flatMap((t, i) => {
    const y = y0 + i * (h + gap);
    const out: DiagramElement[] = [];
    if (i > 0) out.push(A(x + w / 2, y - gap + 1, x + w / 2, y - 1, k));
    out.push(B(x, y, w, h, t, k, size));
    return out;
  });

/** 左→右の対応を縦にならべる */
const pairs = (items: [string, string][], y0: number, o?: { h?: number; gap?: number; lw?: number; kl?: K; kr?: K; sl?: number; sr?: number }): DiagramElement[] => {
  const h = o?.h ?? 26, gap = o?.gap ?? 6, lw = o?.lw ?? 120, kl = o?.kl ?? 'b', kr = o?.kr ?? 'g';
  const rx = 10 + lw + 28;
  return items.flatMap(([a, b], i) => {
    const y = y0 + i * (h + gap);
    return [B(10, y, lw, h, a, kl, o?.sl ?? 12), A(10 + lw + 1, y + h / 2, rx - 1, y + h / 2, 'k'), B(rx, y, 310 - rx, h, b, kr, o?.sr ?? 12)];
  });
};

/** 横にならんだ等分の箱 */
const cols = (labels: string[], y: number, h: number, k: K | K[], size = 12, x0 = 10, x1 = 310, gap = 6): DiagramElement[] => {
  const n = labels.length;
  const w = (x1 - x0 - gap * (n - 1)) / n;
  return labels.map((t, i) => B(x0 + i * (w + gap), y, w, h, t, Array.isArray(k) ? k[i % k.length] : k, size));
};

/** 表（見出し行＋本文行） */
const tbl = (head: string[], rows: string[][], x: number, y: number, cw: number[], rh = 24, size = 11, k: K = 'b'): DiagramElement[] => {
  const out: DiagramElement[] = [];
  let cx = x;
  head.forEach((t, i) => { out.push(B(cx, y, cw[i], rh, t, k, size)); cx += cw[i]; });
  rows.forEach((r, j) => {
    let xx = x;
    r.forEach((t, i) => { out.push(bx(xx, y + rh * (j + 1), cw[i], rh, t, C.gray, '#FFFFFF', size)); xx += cw[i]; });
  });
  return out;
};


/** 番号つきの小さな丸（筆順など） */
const N = (x: number, y: number, n: number | string, k: K = 'r'): DiagramElement => ci(x, y, 7, String(n), TC[k], '#FFFFFF', 9);
/** 太い線（字の画のつもり） */
const ST = (x1: number, y1: number, x2: number, y2: number, k: K = 'k'): DiagramElement => ln(x1, y1, x2, y2, TC[k], false, 4);

const FIG: Record<string, DiagramFigure> = {};
const SEC: Record<string, string> = {};
const reg = (id: string, sec: number, slides: Slide[], caption: string) => {
  FIG['xf_' + id] = show(slides, caption);
  SEC[id + '#' + sec] = 'xf_' + id;
};

