const rad = (d: number) => (d * Math.PI) / 180;
const r1 = (n: number) => Math.round(n * 10) / 10;
/** 中心(cx,cy)・半径r・角度deg（数学の向き）の点 */
const P = (cx: number, cy: number, r: number, deg: number): Pt => [r1(cx + r * Math.cos(rad(deg))), r1(cy - r * Math.sin(rad(deg)))];
const mid = (a: Pt, b: Pt): Pt => [r1((a[0] + b[0]) / 2), r1((a[1] + b[1]) / 2)];
/** 円（白ぬり） */
const circ = (c: Pt, r: number, col: string = C.blue): E => ci(c[0], c[1], r, undefined, col, '#FFFFFF');
const seg = (a: Pt, b: Pt, col: string = C.ink, dashed = false, w = 1.6): E => ln(a[0], a[1], b[0], b[1], col, dashed, w);
/** 点と名前 */
const dot = (p: Pt, name: string, dx: number, dy: number, col: string = C.ink): E[] => [ci(p[0], p[1], 2.4, undefined, col, col), lb(p[0] + dx, p[1] + dy, name, 12, col, 'middle', true)];
const tag = (x: number, y: number, t: string, col: string = C.ink, size = 11): E => lb(x, y, t, size, col, 'middle', true);
/** 円弧（太い折れ線） */
const arc = (c: Pt, r: number, a1: number, a2: number, col: string = C.red, w = 3.4): E[] => {
  const out: E[] = [];
  const n = Math.max(2, Math.ceil(Math.abs(a2 - a1) / 6));
  let prev = P(c[0], c[1], r, a1);
  for (let i = 1; i <= n; i++) {
    const q = P(c[0], c[1], r, a1 + ((a2 - a1) * i) / n);
    out.push(seg(prev, q, col, false, w));
    prev = q;
  }
  return out;
};
const dirDeg = (v: Pt, p: Pt) => (Math.atan2(-(p[1] - v[1]), p[0] - v[0]) * 180) / Math.PI;
/** 頂点vで、辺va と vb がつくる角のしるし（小さいほうの角）。label があれば内側に数値 */
const ang = (v: Pt, a: Pt, b: Pt, r = 14, col: string = C.red, label?: string, lr = 0, size = 10): E[] => {
  let a1 = dirDeg(v, a);
  let a2 = dirDeg(v, b);
  let d = (((a2 - a1) % 360) + 360) % 360;
  if (d > 180) { const t = a1; a1 = a2; a2 = t; d = 360 - d; }
  const els: E[] = [sc(v[0], v[1], r, r1(a1), r1(a1 + d), col, TINT[col] ?? 'rgba(0,0,0,0.2)')];
  if (label) {
    const q = P(v[0], v[1], lr || r + 11, a1 + d / 2);
    els.push(lb(q[0], q[1] + 3, label, size, col, 'middle', true));
  }
  return els;
};
/** 直線 a→b を延ばして、円(c,r)と交わる「遠いほうの」点 */
const farHit = (a: Pt, b: Pt, c: Pt, r: number): Pt => {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const fx = a[0] - c[0], fy = a[1] - c[1];
  const A = dx * dx + dy * dy, B = 2 * (fx * dx + fy * dy), Cc = fx * fx + fy * fy - r * r;
  const D = Math.sqrt(Math.max(0, B * B - 4 * A * Cc));
  const t = (-B + D) / (2 * A);
  return [r1(a[0] + t * dx), r1(a[1] + t * dy)];
};
/** 直角のしるし（頂点v、辺方向 a と b） */
const rt = (v: Pt, a: Pt, b: Pt, s = 8): E => {
  const ua: Pt = [(a[0] - v[0]) / Math.hypot(a[0] - v[0], a[1] - v[1]), (a[1] - v[1]) / Math.hypot(a[0] - v[0], a[1] - v[1])];
  const ub: Pt = [(b[0] - v[0]) / Math.hypot(b[0] - v[0], b[1] - v[1]), (b[1] - v[1]) / Math.hypot(b[0] - v[0], b[1] - v[1])];
  const p1: Pt = [v[0] + ua[0] * s, v[1] + ua[1] * s];
  const p2: Pt = [v[0] + (ua[0] + ub[0]) * s, v[1] + (ua[1] + ub[1]) * s];
  const p3: Pt = [v[0] + ub[0] * s, v[1] + ub[1] * s];
  return pg([v, p1, p2, p3], C.gray, 'rgba(110,100,92,0.18)');
};

/** 下の帯のひとこと（前の帯はおおいかくす） */
const cap = (t: string, c: Col = BLUE, size = 12): E[] => {
  const n = t.split('\n').length;
  return band(158, bx(10, 164, 300, 14 + 16 * n, t, c[0], c[1], size));
};
/** 図（累積）＋下の帯 */
const G = (note: string, els: E[], capText: string, c: Col = BLUE, size = 12) => ({ note, add: [...els, ...cap(capText, c, size)] });
/** まっさらにして描き直す */
const F = (note: string, els: E[], capText: string, c: Col = BLUE, size = 12) => ({ note, add: [...fresh(...els), ...cap(capText, c, size)] });
/** 「なぜ？」の問い→答え（上半分） */
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13): E[] => [
  bx(10, 8, 300, 38, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 48, 160, 62, PURPLE[0]),
  bx(10, 64, 300, 82, a, c[0], c[1], aSize),
];
/** 右パネルの箱（x=168〜） */
const rp = (y: number, h: number, t: string, c: Col = MAIN, size = 11, x = 166, w = 146): E => bx(x, y, w, h, t, c[0], c[1], size);

/** 右パネルをいったん消して置きかえる */
const RP = (...els: E[]): E[] => [cover(162, 2, 158, 154), ...els];
/** 点pから直線ab におろした垂線の足 */
const foot = (p: Pt, a: Pt, b: Pt): Pt => {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const t = ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy);
  return [r1(a[0] + t * dx), r1(a[1] + t * dy)];
};
/** 斜投影の直方体。前面の左上(x,y)・幅w・高さh、奥へ(dx,-dy)。かくれ線は点線。f=前面[左上,右上,右下,左下]、b=奥面の同じ順 */
const cuboid = (x: number, y: number, w: number, h: number, dx: number, dy: number, col: string = C.ink): { els: E[]; f: Pt[]; b: Pt[] } => {
  const f: Pt[] = [[x, y], [x + w, y], [x + w, y + h], [x, y + h]];
  const b: Pt[] = f.map((p) => [p[0] + dx, p[1] - dy] as Pt);
  const els: E[] = [
    seg(f[0], f[1], col), seg(f[1], f[2], col), seg(f[2], f[3], col), seg(f[3], f[0], col),
    seg(b[0], b[1], col), seg(b[1], b[2], col), seg(f[0], b[0], col), seg(f[1], b[1], col), seg(f[2], b[2], col),
    seg(b[3], b[0], col, true, 1.2), seg(b[3], b[2], col, true, 1.2), seg(f[3], b[3], col, true, 1.2),
  ];
  return { els, f, b };
};
