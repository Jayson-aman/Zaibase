  o.steps.map((s, i) => `【ステップ${i + 1}】\n${s}`).join('\n\n') +
  `\n\n【答え】\n${o.ans}\n\n【確かめ】\n${o.check}\n\n【よくあるまちがい】\n${o.miss}`;

