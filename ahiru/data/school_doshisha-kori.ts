type Subj = 'sansu' | 'kokugo' | 'rika' | 'shakai';
type Diff = 'basic' | 'standard' | 'advanced';

type Spec = {
  id: string;
  subj: Subj;
  diff: Diff;
  q: string;
  passage?: string;
  choices?: string[];
  answer: string;
  hint: string;
  ask: string;
  why: string;
  steps: string[];
  check: string;
  mistake: string;
  pitfall: string;
  tip: string;
};

function mk(s: Spec): Question {
  const steps = s.steps.map((t, i) => '【ステップ' + (i + 1) + '】' + t).join('\n');
  const explanation =
    '【何を聞かれているか】' + s.ask + '\n' +
    '【なぜそうなるのか】' + s.why + '\n' +
    steps + '\n' +
    '【答え】' + s.answer + '\n' +
    '【たしかめ】' + s.check + '\n' +
    '【よくあるまちがい】' + s.mistake;
  const q: Question = {
    id: s.id,
    subject: s.subj,
    difficulty: s.diff,
    course: 'doshisha-kori',
    examType: 'chugaku',
    question: s.q,
    answer: s.answer,
    hint: s.hint,
    explanation,
    pitfall: s.pitfall,
    memoryTip: s.tip,
  };
  if (s.choices) q.choices = s.choices;
  if (s.passage) q.passage = s.passage;
  return q;
}

