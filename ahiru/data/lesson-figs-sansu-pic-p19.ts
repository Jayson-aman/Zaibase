/** 正の字を n 画ぶん描く（24×24 の枠、左上が x,y）。 */
function seiji(x: number, y: number, n: number, color: string): DiagramElement[] {
  const strokes: [number, number, number, number][] = [
    [0, 0, 24, 0],
    [12, 0, 12, 24],
    [12, 11, 24, 11],
    [4, 11, 4, 24],
    [0, 24, 24, 24],
  ];
  return strokes.slice(0, n).map(([a, b, c, d]) => ln(x + a, y + b, x + c, y + d, color, false, 3));
}

