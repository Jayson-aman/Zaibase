import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, C, FILL } from './diagram-kit';

type E = DiagramElement;
const L = (y: number, text: string, color: string = C.ink, size = 13, anchor: 'start' | 'middle' | 'end' = 'middle', x = 160): E => lb(x, y, text, size, color, anchor, true);

/** 2本の線分図（共通の部分＋ちがう部分の個数）。 */
function twoBars(o: { y1: number; y2: number; cw: number; uw: number; n1: number; n2: number; common: string; cwText?: boolean }) {
  const x0 = 20, h = 26, ux = x0 + o.cw;
  const units = (n: number, y: number, t: string | undefined, color: string, fill: string): E[] =>
    Array.from({ length: n }, (_, i) => bx(ux + i * o.uw, y, o.uw, h, t, i >= o.n1 ? C.red : color, i >= o.n1 ? FILL.red : fill, o.uw < 24 ? 10 : 11));
  return {
    end1: ux + o.uw * o.n1,
    end2: ux + o.uw * o.n2,
    whole1: bx(x0, o.y1, o.cw + o.uw * o.n1, h, undefined, C.blue, FILL.blue),
    whole2: bx(x0, o.y2, o.cw + o.uw * o.n2, h, undefined, C.green, FILL.green),
    common1: (t?: string, color: string = C.main, fill: string = FILL.yellow) => bx(x0, o.y1, o.cw, h, t, color, fill, 12),
    common2: (t?: string, color: string = C.main, fill: string = FILL.yellow) => bx(x0, o.y2, o.cw, h, t, color, fill, 12),
    units1: (t?: string) => units(o.n1, o.y1, t, C.blue, FILL.blue),
    units2: (t?: string) => units(o.n2, o.y2, t, C.green, FILL.green),
    extra: () => bx(ux + o.n1 * o.uw, o.y2, (o.n2 - o.n1) * o.uw, h, undefined, C.red, FILL.red),
  };
}

/** 子ども（k）・大人（o）の人数を、1人1箱で並べる。 */
const people = (x: number, y: number, pat: string, w = 17, h = 20, size = 10): E[] =>
  [...pat].map((c, i) => bx(x + i * w, y, w, h, c === 'k' ? '子' : '大', c === 'k' ? C.green : C.blue, c === 'k' ? FILL.green : FILL.blue, size));

/** つるかめ算の面積図（たて＝1つあたり、よこ＝個数、面積＝合計）。 */
function tsuru(g: { N: number; lo: number; hi: number; extra: number; baseText: string; loLab: string; hiLab: string; diffLab: string; xLab: string }) {
  const X0 = 40, W = 228, baseY = 190, HI = 88;
  const loH = (HI * g.lo) / g.hi;
  const sh = HI - loH;
  const n = g.extra / (g.hi - g.lo);
  const sw = (W * n) / g.N;
  const sx = X0 + W - sw;
  return {
    base: bx(X0, baseY - loH, W, loH, g.baseText, C.blue, FILL.blue, 12),
    axis: [ln(X0, 198, X0 + W, 198, C.gray), lb(X0 + W / 2, 213, g.xLab, 11, C.gray, 'middle')],
    loLab: lb(36, baseY - loH / 2 + 4, g.loLab, 11, C.gray, 'end'),
    hiLab: [ln(X0, baseY - HI, sx, baseY - HI, C.gray, true), lb(36, baseY - HI + 4, g.hiLab, 11, C.gray, 'end')],
    stripBlank: bx(sx, baseY - HI, sw, sh, undefined, C.red, FILL.red),
    stripAmount: (t: string) => lb(sx + sw / 2, baseY - HI - 6, t, 12, C.red, 'middle', true),
    stripText: (t: string) => bx(sx, baseY - HI, sw, sh, t, C.red, FILL.red, 11),
    tate: [ar(280, baseY - loH, 280, baseY - HI, C.red), ar(280, baseY - HI, 280, baseY - loH, C.red), lb(284, baseY - loH - sh / 2 + 4, g.diffLab, 12, C.red, 'start', true)],
  };
}

