// 雨温図（気温の折れ線と降水量の棒を、左右2つのパネルに分けて描く。1・4・7・10月のみ）
const climate = (temps: number[], rains: number[], maxR: number): DiagramElement[] => {
  const out: DiagramElement[] = [];
  const months = ['1月', '4月', '7月', '10月'];
  // 左：気温（0〜30℃）
  out.push(lb(82, 16, '月平均気温（℃）', 11, C.red, 'middle', true));
  out.push(ln(14, 122, 150, 122, C.ink, false, 1.5));
  const px = (i: number) => 31 + 34 * i;
  const py = (t: number) => 122 - t * 2.6;
  temps.forEach((t, i) => {
    if (i > 0) out.push(ln(px(i - 1), py(temps[i - 1]), px(i), py(t), C.red, false, 2));
  });
  temps.forEach((t, i) => {
    out.push(ci(px(i), py(t), 3.5, undefined, C.red, FILL.red));
    out.push(lb(px(i), py(t) - 8, String(t), 10, C.red, 'middle', true));
    out.push(lb(px(i), 136, months[i], 10, C.ink, 'middle'));
  });
  // 右：降水量
  out.push(lb(238, 16, '月降水量（mm）', 11, C.blue, 'middle', true));
  out.push(ln(170, 122, 306, 122, C.ink, false, 1.5));
  rains.forEach((r, i) => {
    const cx = 187 + 34 * i;
    const h = (r / maxR) * 84;
    out.push(bx(cx - 11, 122 - h, 22, h, undefined, C.blue, FILL.blue));
    out.push(lb(cx, 122 - h - 4, String(r), 10, C.blue, 'middle', true));
    out.push(lb(cx, 136, months[i], 10, C.ink, 'middle'));
  });
  return out;
};

