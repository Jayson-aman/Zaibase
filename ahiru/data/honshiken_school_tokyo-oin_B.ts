const mk = (subject: 'rika' | 'shakai') => (s: Spec): Question => {
  const written = !!s.rubric;
  const len = [...s.a].length;
  const ans = written ? `${s.a}（${len}字）` : s.a;
  const explanation =
    `【何を聞かれているか】${s.p.what}\n【なぜそうなるのか】${s.p.why}\n` +
    s.p.steps.map((t, i) => `【ステップ${i + 1}】${t}`).join('\n') +
    `\n【答え】${ans}\n【確かめ】${s.p.check.replace('{N}', String(len))}\n【よくあるまちがい】${s.p.mistake}`;
  return {
    id: `honshiken_school_tokyo_oin_${subject}_${s.n}`,
    subject,
    examType: 'chugaku',
    course: 'tokyo-oin',
    difficulty: s.d,
    question: s.q,
    ...(s.fd ? { figureDescription: s.fd } : {}),
    ...(s.choices ? { choices: s.choices } : {}),
    answer: s.a,
    hint: s.h,
    explanation,
    pitfall: s.pit,
    memoryTip: s.tip,
    ...(written ? { isWritten: true, rubricPoints: s.rubric } : {}),
  };
};
