// 「なぜ？」の連鎖で 7 枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, sc, show, fresh, cover, flow, stack, dots } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=160 から）に、そのスライドのひとこと。\n で改行できる。
const capBox = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 164, 292, 14 + 15 * n, t, c[0], c[1], size);
};
// 前の帯をかくして、新しい帯を出す（図はそのまま足していく）
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: [...top, cover(0, 158, 320, 82), capBox(capText, c, size)],
});
// まっさらな図に切りかえる
const F = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: [cover(0, 0, 320, 240), ...top, capBox(capText, c, size)],
});
// 「なぜ？」の問い → 答え
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13, h = 80): DiagramElement[] => [
  bx(12, 8, 296, 38, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 48, 160, 62, PURPLE[0]),
  bx(12, 64, 296, h, a, c[0], c[1], aSize),
];
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap: 14 }).flat();
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 26, gap = 12): DiagramElement[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();
const pt = (x: number, y: number, name: string, color: string = C.ink, dx = 0, dy = -10): DiagramElement[] => [
  ci(x, y, 3.5, undefined, color, color), lb(x + dx, y + dy, name, 11, color, 'middle', true),
];

const FIG: Record<string, DiagramFigure> = {};
const SEC: Record<string, string> = {};
const reg = (id: string, secs: number[], fig: DiagramFigure) => {
  FIG['xf_' + id] = fig;
  for (const s of secs) SEC[id + '#' + s] = 'xf_' + id;
};

