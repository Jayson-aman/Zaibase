// 新傾向の単元（ntch）の動く図解スライド。中学受験の社会。各8枚。
// 「問→答→では、なぜ？→答…→確かめ」の連鎖。
// 前のスライドの文字は消えない前提で検査されるので、1枚ごとに新しい箱を、空いている場所へ足していく。
// 画面は 4段×2列の8マス。順番に、ジグザグに矢印でつなぐ（0→1 は右、1→2 は下、2→3 は左…）。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, ar, show } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];

const BW = 150;
const BH = 50;
const XS = [4, 166];
const YS = [4, 64, 124, 184];
// 8マスの位置（列, 段）。0→1→2→…とジグザグにたどる
const SLOTS: [number, number][] = [
  [0, 0], [1, 0], [1, 1], [0, 1], [0, 2], [1, 2], [1, 3], [0, 3],
];

type Cell = { note: string; text: string; color: Col };

// 8つのマスから、動く図解を組み立てる
function snake(cells: Cell[], caption: string): DiagramFigure {
  const slides = cells.map((cell, i) => {
    const [c, r] = SLOTS[i];
    const x = XS[c];
    const y = YS[r];
    const add: DiagramElement[] = [];
    if (i > 0) {
      const [pc, pr] = SLOTS[i - 1];
      const px = XS[pc];
      const py = YS[pr];
      if (pr === r) {
        // 横にならんでいる：となりの端どうしを結ぶ
        if (c > pc) add.push(ar(px + BW + 1, py + BH / 2, x - 1, y + BH / 2, cell.color[0]));
        else add.push(ar(px - 1, py + BH / 2, x + BW + 1, y + BH / 2, cell.color[0]));
      } else {
        add.push(ar(px + BW / 2, py + BH + 1, x + BW / 2, y - 1, cell.color[0]));
      }
    }
    add.push(bx(x, y, BW, BH, cell.text, cell.color[0], cell.color[1], 11));
    return { note: cell.note, add };
  });
  return show(slides, caption);
}

