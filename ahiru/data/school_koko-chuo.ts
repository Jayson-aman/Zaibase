type Ex = { choices?: string[]; passage?: string };

function S(
  id: string, _d: Diff, q: string, answer: string, hint: string,
  ask: string, why: string, steps: string[], check: string,
  mistake: string, pitfall: string, tip: string,
): Spec {
  const subj = id.split('_')[1] as Subj;
  const e: Ex = EX[id] || {};
  return {
    id, subj, diff: DIFF[id.replace('kchuo_', '')] || 'standard', q, answer, hint, ask, why, steps, check, mistake, pitfall, tip,
    choices: e.choices, passage: e.passage,
  };
}

function mk(s: Spec): Question {
  const steps = s.steps.map((t, i) => '【ステップ' + (i + 1) + '】' + t).join('\n');
  const explanation =
    '【何を聞かれているか】' + s.ask + '\n' +
    '【なぜそうなるのか】' + s.why + '\n' +
    steps + '\n' +
    '【答え】' + s.answer + '\n' +
    '【たしかめ】' + s.check + '\n' +
    '【よくあるまちがい】' + s.mistake;
  const q: Question = {
    id: s.id,
    subject: s.subj,
    difficulty: s.diff,
    course: 'koko-chuo',
    examType: 'koko',
    question: s.q,
    answer: s.answer,
    hint: s.hint,
    explanation,
    pitfall: s.pitfall,
    memoryTip: s.tip,
  };
  if (s.choices) q.choices = s.choices;
  if (s.passage) q.passage = s.passage;
  return q;
}

