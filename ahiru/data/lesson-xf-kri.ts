const cap = (t: string, color: string = C.ink, size = 12) => band(150, lb(160, 190, t, size, color, 'middle', true));
const sl = (note: string, c: string, cc: string, ...els: DiagramElement[]): Slide => ({ note, add: fresh(...els, ...cap(c, cc)) });
const AX = (x0 = 50, y0 = 135, x1 = 300, y1 = 12, xl = '', yl = ''): DiagramElement[] => [
  ar(x0, y0, x1, y0, C.gray), ar(x0, y0, x0, y1, C.gray),
  ...(xl ? [lb(x1 - 12, y0 + 9, xl, 10, C.gray, 'end')] : []),
  ...(yl ? [lb(x0 + 4, y1 + 2, yl, 10, C.gray, 'start')] : []),
];

/** 箱を横に並べて矢印でつなぐ（箱ごとに色を変えられる）。 */
const rowf = (labels: string[], y: number, h: number, cols: string[], fills: string[], size = 11, pad = 8, gap = 12): DiagramElement[] => {
  const n = labels.length;
  const w = (320 - pad * 2 - gap * (n - 1)) / n;
  const out: DiagramElement[] = [];
  labels.forEach((t, i) => {
    const x = pad + i * (w + gap);
    if (i > 0) out.push(ar(x - gap + 1, y + h / 2, x - 1, y + h / 2, C.gray));
    out.push(bx(x, y, w, h, t, cols[i], fills[i], size));
  });
  return out;
};
/** ばね（ジグザグの線）。x を中心に y0 から y1 まで。 */
const zig = (x: number, y0: number, y1: number, n = 6, amp = 8, color: string = C.gray): DiagramElement[] => {
  const out: DiagramElement[] = [];
  const step = (y1 - y0) / (n * 2);
  let px = x, py = y0;
  for (let i = 1; i <= n * 2; i++) {
    const nx = x + (i % 2 === 1 ? amp : -amp), ny = y0 + step * i;
    out.push(ln(px, py, i === n * 2 ? x : nx, ny, color, false, 2));
    px = nx; py = ny;
  }
  return out;
};
