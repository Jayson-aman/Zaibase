// 中学受験 英語（長文読解・英作文）単元の動く図解スライド（図のなかった単元に1つずつ）。
// 「なぜ？」の連鎖で7枚以上。各スライドは画面ぜんたいを作りかえる（fresh）。下のほうにそのスライドのひとこと。
import type { DiagramFigure } from './figures';
import { show, bx, lb, ar, ln, fresh, C, FILL } from './diagram-kit';

type K = 'blue' | 'green' | 'red' | 'purple' | 'main' | 'gray';
const FL: Record<K, string> = { blue: FILL.blue, green: FILL.green, red: FILL.red, purple: FILL.purple, main: FILL.warm, gray: FILL.gray };
const b = (x: number, y: number, w: number, h: number, t: string, k: K = 'main', s = 12) => bx(x, y, w, h, t, C[k], FL[k], s);
const tx = (x: number, y: number, t: string, k: K | 'ink' = 'ink', s = 11, a: 'start' | 'middle' | 'end' = 'middle', bold = false) =>
  lb(x, y, t, s, k === 'ink' ? C.ink : C[k], a, bold);
const hd = (t: string, k: K | 'ink' = 'ink') => lb(160, 14, t, 12, k === 'ink' ? C.ink : C[k], 'middle', true);
const cap = (t: string, k: K | 'ink' = 'ink') => lb(160, 220, t, 12, k === 'ink' ? C.ink : C[k], 'middle', true);
const sl = (note: string, ...els: ReturnType<typeof bx>[]) => ({ note, add: fresh(...els) });
const units = (s: string) => [...s].reduce((u, ch) => u + (ch.charCodeAt(0) < 256 ? 0.55 : 1), 0);
/** 1行に、ことばの長さに合わせた幅の箱を並べる（英文を切り分けて見せる）。 */
const chain = (y: number, items: [string, K][], h = 28, s = 10, x0 = 8, total = 304, gap = 3) => {
  const wt = items.map(([t]) => units(t) + 1.2);
  const sum = wt.reduce((a, c) => a + c, 0);
  const avail = total - gap * (items.length - 1);
  let x = x0;
  return items.map(([t, k], i) => {
    const w = (wt[i] / sum) * avail;
    const e = b(x, y, w, h, t, k, s);
    x += w + gap;
    return e;
  });
};
/** 縦に箱を並べ、間を矢印でつなぐ。 */
const col = (items: [string, K][], x: number, y0: number, w: number, h: number, gap: number, s = 12) =>
  items.flatMap(([t, k], i) => {
    const y = y0 + i * (h + gap);
    return [...(i > 0 ? [ar(x + w / 2, y - gap + 1, x + w / 2, y - 1, C[k])] : []), b(x, y, w, h, t, k, s)];
  });
/** 左に見出し、右に内容の表。 */
const rows = (items: [string, string][], y0: number, o?: { wl?: number; wr?: number; h?: number; gap?: number; kl?: K; kr?: K; s?: number; x?: number }) => {
  const x = o?.x ?? 8, wl = o?.wl ?? 96, wr = o?.wr ?? 200, h = o?.h ?? 28, gap = o?.gap ?? 6, s = o?.s ?? 11;
  return items.flatMap(([a, c], i) => {
    const y = y0 + i * (h + gap);
    return [b(x, y, wl, h, a, o?.kl ?? 'blue', s), b(x + wl + 6, y, wr, h, c, o?.kr ?? 'main', s)];
  });
};
void ln;

