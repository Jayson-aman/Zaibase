// 数列・規則性（sext08 / lf_ext08）とつるかめ算（sext09 / lf_ext09）の図。座標は 320×240 の内部座標。
import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, flow, C, FILL, type Slide } from './diagram-kit';

/** 太い枠（強調用）。 */
const frame = (x: number, y: number, w: number, h: number, color: string): DiagramElement[] => [
  ln(x, y, x + w, y, color, false, 3), ln(x + w, y, x + w, y + h, color, false, 3), ln(x + w, y + h, x, y + h, color, false, 3), ln(x, y + h, x, y, color, false, 3),
];
/** 点線の枠。 */
const dframe = (x: number, y: number, w: number, h: number, color: string): DiagramElement[] => [
  ln(x, y, x + w, y, color, true, 2), ln(x + w, y, x + w, y + h, color, true, 2), ln(x + w, y + h, x, y + h, color, true, 2), ln(x, y + h, x, y, color, true, 2),
];
/** 同じ大きさの箱を横に並べる。 */
const boxes = (vals: string[], x0: number, y: number, bw: number, gap: number, h: number, color: string, fill: string, size = 13): DiagramElement[] =>
  vals.map((t, i) => bx(x0 + i * (bw + gap), y, bw, h, t, color, fill, size));
/** 箱のとなりどうしの差（階差）を、矢印とラベルで示す。 */
const jumpMarks = (diffs: (number | string)[], x0: number, bw: number, gap: number, ya: number, yl: number, color: string, size = 12): DiagramElement[] =>
  diffs.flatMap((d, i) => [ar(x0 + i * (bw + gap) + bw - 2, ya, x0 + (i + 1) * (bw + gap) + 2, ya, color), lb(x0 + i * (bw + gap) + bw + gap / 2, yl, `+${d}`, size, color, 'middle', true)]);
/** 箱の上を、ひとつ先の箱へ向かう矢印（かけ算や次の項）。 */
const topArrows = (n: number, x0: number, bw: number, gap: number, y: number, text: string, color: string): DiagramElement[] =>
  Array.from({ length: n - 1 }, (_, i) => i).flatMap((i) => [ar(x0 + i * (bw + gap) + bw / 2, y, x0 + (i + 1) * (bw + gap) + bw / 2, y, color), lb(x0 + i * (bw + gap) + bw + gap / 2, y - 8, text, 11, color, 'middle', true)]);
/** 正方形ならびの点（i＝よこ、j＝たて）。 */
const sqDots = (pred: (i: number, j: number) => boolean, color: string, fill: string): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (let j = 0; j < 8; j++) for (let i = 0; i < 8; i++) if (pred(i, j)) out.push(ci(28 + 14 * i, 34 + 14 * j, 5, undefined, color, fill));
  return out;
};
/** 三角形・長方形にならべた点。 */
const gridDots = (x0: number, y0: number, gap: number, r: number, cells: [number, number][], color: string, fill: string): DiagramElement[] =>
  cells.map(([i, j]) => ci(x0 + i * gap, y0 + j * gap, r, undefined, color, fill));

/** つるかめ算の面積図（たて＝1つあたりの数、よこ＝個数、面積＝合計）。 */
type KameCfg = { N: number; a: number; b: number; T: number; s: number; sm: string; bg: string; cnt: string; u: string; ta: (v: number) => string; notes: string[]; cap: string };
function kame(c: KameCfg) {
  const x0 = 60, W = 200, y0 = 170, pw = W / c.N, d = c.b - c.a, base = c.a * c.N, diff = c.T - base, k = diff / d;
  if (!Number.isInteger(k)) throw new Error('kame: 整数で解けない');
  const xs = x0 + (c.N - k) * pw, hs = c.a * c.s, hb = c.b * c.s;
  const slides: Slide[] = [
    { note: c.notes[0],
      add: [ln(x0, y0, x0 + W, y0, C.ink, false, 2), ln(x0, 34, x0 + W, 34, C.gray), lb(x0 + W / 2, 26, `よこ 合計${c.N}${c.cnt}`, 12, C.ink, 'middle', true),
        bx(x0, y0 - hs, W, hs, `全部${c.sm}と仮定`, C.blue, FILL.blue, 12), lb(x0 - 4, y0 - hs / 2 + 4, c.ta(c.a), 11, C.blue, 'end', true)] },
    { note: c.notes[1], add: [lb(160, 202, `全部${c.sm}なら ${c.a}×${c.N}＝${base}${c.u}`, 12, C.blue, 'middle', true)] },
    { note: c.notes[2],
      add: [ln(x0, y0 - hb, xs, y0 - hb, C.red, true), lb(x0 - 4, y0 - hb + 4, c.ta(c.b), 11, C.red, 'end', true),
        bx(xs, y0 - hb, k * pw, d * c.s, `足りない\n${diff}${c.u}`, C.red, FILL.red, 11), lb(x0 + W + 4, y0 - hs - (d * c.s) / 2 + 4, `差${c.ta(d)}`, 11, C.red, 'start', true)] },
    { note: c.notes[3],
      add: [lb((x0 + xs) / 2, 186, `${c.sm}${c.N - k}${c.cnt}`, 12, C.blue, 'middle', true), lb((xs + x0 + W) / 2, 186, `${c.bg}${k}${c.cnt}`, 12, C.red, 'middle', true),
        lb(160, 216, `${diff}÷${d}＝${k} → ${c.bg}${k}${c.cnt}`, 12, C.red, 'middle', true)] },
    { note: c.notes[4], add: [lb(160, 230, `確かめ ${k}×${c.b}＋${c.N - k}×${c.a}＝${c.T}${c.u} ✓`, 12, C.green, 'middle', true)] },
  ];
  return show(slides, c.cap);
}

