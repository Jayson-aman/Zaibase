import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, band, fresh } from './diagram-kit';

type Cell = [string, string?];
const PAL: Record<string, [string, string]> = {
  b: [C.blue, FILL.blue],
  g: [C.green, FILL.green],
  r: [C.red, FILL.red],
  p: [C.purple, FILL.purple],
  y: [C.main, FILL.yellow],
  m: [C.main, FILL.warm],
  k: [C.gray, FILL.gray],
};
const U = (s: string) => [...s].reduce((u, ch) => u + (ch.charCodeAt(0) < 256 ? 0.55 : 1), 0);

/** 箱を横一列に並べる（幅は文字数に比例）。cx は各箱の中心x。 */
function row(cells: Cell[], y: number, o?: { h?: number; size?: number; x0?: number; x1?: number; gap?: number }) {
  const h = o?.h ?? 32;
  const gap = o?.gap ?? 4;
  const x0 = o?.x0 ?? 6;
  const x1 = o?.x1 ?? 314;
  const ws = cells.map(([t]) => Math.max(2.2, ...t.split('\n').map(U)) + 1);
  const tot = ws.reduce((a, b) => a + b, 0);
  const k = (x1 - x0 - gap * (cells.length - 1)) / tot;
  let x = x0;
  const els: DiagramElement[] = [];
  const cx: number[] = [];
  cells.forEach(([t, c], i) => {
    const w = ws[i] * k;
    const [col, fill] = PAL[c ?? 'k'];
    els.push(bx(x, y, w, h, t, col, fill, o?.size ?? 13));
    cx.push(x + w / 2);
    x += w + gap;
  });
  return { els, cx };
}
/** 箱の上をまわって、cxA から cxB へかかる矢印。y は箱の上端。 */
const link = (a: number, b: number, y: number, color: string, up = 14): DiagramElement[] => [
  ln(a, y - 2, a, y - up, color, false, 2),
  ln(a, y - up, b, y - up, color, false, 2),
  ar(b, y - up, b, y - 2, color),
];
const S = (text: string, y = 150, color: string = C.green, fill: string = FILL.green, size = 14) => bx(20, y, 280, 30, text, color, fill, size);
const H = (text: string, y = 165, color: string = C.blue, size = 13) => lb(160, y, text, size, color, 'middle', true);
const N = (text: string, y = 205, color: string = C.gray, size = 11) => lb(160, y, text, size, color);
const T = (text: string, y = 20, color: string = C.ink, size = 12) => lb(160, y, text, size, color, 'middle', true);

