// 「なぜ？」の連鎖で7枚以上。上半分に図、下の帯（band）にそのスライドのひとこと。
import type { DiagramFigure } from './figures';
import { show, bx, lb, ar, ln, band, fresh, C, FILL } from './diagram-kit';

type K = 'blue' | 'green' | 'red' | 'purple' | 'main' | 'gray';
const FL: Record<K, string> = { blue: FILL.blue, green: FILL.green, red: FILL.red, purple: FILL.purple, main: FILL.warm, gray: FILL.gray };
const b = (x: number, y: number, w: number, h: number, t: string, k: K = 'main', s = 12) => bx(x, y, w, h, t, C[k], FL[k], s);
const cap = (t: string, k: K | 'ink' = 'ink', s = 12) => band(150, lb(160, 192, t, s, k === 'ink' ? C.ink : C[k], 'middle', true));
const ttl = (t: string, k: K | 'ink' = 'ink') => lb(160, 14, t, 12, k === 'ink' ? C.ink : C[k], 'middle', true);
const tx = (x: number, y: number, t: string, k: K | 'ink' = 'ink', s = 11, a: 'start' | 'middle' | 'end' = 'middle', bold = false) =>
  lb(x, y, t, s, k === 'ink' ? C.ink : C[k], a, bold);
/** 左右2列の表（左が見出し、右が内容）。 */
const rows = (items: [string, string][], y0: number, o?: { xl?: number; wl?: number; wr?: number; h?: number; gap?: number; kl?: K; kr?: K; s?: number }) => {
  const xl = o?.xl ?? 8, wl = o?.wl ?? 96, wr = o?.wr ?? 200, h = o?.h ?? 26, gap = o?.gap ?? 5, s = o?.s ?? 11;
  return items.flatMap(([a, c], i) => {
    const y = y0 + i * (h + gap);
    return [b(xl, y, wl, h, a, o?.kl ?? 'blue', s), b(xl + wl + 6, y, wr, h, c, o?.kr ?? 'main', s)];
  });
};

