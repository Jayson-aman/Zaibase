type Subj = 'sansu' | 'kokugo' | 'rika' | 'shakai' | 'eigo';
type Diff = 'basic' | 'standard' | 'advanced';
type Opt = { choices?: string[]; passage?: string };

type Spec = {
  id: string;
  subj: Subj;
  diff: Diff;
  q: string;
  passage?: string;
  choices?: string[];
  answer: string;
  hint: string;
  ask: string;
  why: string;
  steps: string[];
  check: string;
  mistake: string;
  pitfall: string;
  tip: string;
};

function mk(s: Spec): Question {
  const steps = s.steps.map((t, i) => '【ステップ' + (i + 1) + '】' + t).join('\n');
  const explanation =
    '【何を聞かれているか】' + s.ask + '\n' +
    '【なぜそうなるのか】' + s.why + '\n' +
    steps + '\n' +
    '【答え】' + s.answer + '\n' +
    '【たしかめ】' + s.check + '\n' +
    '【よくあるまちがい】' + s.mistake;
  const q: Question = {
    id: s.id,
    subject: s.subj,
    difficulty: s.diff,
    course: 'koko-doshisha-kori',
    examType: 'koko',
    question: s.q,
    answer: s.answer,
    hint: s.hint,
    explanation,
    pitfall: s.pitfall,
    memoryTip: s.tip,
  };
  if (s.choices) q.choices = s.choices;
  if (s.passage) q.passage = s.passage;
  return q;
}

/** 教科ごとに連番の id を付けて Spec にする（行の並びは 難度・問題文・答え・ヒント・聞かれていること・理由・手順・たしかめ・まちがい・注意・覚え方・選択肢/本文）。 */
type Row = [Diff, string, string, string, string, string, string[], string, string, string, string, Opt?];
function build(subj: Subj, rows: Row[]): Spec[] {
  return rows.map((r, i) => ({
    id: 'kdkori_' + subj + '_' + String(i + 1).padStart(2, '0'),
    subj,
    diff: r[0],
    q: r[1],
    answer: r[2],
    hint: r[3],
    ask: r[4],
    why: r[5],
    steps: r[6],
    check: r[7],
    mistake: r[8],
    pitfall: r[9],
    tip: r[10],
    choices: r[11]?.choices,
    passage: r[11]?.passage,
  }));
}

