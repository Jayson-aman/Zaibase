import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

type E = DiagramElement;

/** 川（上流が左、下流が右）。 */
const river = (y1: number, y2: number): E[] => [
  ln(8, y1, 312, y1, C.blue, false, 2), ln(8, y2, 312, y2, C.blue, false, 2),
  lb(12, y1 - 6, '上流', 12, C.gray), lb(308, y1 - 6, '下流', 12, C.gray, 'end'),
];
/** 船の絵。 */
const boat = (x: number, y: number, color: string): E[] => [
  pg([[x, y], [x + 56, y], [x + 46, y + 16], [x + 10, y + 16]], color, FILL.warm),
  ln(x + 28, y, x + 28, y - 20, color, false, 2),
  pg([[x + 28, y - 20], [x + 46, y - 4], [x + 28, y - 4]], color, FILL.yellow),
];
/** 円の外ぐるり（文字を重ねても平気なように、多角形で描く）。 */
const ring = (cx: number, cy: number, r: number, color: string, fill?: string): E => {
  const pts: [number, number][] = [];
  for (let i = 0; i < 36; i++) pts.push([cx + r * Math.sin((i * Math.PI) / 18), cy - r * Math.cos((i * Math.PI) / 18)]);
  return pg(pts, color, fill);
};
const half = (cx: number, cy: number, r: number, up: boolean, color: string, fill: string): E => {
  const pts: [number, number][] = [];
  for (let i = 0; i <= 24; i++) { const t = (i * Math.PI) / 24; pts.push([cx + r * Math.cos(t), cy + (up ? -1 : 1) * r * Math.sin(t)]); }
  return pg(pts, color, fill);
};

