// 「なぜ？」の連鎖で、7枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { show, bx, lb, ar, ln, ci, fresh, C, FILL } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯に、そのスライドのひとことを出す。\n で改行（最大3行）。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  const h = 10 + 15 * n;
  return bx(10, 238 - h, 300, h, t, c[0], c[1], size);
};
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});
// 「なぜ？」の問い → 答え
const QA = (note: string, q: string, a: string, capText: string, c: Col = BLUE, aSize = 13) =>
  S(note, [bx(10, 8, 300, 40, q, PURPLE[0], PURPLE[1], 12), ar(160, 50, 160, 64, PURPLE[0]), bx(10, 66, 300, 100, a, c[0], c[1], aSize)], capText, c);
// 表
const tbl = (x: number, y: number, ws: number[], h: number, rows: string[][], size = 11): DiagramElement[] => {
  const out: DiagramElement[] = [];
  rows.forEach((r, i) => {
    let cx = x;
    r.forEach((t, j) => {
      out.push(bx(cx, y + i * h, ws[j], h, t, i === 0 ? C.blue : C.gray, i === 0 ? FILL.blue : '#FFFFFF', size));
      cx += ws[j];
    });
  });
  return out;
};
// 縦に並べた箱（矢印なし）
const rows = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 28, gap = 10): DiagramElement[] =>
  labels.map((t, i) => bx(x, y0 + i * (h + gap), w, h, t, c[0], c[1], size));
// 横に並べた箱を矢印でつなぐ
const flowRow = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44, gap = 16): DiagramElement[] => {
  const n = labels.length;
  const w = (300 - gap * (n - 1)) / n;
  const out: DiagramElement[] = [];
  labels.forEach((t, i) => {
    const x = 10 + i * (w + gap);
    if (i > 0) out.push(ar(x - gap + 1, y + h / 2, x - 1, y + h / 2, c[0]));
    out.push(bx(x, y, w, h, t, c[0], c[1], size));
  });
  return out;
};

// ── 磁界の中の導線（横から見た図）。磁界は N→S の向き。⊙＝手前向き ⊗＝奥向き ──
const scene = (fieldRight: boolean, out: boolean, force: 'up' | 'down' | 'none', labels = false): DiagramElement[] => {
  const L = fieldRight ? 'N' : 'S';
  const R = fieldRight ? 'S' : 'N';
  const colOf = (p: string): Col => (p === 'N' ? RED : BLUE);
  const els: DiagramElement[] = [
    bx(14, 30, 44, 100, L, colOf(L)[0], colOf(L)[1], 18),
    bx(262, 30, 44, 100, R, colOf(R)[0], colOf(R)[1], 18),
  ];
  for (const y of [48, 80, 112]) els.push(fieldRight ? ar(62, y, 258, y, C.blue) : ar(258, y, 62, y, C.blue));
  els.push(ci(160, 80, 12, out ? '⊙' : '⊗', C.ink, FILL.yellow, 14));
  if (force === 'up') els.push(ar(160, 66, 160, 26, C.red), lb(184, 30, '力', 13, C.red, 'start', true));
  if (force === 'down') els.push(ar(160, 94, 160, 134, C.red), lb(184, 128, '力', 13, C.red, 'start', true));
  els.push(lb(160, 150, out ? '電流：手前向き（⊙）' : '電流：奥向き（⊗）', 11, C.ink, 'middle'));
  if (labels) els.push(lb(110, 40, '磁界', 12, C.blue, 'middle', true));
  return els;
};
