const rect = (x: number, y: number, w: number, h: number, color: string = C.ink, fill?: string): E => pg([[x, y], [x + w, y], [x + w, y + h], [x, y + h]], color, fill);

type K = 'b' | 'g' | 'r' | 'p' | 'y' | 'k';
const PAL: Record<K, [string, string]> = { b: [C.blue, FILL.blue], g: [C.green, FILL.green], r: [C.red, FILL.red], p: [C.purple, FILL.purple], y: [C.main, FILL.yellow], k: [C.gray, FILL.gray] };
type R = [string, K?];
/** 文字カードを縦にならべる。chain=true で矢印でつなぐ。 */
const cards = (rows: R[], title?: string, chain = false): E[] => {
  const n = rows.length;
  const h = n >= 4 ? 24 : n === 3 ? 30 : 34;
  const gap = chain ? 12 : n >= 4 ? 6 : 10;
  const y0 = title ? 22 : 12;
  const out: E[] = [];
  if (title) out.push(tx(160, 13, title, 11, C.gray));
  rows.forEach(([t, k], i) => {
    const y = y0 + i * (h + gap);
    const [col, fill] = PAL[k ?? 'k'];
    if (chain && i > 0) out.push(ar(160, y - gap + 1, 160, y - 1, C.gray));
    out.push(bx(10, y, 300, h, t, col, fill, 12));
  });
  return out;
};
const CS = (note: string, lines: string[], rows: R[], title?: string, chain = false): Slide => SF(note, lines, cards(rows, title, chain));

/** 横一列に並べた箱。w を指定しない箱は残りを等分。 */
const row = (items: { t: string; k?: K; w?: number }[], y: number, h = 30, size = 12, gap = 8): E[] => {
  const total = items.reduce((a, it) => a + (it.w ?? 0), 0);
  const free = 300 - gap * (items.length - 1) - total;
  const nAuto = items.filter((it) => it.w === undefined).length;
  const auto = nAuto ? free / nAuto : 0;
  let x = 10;
  return items.map((it) => {
    const w = it.w ?? auto;
    const [col, fill] = PAL[it.k ?? 'b'];
    const e = bx(x, y, w, h, it.t, col, fill, size);
    x += w + gap;
    return e;
  });
};
/** 表。cells は行ごとの文字、colW は列の幅。先頭行を見出し色にする。 */
const tbl = (cells: string[][], x0: number, y0: number, colW: number[], rowH = 22, size = 11, hi?: [number, number][]): E[] => {
  const out: E[] = [];
  cells.forEach((r, i) => {
    let x = x0;
    r.forEach((t, j) => {
      const isHi = hi?.some(([a, b]) => a === i && b === j);
      const [col, fill] = isHi ? PAL.r : i === 0 ? PAL.b : PAL.k;
      out.push(bx(x, y0 + i * rowH, colW[j], rowH, t, col, fill, size));
      x += colW[j];
    });
  });
  return out;
};
/** 横軸の年表。items は [x, 上の文字, 下の文字?, 色?] */
const tline = (items: [number, string, string?, K?][], y = 70, x0 = 14, x1 = 306): E[] => {
  const out: E[] = [ar(x0, y, x1, y, C.ink)];
  items.forEach(([x, up, dn, k], i) => {
    const col = PAL[k ?? 'b'][0];
    out.push(ln(x, y - 5, x, y + 5, col, false, 3));
    const ty = i % 2 === 0 ? y - 12 : y + 20;
    out.push(tx(x, ty, up, 11, col));
    if (dn) out.push(tx(x, ty + (i % 2 === 0 ? -14 : 14), dn, 11, C.gray, false));
  });
  return out;
};
/** 棒グラフ。vals は値、unit は 1 あたりの高さ（px）。基準線は y=base。 */
const bars = (labels: string[], vals: number[], unit: number, base = 120, x0 = 40, step = 52, ks: K[] = []): E[] => {
  const out: E[] = [ln(x0 - 10, base, x0 + step * labels.length, base, C.ink, false, 2)];
  vals.forEach((v, i) => {
    const [col, fill] = PAL[ks[i] ?? 'b'];
    out.push(rect(x0 + i * step, base - v * unit, 32, v * unit, col, fill));
    out.push(tx(x0 + 16 + i * step, base - v * unit - 4, String(v), 11, col));
    out.push(tx(x0 + 16 + i * step, base + 14, labels[i], 11, C.gray));
  });
  return out;
};
