const zig = (x: number, y0: number, y1: number, n = 6, amp = 8, color: string = C.gray): E[] => {
  const out: E[] = [];
  const step = (y1 - y0) / (n * 2);
  let px = x, py = y0;
  for (let i = 0; i < n * 2; i++) {
    const nx = x + (i % 2 === 0 ? amp : -amp);
    const ny = y0 + step * (i + 1);
    out.push(ln(px, py, nx, ny, color, false, 2));
    px = nx; py = ny;
  }
  out.push(ln(px, py, x, y1, color, false, 2));
  return out;
};
