import type { Figure, DiagramElement } from './figures';
import { show, flow, bx, lb, ln, ar, ci, pg, C, FILL } from './diagram-kit';

type E = DiagramElement;
const NONE = 'none';
/** 画面の中央にそろえた1行の文字（式・まとめ）。 */
const row = (y: number, text: string, color: string = C.red, size = 12): E => lb(160, y, text, size, color, 'middle', true);

/** 風船（ひもつき）。気体の重さくらべ用。 */
const balloon = (x: number, cy: number, name: string, val: string, color: string, fill: string): E[] => [
  ln(x, cy + 16, x, 172, C.gray),
  ci(x, cy, 16, undefined, color, fill),
  lb(x, 190, name, 12, color, 'middle', true),
  lb(x, 208, val, 12, C.ink, 'middle'),
];

/** 心臓の部屋の絵。 */
const atrium = (x: number, w: number): E => bx(x, 52, w, 28, '心房', C.blue, FILL.blue, 12);
const ventricle = (x: number, w: number): E => bx(x, 84, w, 36, '心室', C.red, FILL.red, 12);

/** 虫のあし（上から見た絵）。pairs＝あしの対の数。 */
const bug = (cx: number, cy: number, pairs: number, color: string, fill: string): E[] => {
  const out: E[] = [];
  const step = pairs <= 3 ? 12 : pairs === 4 ? 10 : 8;
  const y0 = cy - ((pairs - 1) * step) / 2;
  for (let k = 0; k < pairs; k++) {
    const y = y0 + k * step;
    out.push(ln(cx - 9, y, cx - 32, y + 9, color, false, 2), ln(cx + 9, y, cx + 32, y + 9, color, false, 2));
  }
  out.push(bx(cx - 10, cy - 28, 20, 56, undefined, color, fill));
  return out;
};

/** 石（上流＝角ばった多角形、中流・下流＝丸）。 */
const sharpStone = (cx: number, cy: number, r: number): E =>
  pg([[cx - r, cy + r * 0.6], [cx - r * 0.7, cy - r * 0.5], [cx - r * 0.1, cy - r], [cx + r * 0.8, cy - r * 0.6], [cx + r, cy + r * 0.5], [cx + r * 0.2, cy + r * 0.8]], C.gray, FILL.gray);
const roundStone = (cx: number, cy: number, r: number): E => ci(cx, cy, r, undefined, C.gray, FILL.gray);

/** 発芽実験などのコップ。water＝水面のy（なしは null）。sprout＝芽が出ているか。 */
const cup = (cx: number, hw: number, water: number | null, sprout: boolean): E[] => {
  const out: E[] = [];
  if (water != null) out.push(bx(cx - hw, water, hw * 2, 116 - water, undefined, C.blue, FILL.blue));
  out.push(bx(cx - hw, 56, hw * 2, 60, undefined, C.gray, NONE));
  out.push(ci(cx - 6, 108, 4, undefined, C.main, '#B5622E'), ci(cx + 7, 108, 4, undefined, C.main, '#B5622E'));
  if (sprout) {
    out.push(ln(cx + 7, 104, cx + 7, 82, C.green, false, 2.5), pg([[cx + 7, 82], [cx + 17, 78], [cx + 10, 90]], C.green, FILL.green));
    out.push(ln(cx - 6, 104, cx - 6, 88, C.green, false, 2.5), pg([[cx - 6, 88], [cx - 16, 84], [cx - 9, 95]], C.green, FILL.green));
  }
  return out;
};

/** ワセリン実験の枝（葉が1枚の横から見た絵）。top／bottom＝ワセリンをぬった面。 */
const twig = (cx: number, top: boolean, bottom: boolean): E[] => {
  const out: E[] = [bx(cx - 9, 70, 18, 56, undefined, C.blue, FILL.blue), ln(cx, 48, cx, 112, C.green, false, 2.5), bx(cx - 22, 36, 44, 10, undefined, C.green, FILL.green)];
  if (top) out.push(bx(cx - 22, 30, 44, 5, undefined, '#CA8A04', FILL.yellow));
  if (bottom) out.push(bx(cx - 22, 47, 44, 5, undefined, '#CA8A04', FILL.yellow));
  return out;
};

/** 葉をとった枝（切り口を小さな丸で表す）。leaf＝葉あり、seal＝切り口にワセリン。 */
const stem = (cx: number, leaf: boolean, seal: boolean): E[] => {
  const out: E[] = [bx(cx - 9, 70, 18, 56, undefined, C.blue, FILL.blue), ln(cx, 30, cx, 112, C.green, false, 3)];
  if (leaf) out.push(bx(cx - 34, 34, 30, 8, undefined, C.green, FILL.green), bx(cx + 4, 46, 30, 8, undefined, C.green, FILL.green));
  else {
    out.push(ci(cx - 3, 40, 2.5, undefined, C.green, FILL.green), ci(cx + 3, 52, 2.5, undefined, C.green, FILL.green));
    if (seal) out.push(ci(cx - 3, 40, 5, undefined, '#CA8A04', FILL.yellow), ci(cx + 3, 52, 5, undefined, '#CA8A04', FILL.yellow));
  }
  return out;
};

/** 発芽のようすを見るお皿。n＝つぶの数（10）、k＝芽が出ている数。 */
const dish = (x: number, y: number, k: number): E[] => {
  const out: E[] = [pg([[x, y], [x + 120, y], [x + 120, y + 46], [x, y + 46]], C.gray, FILL.warm)];
  for (let i = 0; i < 10; i++) {
    const cx = x + 16 + (i % 5) * 22;
    const cy = y + 17 + Math.floor(i / 5) * 20;
    if (i < k) out.push(ln(cx, cy - 4, cx, cy - 12, C.green, false, 2.5), ci(cx, cy, 5, undefined, C.green, FILL.green));
    else out.push(ci(cx, cy, 5, undefined, C.main, '#B5622E'));
  }
  return out;
};

