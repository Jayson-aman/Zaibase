/** 横一列の流れ図（fresh の中で使う）。 */
function flowBoxes(labels: string[], y: number) {
  const n = labels.length;
  const w = (300 - 22 * (n - 1)) / n;
  return labels.flatMap((t, i) => {
    const x = 10 + i * (w + 22);
    const els = [bx(x, y, w, 60, t, C.main, FILL.warm, 12)];
    if (i > 0) els.unshift(ar(x - 21, y + 30, x - 1, y + 30, C.main));
    return els;
  });
}

