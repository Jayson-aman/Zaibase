// 中学受験・算数（以前からある公式 割合・比・数列）の動く図解スライド。
// キーは項目の label（買い切りの識別キーと同じ）。「なぜそうなるの？」を根っこまでたどる7枚以上。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, band, fresh, flow, stack, cover } from './diagram-kit';

type Tone = [string | undefined, string, string]; // [文字, 線の色, ぬりの色]
const tone = (t: 'blue' | 'main' | 'green' | 'red' | 'purple' | 'gray', text?: string): Tone => {
  const m = { blue: [C.blue, FILL.blue], main: [C.main, FILL.warm], green: [C.green, FILL.green], red: [C.red, FILL.red], purple: [C.purple, FILL.purple], gray: [C.gray, FILL.gray] } as const;
  return [text, m[t][0], m[t][1]];
};
/** 横に n 個ならべた同じ大きさの区画。 */
const cellRow = (n: number, x0: number, y: number, w: number, h: number, fn: (i: number) => Tone, size = 12): DiagramElement[] =>
  Array.from({ length: n }, (_, i) => {
    const [text, color, fill] = fn(i);
    return bx(x0 + i * w, y, w, h, text, color, fill, size);
  });
/** 流れの矢印の上にそえる文字。 */
const flowOps = (n: number, y: number, ops: string[], gap = 30, pad = 8, color?: string): DiagramElement[] => {
  const w = (320 - pad * 2 - gap * (n - 1)) / n;
  return ops.map((t, i) => lb(pad + (i + 1) * (w + gap) - gap / 2, y, t, 10, color, 'middle', true));
};

