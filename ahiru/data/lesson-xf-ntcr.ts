const graphEls = (upto: number): DiagramElement[] => {
  const pts: [number, number][] = [[0, 20], [4, 40], [8, 60], [12, 80], [16, 100], [20, 100]];
  const els: DiagramElement[] = [ln(30, 128, 280, 128, C.gray, false, 1.4), ln(30, 128, 30, 30, C.gray, false, 1.4), lb(284, 132, '分', 10, C.gray, 'start'), lb(30, 24, '水温℃', 10, C.gray, 'start')];
  for (let i = 0; i < pts.length; i++) {
    if (pts[i][0] > upto) break;
    els.push(ci(gx(pts[i][0]), gy(pts[i][1]), 3, undefined, C.red, C.red));
    if (i > 0) els.push(ln(gx(pts[i - 1][0]), gy(pts[i - 1][1]), gx(pts[i][0]), gy(pts[i][1]), C.red, false, 2));
  }
  return els;
};
