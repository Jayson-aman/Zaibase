【何を聞かれているか】条約を結ぶ機関と、承認する機関。
【なぜこの考え方か】日本の政治は三権分立で、仕事ごとに受け持つ機関が分かれている。外国との交渉や実際の手続きは、行政をおこなう内閣の仕事である。しかし、条約は国のあり方に関わる重要な約束なので、国民の代表が集まる国会が確かめる仕組みになっている。
【ステップ1】外国との交渉や調印をするのは、行政の役目をもつ内閣。
【ステップ2】結ばれた条約が、国民の考えにそっているかを確かめるのは、国民の代表である国会。
【ステップ3】国会が承認しなければ、条約は効力をもたない（承認の時期は、事前または事後）。
【答え】結ぶのは内閣、承認するのは国会。
【確かめ】三権分立の「行政＝内閣」「立法＝国会」に当てはめる。結ぶ側が内閣、見張る側が国会で、同じ機関が結んで承認することはない。
【よくあるまちがい】「条約は法律だから国会が結ぶ」と考えてしまう。結ぶのは内閣、国会は承認する側である。

