// 新傾向の単元（ntkk）の動く図解スライド（各 8 枚）。
// 「問い → なぜ？ → 答え → 注意 → 確かめ」の連鎖を、2列×4段のカードに1枚ずつ描き足していく。
// 画面の同じ場所に文字を重ねない作りにして、前のスライドの文字が消えなくても読めるようにしてある。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, ar, show } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];

// 1行を n 字ごとに折り返す（\n はそのまま改行）
const wrap = (t: string, n = 13): string =>
  t
    .split('\n')
    .map((line) => {
      const out: string[] = [];
      for (let i = 0; i < line.length; i += n) out.push(line.slice(i, i + n));
      return out.join('\n');
    })
    .join('\n');

// i 番目（0〜7）のカード。2列×4段。奇数番は左のカードから矢印でつなぐ。
const card = (i: number, text: string, c: Col): DiagramElement[] => {
  const x = 6 + (i % 2) * 160;
  const y = 6 + Math.floor(i / 2) * 58;
  const els: DiagramElement[] = [];
  if (i % 2 === 1) els.push(ar(154, y + 26, 166, y + 26, c[0]));
  els.push(bx(x, y, 148, 52, wrap(text), c[0], c[1], 11));
  return els;
};

type Row = [string, Col, string];
const build = (rows: Row[], caption: string): DiagramFigure =>
  show(
    rows.map(([text, col, note], i) => ({ note, add: card(i, text, col) })),
    caption,
  );

