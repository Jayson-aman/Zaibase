const arrowRow = (y: number, label: string, items: string[], color: string, fill: string) => {
  const x0 = 56, total = 256, gap = 14, n = items.length;
  const w = (total - gap * (n - 1)) / n;
  const els = [lb(4, y + 16, label, 11, color, 'start', true)];
  items.forEach((t, i) => {
    const x = x0 + i * (w + gap);
    if (i > 0) els.push(ar(x - gap + 1, y + 16, x - 1, y + 16, color));
    els.push(bx(x, y, w, 32, t, color, fill, 11));
  });
  return els;
};
