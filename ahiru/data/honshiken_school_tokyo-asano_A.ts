/** 解説の型：【何を聞かれているか】→【なぜそうなるのか】→【ステップ】→【答え】→【確かめ】→【よくあるまちがい】 */
const X = (ask: string, why: string, steps: string[], ans: string, check: string, miss: string): string =>
  [
    `【何を聞かれているか】${ask}`,
    `【なぜそうなるのか】${why}`,
    ...steps.map((s, i) => `【ステップ${i + 1}】${s}`),
    `【答え】${ans}`,
    `【確かめ】${check}`,
    `【よくあるまちがい】${miss}`,
  ].join('\n');

