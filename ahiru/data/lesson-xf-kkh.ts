// 「なぜ？」の連鎖で、7枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, fresh, flow, stack } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=176 から）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 176, 292, 14 + 15 * n, t, c[0], c[1], size);
};

// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});

// 「なぜ？」の問い → 答え、の1組（上 8〜48 が問い、68〜160 が答え）
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13): DiagramElement[] => [
  bx(12, 8, 296, 40, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 50, 160, 66, PURPLE[0]),
  bx(12, 68, 296, 94, a, c[0], c[1], aSize),
];

// 横一列の箱（矢印つき）
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap: 14 }).flat();

// 縦に並べた箱（矢印つき）
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 26, gap = 12): DiagramElement[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();

// 左右の対応表：[左, 右] を縦に並べる
const tb = (pairs: [string, string][], y0 = 10, h = 30, gap = 6, c: Col = MAIN, lw = 96, size = 12): DiagramElement[] =>
  pairs.flatMap(([a, b], i) => {
    const y = y0 + i * (h + gap);
    return [bx(10, y, lw, h, a, c[0], c[1], size), ar(10 + lw + 2, y + h / 2, 10 + lw + 16, y + h / 2, c[0]), bx(10 + lw + 18, y, 300 - lw - 18, h, b, c[0], FILL.warm, size)];
  });

// 矢印なしの箱の縦並び
const lst = (items: string[], c: Col = MAIN, y0 = 8, h = 28, gap = 6, size = 12, x = 10, w = 300): DiagramElement[] =>
  items.map((t, i) => bx(x, y0 + i * (h + gap), w, h, t, c[0], c[1], size));

// 配点の表：[内容, 点] を縦に並べる（点は右の小さい箱）
const pts = (rows: [string, string][], c: Col = MAIN, y0 = 8, h = 28, gap = 6, size = 12): DiagramElement[] =>
  rows.flatMap(([a, p], i) => {
    const y = y0 + i * (h + gap);
    return [bx(10, y, 236, h, a, c[0], FILL.warm, size), bx(252, y, 58, h, p, c[0], c[1], size)];
  });

// 見出し帯（上）
const hd = (t: string, c: Col = MAIN, y = 8): DiagramElement => bx(10, y, 300, 26, t, c[0], c[1], 13);

// 左右ふたつの箱（見出し＋中身）
const two = (l: string, r: string, y: number, h: number, cl: Col, cr: Col, size = 12): DiagramElement[] => [
  bx(10, y, 147, h, l, cl[0], cl[1], size),
  bx(163, y, 147, h, r, cr[0], cr[1], size),
];

// 中心に1つ、まわりに4つ
const hub = (center: string, outs: string[], c: Col = MAIN, size = 12): DiagramElement[] => {
  const pos: [number, number][] = [[10, 12], [214, 12], [10, 112], [214, 112]];
  const els: DiagramElement[] = [];
  outs.slice(0, 4).forEach((_, i) => {
    const [x, y] = pos[i];
    els.push(ln(160, 85, x + 48, y + 23, c[0]));
  });
  els.push(bx(100, 62, 120, 46, center, c[0], c[1], 13));
  outs.slice(0, 4).forEach((t, i) => {
    const [x, y] = pos[i];
    els.push(bx(x, y, 96, 46, t, c[0], FILL.warm, size));
  });
  return els;
};

const FIG: Record<string, DiagramFigure> = {};
const SEC: Record<string, string> = {};
const reg = (unit: string, sec: number, fig: DiagramFigure) => {
  FIG['xf_' + unit] = fig;
  SEC[unit + '#' + sec] = 'xf_' + unit;
};

