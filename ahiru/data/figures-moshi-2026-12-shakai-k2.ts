// 問題の場面 → 手がかり → 理由（なぜ？） → 整理 → 他の選択肢 → 答えと確かめ の順に、7枚で動かす。
// 座標は 320×240。下の帯（y=160 から）にそのスライドのひとことを出す。
import type { DiagramElement, Figure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, show, fresh, flow } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];

const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 160, 292, 16 + 15 * n, t, c[0], c[1], size);
};
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13): DiagramElement[] => [
  bx(12, 8, 296, 40, (q.startsWith('なぜ') ? q : 'なぜ？ ' + q), PURPLE[0], PURPLE[1], 12),
  ar(160, 50, 160, 66, PURPLE[0]),
  bx(12, 68, 296, 74, a, c[0], c[1], aSize),
];
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap: 14 }).flat();
// 横一列の年表。items は [年, 出来事（\n で改行）]
const tl = (items: [string, string][], y: number, c: Col = MAIN): DiagramElement[] => {
  const n = items.length;
  const out: DiagramElement[] = [ln(14, y, 306, y, c[0], false, 2)];
  items.forEach(([yr, lab], i) => {
    const x = 14 + ((i + 0.5) * 292) / n;
    out.push(ci(x, y, 5, undefined, c[0], c[1]));
    out.push(lb(x, y - 12, yr, 11, c[0], 'middle', true));
    lab.split('\n').forEach((t, j) => out.push(lb(x, y + 20 + j * 13, t, 10, C.ink, 'middle')));
  });
  return out;
};
// 「×」の選択肢をならべる3段の箱
const wrong3 = (a: string, b: string, c: string, size = 11): DiagramElement[] => [
  bx(14, 8, 292, 36, a, C.red, FILL.red, size),
  bx(14, 50, 292, 36, b, C.red, FILL.red, size),
  bx(14, 92, 292, 36, c, C.red, FILL.red, size),
];
// 答えの箱
const ans = (t: string, c: Col = GREEN, h = 60, size = 13): DiagramElement[] => [bx(14, 14, 292, h, t, c[0], c[1], size)];
// 縦棒グラフ。items は [名前（\n で改行）, 値, 色]
const bars = (items: [string, number, Col][], maxV: number, valText?: string[], y0 = 118, hmax = 84): DiagramElement[] => {
  const n = items.length;
  const slot = 280 / n;
  const bw = Math.min(46, slot * 0.55);
  const out: DiagramElement[] = [ln(20, y0, 306, y0, C.ink, false, 1.5)];
  items.forEach(([name, v, c], i) => {
    const cx = 20 + slot * (i + 0.5);
    const h = Math.max(2, (v / maxV) * hmax);
    out.push(bx(cx - bw / 2, y0 - h, bw, h, undefined, c[0], c[1]));
    out.push(lb(cx, y0 - h - 4, valText ? valText[i] : String(v), 11, C.ink, 'middle', true));
    name.split('\n').forEach((t, j) => out.push(lb(cx, y0 + 14 + j * 12, t, 10, C.ink, 'middle')));
  });
  return out;
};

