const cap = (t: string, y = 185, col: string = C.ink) => lb(160, y, t, 13, col, 'middle', true);
const cap2 = (t: string, y = 210, col: string = C.gray) => lb(160, y, t, 11, col, 'middle');

/** 左右に並べた2つの箱（間に記号）。 */
const two = (a: string, b: string, mid: string, y = 14, h = 50, size = 26, c1: string = C.blue, f1: string = FILL.blue, c2: string = C.green, f2: string = FILL.green) => [
  bx(50, y, 90, h, a, c1, f1, size),
  lb(160, y + h / 2, mid, 16, C.gray, 'middle', true),
  bx(180, y, 90, h, b, c2, f2, size),
];
/** 「左 → 右」の1行。 */
const row = (y: number, l: string, mid: string, r: string, c1: string = C.blue, f1: string = FILL.blue, c2: string = C.green, f2: string = FILL.green, h = 30, size = 13) => [
  bx(12, y, 116, h, l, c1, f1, size),
  lb(160, y + h / 2, mid, 10, C.gray, 'middle', true),
  bx(192, y, 116, h, r, c2, f2, size),
];
/** 小さな箱を格子に並べる。 */
const grid = (cells: string[], x0: number, y0: number, w: number, h: number, gap: number, per: number, c: string = C.main, f: string = FILL.warm, size = 13) =>
  cells.map((t, i) => bx(x0 + (i % per) * (w + gap), y0 + Math.floor(i / per) * (h + gap), w, h, t, c, f, size));

