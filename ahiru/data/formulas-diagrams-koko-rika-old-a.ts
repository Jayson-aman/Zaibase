const wave = (x0: number, y0: number, amp: number, period: number, cycles: number, color: string = C.blue): DiagramElement[] => {
  const out: DiagramElement[] = [];
  const n = cycles * 16;
  let px = x0;
  let py = y0;
  for (let i = 1; i <= n; i++) {
    const x = x0 + (i * period * cycles) / n;
    const y = y0 - amp * Math.sin((2 * Math.PI * i) / 16);
    out.push(ln(px, py, x, y, color, false, 2));
    px = x;
    py = y;
  }
  return out;
};

