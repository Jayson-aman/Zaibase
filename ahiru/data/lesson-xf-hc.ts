// 中学受験 社会（教科書単元 13 件・古代〜鎌倉）の「動く図解スライド」。
// 「なぜ？」の連鎖で、7枚以上。単元の節（section）ひとつに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, fresh, flow, stack } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=164 から）にそのスライドのひとこと。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 164, 292, 16 + 15 * n, t, c[0], c[1], size);
};

// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});

// 「なぜ？」の問い → 答え、の1組
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13): DiagramElement[] => [
  bx(12, 8, 296, 36, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 46, 160, 60, PURPLE[0]),
  bx(12, 62, 296, 90, a, c[0], c[1], aSize),
];

// 箱を矢印でつないだ横一列
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44, gap = 14): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap }).flat();

// 縦に並べた箱
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 26, gap = 12): DiagramElement[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();

// 2つをくらべる表（左右2列・各3行まで）
const cmp = (lt: string, ll: string[], rt: string, rl: string[], lc: Col = BLUE, rc: Col = RED, size = 11): DiagramElement[] => {
  const out: DiagramElement[] = [bx(8, 8, 148, 28, lt, lc[0], lc[1], 12), bx(164, 8, 148, 28, rt, rc[0], rc[1], 12)];
  ll.forEach((t, i) => out.push(bx(8, 44 + i * 37, 148, 31, t, lc[0], FILL.warm, size)));
  rl.forEach((t, i) => out.push(bx(164, 44 + i * 37, 148, 31, t, rc[0], FILL.warm, size)));
  return out;
};

// 年表（年と出来事の箱を横にならべる）
const tl = (items: [string, string][], c: Col = MAIN, y = 30, size = 11): DiagramElement[] => {
  const n = items.length;
  const gap = 10;
  const w = (304 - gap * (n - 1)) / n;
  const out: DiagramElement[] = [ln(8, y + 20, 312, y + 20, C.gray)];
  items.forEach(([yr, ev], i) => {
    const x = 8 + i * (w + gap);
    out.push(bx(x, y, w, 24, yr, c[0], c[1], 12));
    out.push(bx(x, y + 34, w, 52, ev, c[0], FILL.warm, size));
  });
  return out;
};

