// 「なぜ？」の連鎖で、7枚以上。単元の節（section）ごとに 1 枚の図解をひもづける。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, sc, show, fresh, flow, stack } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=160 から）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(14, 160, 292, 16 + 15 * n, t, c[0], c[1], size);
};

// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});

// 「なぜ？」の問い → 答え、の1組
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13): DiagramElement[] => [
  bx(12, 8, 296, 40, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 50, 160, 66, PURPLE[0]),
  bx(12, 68, 296, 80, a, c[0], c[1], aSize),
];

// 「問い」→ 答え（なぜ、ではない問い用）
const qd = (q: string, a: string, c: Col = BLUE, aSize = 13): DiagramElement[] => [
  bx(12, 8, 296, 40, '問い　' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 50, 160, 66, PURPLE[0]),
  bx(12, 68, 296, 80, a, c[0], c[1], aSize),
];

// 箱を矢印でつないだ横一列
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap: 14 }).flat();

// 縦に並べた箱
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 26, gap = 12): DiagramElement[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();

// 表：1行目が見出し。widths は列の幅（合計は 300 まで）。
const tbl = (head: string[], rows: string[][], y0: number, widths: number[], rh = 28, hc: Col = BLUE, bc: Col = MAIN, size = 11, x0 = 10): DiagramElement[] => {
  const out: DiagramElement[] = [];
  const all = [head, ...rows];
  all.forEach((r, i) => {
    let x = x0;
    r.forEach((t, j) => {
      const c = i === 0 ? hc : bc;
      out.push(bx(x, y0 + i * (rh + 2), widths[j], rh, t, c[0], c[1], size));
      x += widths[j] + 2;
    });
  });
  return out;
};

// 同じ大きさの箱を n 列で並べる
const grid = (cells: string[], ncol: number, x0: number, y0: number, w: number, h: number, gx = 6, gy = 6, c: Col = MAIN, size = 11): DiagramElement[] =>
  cells.map((t, i) => bx(x0 + (i % ncol) * (w + gx), y0 + Math.floor(i / ncol) * (h + gy), w, h, t, c[0], c[1], size));

// 左右ならべ（比べる）
const two = (l: string, r: string, y: number, h: number, cl: Col = BLUE, cr: Col = RED, size = 12): DiagramElement[] => [
  bx(10, y, 148, h, l, cl[0], cl[1], size),
  bx(162, y, 148, h, r, cr[0], cr[1], size),
];

// 年表：items は [年, ことがら]。n は 3〜5。
const tline = (items: [string, string][], y = 40, c: Col = MAIN, size = 10): DiagramElement[] => {
  const n = items.length;
  const w = (300 - 4 * (n - 1)) / n;
  const out: DiagramElement[] = [ln(10, y, 310, y, C.gray, false, 2)];
  items.forEach(([yr, t], i) => {
    const x = 10 + i * (w + 4);
    out.push(ci(x + w / 2, y, 5, undefined, c[0], c[1]));
    out.push(lb(x + w / 2, y - 14, yr, 12, c[0], 'middle', true));
    out.push(bx(x, y + 12, w, 62, t, c[0], c[1], size));
  });
  return out;
};

