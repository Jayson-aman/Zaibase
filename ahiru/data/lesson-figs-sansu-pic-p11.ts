// 等差数列・数列の和・碁石やマッチ棒の並びを、数の箱・碁石・マッチ棒の絵で見せる。
import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, C, FILL } from './diagram-kit';

type E = DiagramElement;

const cxOf = (i: number, x0: number, bw: number, gap: number) => x0 + i * (bw + gap) + bw / 2;

/** 数の箱を横に並べる（pos0＝左から何番目の位置から置くか）。 */
const cells = (vals: string[], pos0: number, x0: number, y: number, bw: number, gap: number, h: number, color: string, fill: string, size = 13): E[] =>
  vals.map((v, i) => bx(x0 + (pos0 + i) * (bw + gap), y, bw, h, v, color, fill, size));

/** 位置 a から b までの、となりどうしの上に「＋4」のような矢印とラベルを置く（y＝箱の上のはし）。 */
const hops = (a: number, b: number, x0: number, y: number, bw: number, gap: number, texts: string[], color: string, size = 12): E[] => {
  const out: E[] = [];
  for (let i = a; i < b; i++) {
    const p = cxOf(i, x0, bw, gap), q = cxOf(i + 1, x0, bw, gap);
    out.push(ar(p + 4, y - 6, q - 4, y - 6, color), lb((p + q) / 2, y - 12, texts[i - a], size, color, 'middle', true));
  }
  return out;
};

/** 碁石（円）を1つ置く。 */
const dot = (x: number, y: number, r: number, color: string, fill: string): E => ci(x, y, r, undefined, color, fill);

/** 中心から数えて k 重目のひし形の位置（|dx|＋|dy|＝k）。 */
const layerPts = (k: number): [number, number][] => {
  if (k === 0) return [[0, 0]];
  const out: [number, number][] = [];
  for (let dx = -k; dx <= k; dx++) {
    const dy = k - Math.abs(dx);
    out.push([dx, dy]);
    if (dy !== 0) out.push([dx, -dy]);
  }
  return out;
};

