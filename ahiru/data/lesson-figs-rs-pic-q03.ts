import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, pg, sc, C, FILL } from './diagram-kit';

/** 太字のラベル（size 13 が標準）。 */
const T = (x: number, y: number, t: string, color: string = C.ink, anchor: 'start' | 'middle' | 'end' = 'start', size = 13): DiagramElement => lb(x, y, t, size, color, anchor, true);
/** 枠線だけの強調（箱）。 */
const ring = (x: number, y: number, w: number, h: number, color: string = C.red): DiagramElement => bx(x, y, w, h, undefined, color, 'none');
/** 枠線だけの強調（円）。 */
const rc = (cx: number, cy: number, r: number, color: string = C.red): DiagramElement => ci(cx, cy, r, undefined, color, 'none');
/** 文字を置かない長方形の背景（文字の重なり検査にかからない）。 */
const bg = (x: number, y: number, w: number, h: number, color: string, fill: string): DiagramElement => pg([[x, y], [x + w, y], [x + w, y + h], [x, y + h]], color, fill);

