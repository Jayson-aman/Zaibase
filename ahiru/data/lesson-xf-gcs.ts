// 中学受験 算数（gcs）：問題集に対して足りなかった 12 単元の「動く図解スライド」。
// 「なぜ？ → 答え → では、なぜ？」の連鎖で、すべて 8 枚。単元の最初の節（#0）にひもづける。
// 座標は 320×240。下の帯（y=164〜）にそのスライドのひとこと。
import type { DiagramElement, DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, sc, show, fresh, flow } from './diagram-kit';

type Col = [string, string];
const BLUE: Col = [C.blue, FILL.blue];
const GREEN: Col = [C.green, FILL.green];
const RED: Col = [C.red, FILL.red];
const MAIN: Col = [C.main, FILL.warm];
const PURPLE: Col = [C.purple, FILL.purple];
const GRAY: Col = [C.gray, FILL.gray];
const YELLOW: Col = [C.main, FILL.yellow];

// 下の帯（y=164 から）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const n = t.split('\n').length;
  return bx(10, 164, 300, 14 + 15 * n, t, c[0], c[1], size);
};

// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});

// 「なぜ？」の問い → 答え
const Q = (note: string, q: string, a: string, capText: string, c: Col = BLUE, aSize = 13) =>
  S(note, [
    bx(10, 8, 300, 34, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
    ar(160, 44, 160, 56, PURPLE[0]),
    bx(10, 58, 300, 92, a, c[0], c[1], aSize),
  ], capText, c);

// 横一列の箱（矢印つき）
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44, gap = 14): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap }).flat();

// 矢印なしの横一列
const cells = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 30, gap = 6, x0 = 10, total = 300): DiagramElement[] => {
  const n = labels.length;
  const w = (total - gap * (n - 1)) / n;
  return labels.map((t, i) => bx(x0 + i * (w + gap), y, w, h, t, c[0], c[1], size));
};

// 横一列の箱のうち、hi 番目だけを緑で目立たせる
const cellsHi = (labels: string[], y: number, hi: number, size = 12, h = 30, gap = 6, x0 = 10, total = 300): DiagramElement[] => {
  const n = labels.length;
  const w = (total - gap * (n - 1)) / n;
  return labels.map((t, i) => (i === hi ? bx(x0 + i * (w + gap), y, w, h, t, C.green, FILL.green, size) : bx(x0 + i * (w + gap), y, w, h, t, C.gray, FILL.gray, size)));
};

// 表（先頭行は見出し）。colW は各列の幅。hl は目立たせるセル [行, 列]。
const tab = (rows: string[][], y0: number, colW: number[], h = 26, size = 12, x0?: number, hl: [number, number][] = []): DiagramElement[] => {
  const tw = colW.reduce((a, b) => a + b, 0);
  const sx = x0 ?? (320 - tw) / 2;
  const out: DiagramElement[] = [];
  rows.forEach((r, i) => {
    let x = sx;
    r.forEach((t, j) => {
      const on = hl.some(([a, b]) => a === i && b === j);
      const c = i === 0 ? BLUE : on ? RED : MAIN;
      out.push(bx(x, y0 + i * h, colW[j], h, t, c[0], on ? FILL.red : i === 0 ? FILL.blue : FILL.warm, size));
      x += colW[j];
    });
  });
  return out;
};

// 円弧を細かい線分でえがく（角度は度。右が0°で反時計回り。画面の y は下向き）
const arc = (cx: number, cy: number, r: number, a0: number, a1: number, color: string = C.red, width = 3): DiagramElement[] => {
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / 8));
  const out: DiagramElement[] = [];
  const pt = (a: number): [number, number] => [cx + r * Math.cos((a * Math.PI) / 180), cy - r * Math.sin((a * Math.PI) / 180)];
  for (let i = 0; i < n; i++) {
    const p = pt(a0 + ((a1 - a0) * i) / n);
    const q = pt(a0 + ((a1 - a0) * (i + 1)) / n);
    out.push(ln(p[0], p[1], q[0], q[1], color, false, width));
  }
  return out;
};

// 方眼（cols×rows）。x0,y0 は左上。cell は1マスの大きさ。shade は色をつけるマス [列, 行(上から)]。
const grid = (x0: number, y0: number, cols: number, rows: number, cell: number, shade: [number, number][] = [], fill: string = FILL.yellow): DiagramElement[] => {
  const out: DiagramElement[] = [];
  for (const [c, r] of shade) out.push(pg([[x0 + c * cell, y0 + r * cell], [x0 + (c + 1) * cell, y0 + r * cell], [x0 + (c + 1) * cell, y0 + (r + 1) * cell], [x0 + c * cell, y0 + (r + 1) * cell]], 'rgba(0,0,0,0)', fill));
  for (let i = 0; i <= cols; i++) out.push(ln(x0 + i * cell, y0, x0 + i * cell, y0 + rows * cell, C.gray, false, 1.2));
  for (let j = 0; j <= rows; j++) out.push(ln(x0, y0 + j * cell, x0 + cols * cell, y0 + j * cell, C.gray, false, 1.2));
  return out;
};

