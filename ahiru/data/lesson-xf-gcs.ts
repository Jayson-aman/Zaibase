// ───────────────────────── 11 方眼の対角線が通るます目の数 ─────────────────────────
const through = (W: number, H: number): [number, number][] => {
  const out: [number, number][] = [];
  for (let c = 0; c < W; c++) for (let r = 0; r < H; r++) {
    // 左下を原点にした (c, r) のマス。線分 y = H/W * x が内部を通るか
    if (H * c < W * (r + 1) && H * (c + 1) > W * r) out.push([c, H - 1 - r]); // 画面の行は上から数える
  }
  return out;
};
