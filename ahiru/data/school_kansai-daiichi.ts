type Subj = 'sansu' | 'kokugo' | 'rika' | 'shakai';
type Diff = 'basic' | 'standard' | 'advanced';

// [難度, 問題, 答え, ヒント, 何を聞かれているか, なぜ, 手順, たしかめ, まちがい, ひっかけ, 覚え方, 選択肢?, 本文?]
type T = [Diff, string, string, string, string, string, string[], string, string, string, string, string[]?, string?];

function mk(subj: Subj, label: string) {
  return (t: T, i: number): Question => {
    const [diff, q, answer, hint, ask, why, steps, check, mistake, pitfall, tip, choices, passage] = t;
    const n = String(i + 1).padStart(2, '0');
    const st = steps.map((s, k) => '【ステップ' + (k + 1) + '】' + s).join('\n');
    const explanation =
      '【何を聞かれているか】' + ask + '\n' +
      '【なぜそうなるのか】' + why + '\n' +
      st + '\n' +
      '【答え】' + answer + '\n' +
      '【たしかめ】' + check + '\n' +
      '【よくあるまちがい】' + mistake;
    const o: Question = {
      id: 'kandai1_' + subj + '_' + n,
      subject: subj,
      difficulty: diff,
      course: 'kansai-daiichi',
      examType: 'chugaku',
      question: '【' + label + (i + 1) + '】' + q,
      answer,
      hint,
      explanation,
      pitfall,
      memoryTip: tip,
    };
    if (choices) o.choices = choices;
    if (passage) o.passage = passage;
    return o;
  };
}

