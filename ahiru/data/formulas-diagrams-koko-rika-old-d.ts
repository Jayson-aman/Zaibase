const BY = 152;
/** 下の帯に式やひとことを出す。 */
const say = (text: string, color: string = C.blue, fill: string = FILL.blue, size = 13): E[] =>
  band(BY, bx(16, 166, 288, 40, text, color, fill, size));
/** 1枚のスライド（図 + 下の帯 + 説明文）。 */
const sl = (note: string, fig: E[], text: string, color: string = C.blue, fill: string = FILL.blue, size = 13) => ({
  note,
  add: fresh(...fig, ...say(text, color, fill, size)),
});
/** 軸（原点 ox,oy から右へ ex、上へ ey）。 */
const axes = (ox: number, oy: number, ex: number, ey: number): E[] => [ar(ox, oy, ox + ex, oy, C.gray), ar(ox, oy, ox, oy - ey, C.gray)];
/** 原子モデル：中心の核と、まわりの電子。 */
const atomModel = (cx: number, cy: number, nuc: string, nElec: number): E[] => {
  const pos: [number, number][] = [[0, -42], [-36, 21], [36, 21], [0, 42]];
  const out: E[] = [ci(cx, cy, 44, undefined, C.gray, FILL.gray), ci(cx, cy, 20, nuc, C.red, FILL.red, 12)];
  for (let i = 0; i < nElec; i++) out.push(ci(cx + pos[i][0], cy + pos[i][1], 8, '−', C.blue, FILL.blue, 12));
  return out;
};

