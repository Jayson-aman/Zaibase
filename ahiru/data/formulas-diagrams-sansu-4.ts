const dotGrid = (n: number, x0: number, y0: number, gap: number, color: string, fill: string, which: 'all' | 'ring') => {
  const els = [];
  for (let i = 0; i < n; i++)
    for (let j = 0; j < n; j++) {
      const edge = i === 0 || j === 0 || i === n - 1 || j === n - 1;
      if (which === 'all' || edge) els.push(ci(x0 + j * gap, y0 + i * gap, 5, undefined, color, fill));
    }
  return els;
};
