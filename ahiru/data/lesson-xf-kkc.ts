import type { DiagramFigure } from './figures';
import { C, FILL, bx, lb, ar, ln, show, fresh, band } from './diagram-kit';
import type { DiagramElement } from './figures';

const K = {
  b: [C.blue, FILL.blue], g: [C.green, FILL.green], r: [C.red, FILL.red],
  m: [C.main, FILL.warm], p: [C.purple, FILL.purple], y: [C.gray, FILL.yellow],
} as const;
type CK = keyof typeof K;
const B = (x: number, y: number, w: number, h: number, t: string, k: CK = 'm', s = 12): DiagramElement => bx(x, y, w, h, t, K[k][0], K[k][1], s);
const L = (x: number, y: number, t: string, s = 11, k: CK | 'ink' | 'gray' = 'ink', a: 'start' | 'middle' | 'end' = 'middle', bold = false): DiagramElement =>
  lb(x, y, t, s, k === 'ink' ? C.ink : k === 'gray' ? C.gray : K[k][0], a, bold);
const AR = (x1: number, y1: number, x2: number, y2: number, k: CK = 'm'): DiagramElement => ar(x1, y1, x2, y2, K[k][0]);
const cap = (t: string, k: CK = 'm'): DiagramElement[] => band(150, lb(160, 190, t, 12, K[k][0], 'middle', true));
const ttl = (t: string): DiagramElement => lb(160, 15, t, 12, C.ink, 'middle', true);
const N = (note: string, title: string, els: DiagramElement[], c?: string, k: CK = 'm') => ({ note, add: fresh(ttl(title), ...els, ...(c ? cap(c, k) : [])) });
const A = (note: string, els: DiagramElement[], c?: string, k: CK = 'm') => ({ note, add: [...els, ...(c ? cap(c, k) : [])] });
void ln;

