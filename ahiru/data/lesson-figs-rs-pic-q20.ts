/** 国・地域を人（円）で表した横一列。 */
function crowd(n: number, y: number, color: string, fill: string): DiagramElement[] {
  const out: DiagramElement[] = [];
  for (let i = 0; i < n; i++) out.push(ci(76 + i * 11, y, 4.5, undefined, color, fill));
  return out;
}

