// 対象：平均とつるかめ・過不足算・差集め算・消去算の図（棒グラフ・座標になっていたもの）
import type { Figure, DiagramElement } from './figures';
import { show, bx, lb, ln, ar, ci, C, FILL } from './diagram-kit';

type DE = DiagramElement;

// 文字の幅の見積もり（figlint と同じ）
const tw = (t: string, s: number) =>
  [...t].reduce((a, c) => a + (/[\x20-\x7e]/.test(c) ? (c === ' ' ? 0.3 : /[0-9]/.test(c) ? 0.58 : /[A-Z]/.test(c) ? 0.66 : 0.52) * s : s), 0);
const clampX = (cx: number, w: number) => Math.min(Math.max(cx, 4 + w / 2), 316 - w / 2);

// ───────────────────────── 過不足算の線分図（総数の点線をはさんで、余りと不足を描く） ─────────────────────────
type SegCfg = {
  a: number; b: number; n: number; T: number; unit: string;
  titleA: string; titleB: string; extraA?: string; extraB?: string;
  totLabel: string; bracket: string; boxHead: string; boxText: string; final: string;
  notes: [string, string, string, string, string, string];
  caption: string;
};

function segFig(c: SegCfg): Figure {
  const H = 26;
  const ra = c.a * c.n, rb = c.b * c.n;
  const k = 288 / Math.max(ra, rb, c.T);
  const X = (v: number) => 16 + v * k;
  const xa = X(ra), xb = X(rb), xt = X(c.T);
  const row = (y: number, v: number, title: string, color: string, fill: string, extra?: string): DE[] => {
    const out: DE[] = [lb(16, y - 6, title, 12, color, 'start', true), bx(16, y, Math.min(v, c.T) * k, H, undefined, color, fill)];
    const over = v > c.T;
    const w = Math.abs(v - c.T) * k;
    const text = extra ?? (over ? `足りない${v - c.T}${c.unit}` : `余り${c.T - v}${c.unit}`);
    const col = over ? C.red : C.green, fl = over ? FILL.red : FILL.green;
    const x0 = X(Math.min(v, c.T));
    if (tw(text, 11) + 6 <= w) out.push(bx(x0, y, w, H, text, col, fl, 11));
    else {
      out.push(bx(x0, y, w, H, undefined, col, fl));
      out.push(lb(clampX(x0 + w / 2, tw(text, 11) * 1.04), y - 6, text, 11, col, 'middle', true));
    }
    return out;
  };
  const mid = clampX((xa + xb) / 2, tw(c.bracket, 12) * 1.05);
  const bw = Math.min(44, (288 - (c.n - 1) * 2) / c.n);
  const s = c.notes;
  return show(
    [
      { note: s[0], add: row(48, ra, c.titleA, C.blue, FILL.blue, c.extraA) },
      { note: s[1], add: row(122, rb, c.titleB, C.purple, FILL.purple, c.extraB) },
      { note: s[2], add: [ln(xt, 44, xt, 78, C.main, true, 2), ln(xt, 118, xt, 152, C.main, true, 2), lb(clampX(xt, 70), 168, c.totLabel, 13, C.main, 'middle', true)] },
      { note: s[3], add: [ln(xa, 76, xa, 99, C.red, true), ln(xb, 99, xb, 120, C.red, true), ar(xa, 99, xb, 99, C.red), lb(mid, 90, c.bracket, 12, C.red, 'middle', true)] },
      { note: s[4], add: [lb(16, 184, c.boxHead, 12, C.ink, 'start', true), ...Array.from({ length: c.n }, (_, i) => bx(16 + i * (bw + 2), 190, bw, 24, c.boxText, C.red, FILL.red, 11))] },
      { note: s[5], add: [lb(160, 232, c.final, 13, C.red, 'middle', true)] },
    ],
    c.caption,
  );
}

// ───────────────────────── 過不足算の面積図（たて＝1人ぶん、よこ＝人数） ─────────────────────────
type G = { x0: number; Wn: number; ytop: number; hs: number };
type AreaCfg = {
  a: number; b: number;
  top: string; aTxt: string; perA: [string, string]; perB: string; whoLbl: string;
  mk3: (g: G) => DE[]; s4: DE[]; l5: string; l6: string;
  notes: [string, string, string, string, string, string];
  caption: string;
};

/** 細長い部分（ストリップ）を区切る。入る文字は箱の中、入らなければ上に出す。 */
const piece = (g: G, xr: number, wr: number, text: string, color: string, fill: string): DE[] => {
  const x = g.x0 + xr;
  if (g.hs >= 15 && tw(text, 11) + 6 <= wr) return [bx(x, g.ytop, wr, g.hs, text, color, fill, 11)];
  return [bx(x, g.ytop, wr, g.hs, undefined, color, fill), lb(clampX(x + wr / 2, tw(text, 11) * 1.04), g.ytop - 4, text, 11, color, 'middle', true)];
};

function areaFig(c: AreaCfg): Figure {
  const x0 = 64, Wn = 180, base = 178, H = 110;
  const sc = H / c.b;
  const ha = c.a * sc, hs = (c.b - c.a) * sc;
  const ytop = base - H, yA = base - ha;
  const g: G = { x0, Wn, ytop, hs };
  const s = c.notes;
  return show(
    [
      { note: s[0], add: [lb(16, 24, c.top, 12, C.gray, 'start'), bx(x0, yA, Wn, ha, c.aTxt, C.blue, FILL.blue, 12),
          lb(250, yA + ha / 2 - 2, c.perA[0], 12, C.blue, 'start', true), lb(250, yA + ha / 2 + 13, c.perA[1], 12, C.blue, 'start', true),
          ar(x0 + Wn / 2, 188, x0 + 2, 188, C.gray), ar(x0 + Wn / 2, 188, x0 + Wn - 2, 188, C.gray), lb(x0 + Wn / 2, 202, c.whoLbl, 12, C.gray, 'middle', true)] },
      { note: s[1], add: [bx(x0, ytop, Wn, hs, undefined, C.purple, FILL.purple), lb(250, ytop + hs / 2 + 4, c.perB, 12, C.purple, 'start', true)] },
      { note: s[2], add: c.mk3(g) },
      { note: s[3], add: c.s4 },
      { note: s[4], add: [lb(16, 218, c.l5, 13, C.ink, 'start', true)] },
      { note: s[5], add: [lb(16, 232, c.l6, 13, C.red, 'start', true)] },
    ],
    c.caption,
  );
}

// 余りと不足に分かれるタイプの面積図（lf_318・lf_321・lf_324）
function areaOpp(o: {
  a: number; b: number; n: number; T: number; u: string; who: string; item: string; thing: string;
  perA: [string, string]; top: string; aTxt: string; perUnit: string; l6: string; verify: string; ab: string; bb: string; caption: string;
}): Figure {
  const ra = o.a * o.n, rb = o.b * o.n;
  const yo = o.T - ra, fu = rb - o.T, d = yo + fu, st = o.b - o.a;
  return areaFig({
    a: o.a, b: o.b, top: o.top, aTxt: o.aTxt, perA: o.perA, perB: `あと${st}${o.u}`, whoLbl: `${o.who === '人' ? '人数' : '個数'}（□${o.who}）`,
    mk3: (g) => [...piece(g, 0, (g.Wn * yo) / d, `余り${yo}${o.u}`, C.green, FILL.green), ...piece(g, (g.Wn * yo) / d, (g.Wn * fu) / d, `足りない${fu}${o.u}`, C.red, FILL.red)],
    s4: [lb(16, 44, `色の部分 ＝ ${yo}＋${fu}＝${d}${o.u}`, 13, C.red, 'start', true)],
    l5: `${d}${o.u} ＝ ${st}${o.u} × □${o.who}`, l6: o.l6,
    notes: [
      `問 ${o.ab} 図にするとどうなるでしょうか。答 たて＝${o.item}、よこ＝${o.who === '人' ? '人数' : '個数'}にします。${o.a}${o.u}ずつ${o.thing}ぶんは、たて${o.a}${o.u}の長方形（面積＝${o.thing}数）です。`,
      `問 ${o.bb} 図はどう変わるでしょうか。答 ${o.who === '人' ? '人数' : '個数'}は同じなので、よこの長さは変わりません。たてが${st}${o.u}ぶん高くなり、細長い長方形（色の部分）がふえます。`,
      `問 その細長い長方形には、何がふくまれているでしょうか。答 ${o.a}${o.u}ずつなら${yo}${o.u}余り、${o.b}${o.u}ずつなら${fu}${o.u}足りません。色の部分は、余った${yo}${o.u}と足りない${fu}${o.u}に分けられます。`,
      `問 色の部分の面積は、いくつでしょうか。答 余りと足りない分は総数をはさんで反対側にあるので、あわせて${yo}＋${fu}＝${d}${o.u}です。`,
      `問 なぜ${d}${o.u}を、たての${st}${o.u}でわると${o.who === '人' ? '人数' : '個数'}が出るのでしょうか。答 色の部分は、たて${st}${o.u}×よこ（${o.who === '人' ? '人数' : '個数'}）の長方形です。面積＝たて×よこだから、よこ＝面積÷たて＝${d}÷${st}です。`,
      `問 ${o.who === '人' ? '人数' : '個数'}と${o.perUnit}は、いくつでしょうか。答 ${d}÷${st}＝${o.n}${o.who}。${o.verify}`,
    ],
    caption: o.caption,
  });
}

// ───────────────────────── 消去算の絵（丸で品物をならべる） ─────────────────────────
type Item = { ch: string; color: string; fill: string };
function elimPics(o: {
  shared: Item; other: Item; k: number; p: number; q: number; P: number; Q: number; sName: string; oName: string; sU: string; oU: string;
  bigRow: 0 | 1; // 品物が多いのはどちらの式か
  notes: [string, string, string, string, string, string];
  l5a: string; l5b: string; l6a: string; l6b: string; leftover: string; caption: string;
}): Figure {
  const rowY = [60, 110];
  const cnt = [o.k + o.p, o.k + o.q];
  const cx = (i: number) => 26 + i * 28;
  const circles = (r: number): DE[] => {
    const out: DE[] = [];
    for (let i = 0; i < cnt[r]; i++) {
      const it = i < o.k ? o.shared : o.other;
      out.push(ci(cx(i), rowY[r], 11, it.ch, it.color, it.fill, 11));
    }
    out.push(lb(cx(cnt[r] - 1) + 21, rowY[r] + 5, `＝${r === 0 ? o.P : o.Q}円`, 13, C.ink, 'start', true));
    return out;
  };
  const sharedLine = (r: number): DE => ln(cx(0) - 12, rowY[r] + 16, cx(o.k - 1) + 12, rowY[r] + 16, C.green, false, 3);
  // のこり：個数の多い式の、あとの d 個
  const d = Math.abs(o.q - o.p);
  const big = o.bigRow;
  const bigStart = o.k + Math.min(o.p, o.q);
  const leftLine = ln(cx(bigStart) - 12, rowY[big] + 16, cx(cnt[big] - 1) + 12, rowY[big] + 16, C.red, false, 3);
  const s = o.notes;
  void d;
  return show(
    [
      { note: s[0], add: circles(0) },
      { note: s[1], add: circles(1) },
      { note: s[2], add: [sharedLine(0), sharedLine(1), lb(16, 92, `どちらにも ${o.sName}${o.k}${o.sU}　→ 引くと消える`, 12, C.green, 'start', true)] },
      { note: s[3], add: [leftLine, lb(16, 146, o.leftover, 12, C.red, 'start', true)] },
      { note: s[4], add: [lb(16, 168, o.l5a, 12, C.ink, 'start', true), lb(16, 186, o.l5b, 12, C.ink, 'start', true)] },
      { note: s[5], add: [lb(16, 208, o.l6a, 12, C.main, 'start', true), lb(16, 226, o.l6b, 12, C.main, 'start', true)] },
    ],
    o.caption,
  );
}

// ───────────────────────── 消去算の線分図 ─────────────────────────
type Seg = [string, number, string, string]; // 名前, 金額, 色, 塗り
function elimBars(o: {
  rows: [Seg[], Seg[]]; sharedN: number; // 左から何こめまでが同じ部分か
  notes: [string, string, string, string, string, string];
  sharedLbl: string; leftLbl: string; l5: string; l6a: string; l6b: string; caption: string;
}): Figure {
  const k = 0.3, y = [50, 92], h = 26;
  const rowParts = (r: number): DE[] => {
    const out: DE[] = [];
    let x = 16;
    for (const [t, v, col, fl] of o.rows[r]) {
      out.push(bx(x, y[r], v * k, h, t, col, fl, 10));
      x += v * k;
    }
    const tot = o.rows[r].reduce((a, e) => a + e[1], 0);
    out.push(lb(x, y[r] - 4, `合計 ${tot}円`, 12, C.ink, 'end', true));
    return out;
  };
  const sharedW = o.rows[0].slice(0, o.sharedN).reduce((a, e) => a + e[1], 0) * k;
  const end0 = 16 + o.rows[0].reduce((a, e) => a + e[1], 0) * k;
  const end1 = 16 + o.rows[1].reduce((a, e) => a + e[1], 0) * k;
  const xs = 16 + sharedW;
  const left0 = Math.min(end0, end1), left1 = Math.max(end0, end1);
  const s = o.notes;
  return show(
    [
      { note: s[0], add: rowParts(0) },
      { note: s[1], add: rowParts(1) },
      { note: s[2], add: [ln(xs, 40, xs, 122, C.green, true, 2), ln(16, 134, xs, 134, C.green, false, 3), lb(clampX((16 + xs) / 2, tw(o.sharedLbl, 11) * 1.04), 148, o.sharedLbl, 11, C.green, 'middle', true)] },
      { note: s[3], add: [ln(left0, 134, left1, 134, C.red, false, 3), lb(clampX((left0 + left1) / 2, tw(o.leftLbl, 11) * 1.04), 164, o.leftLbl, 11, C.red, 'middle', true)] },
      { note: s[4], add: [lb(16, 186, o.l5, 12, C.ink, 'start', true)] },
      { note: s[5], add: [lb(16, 206, o.l6a, 12, C.main, 'start', true), lb(16, 224, o.l6b, 12, C.main, 'start', true)] },
    ],
    o.caption,
  );
}

