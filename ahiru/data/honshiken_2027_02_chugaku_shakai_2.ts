const ex = (o: Src): string =>
  '【何を聞かれているか】\n' + o.ask +
  '\n\n【なぜそうなるのか】\n' + o.why +
  o.steps.map((s, i) => '\n\n【ステップ' + (i + 1) + '】\n' + s).join('') +
  '\n\n【答え】\n' + o.ok +
  '\n\n【確かめ】\n' + o.check +
  '\n\n【よくあるまちがい】\n' + o.miss;

const q = (n: number, difficulty: 'basic' | 'standard' | 'advanced', pos: number, o: Src): Question => {
  const choices: string[] = [...o.ng];
  choices.splice(pos, 0, o.ok);
  return {
    id: 'honshiken_2027_02_shakai_c' + n,
    subject: 'shakai',
    examType: 'chugaku',
    difficulty,
    question: o.question,
    choices,
    answer: o.ok,
    hint: o.hint,
    explanation: ex(o),
    pitfall: o.pitfall,
    memoryTip: o.memoryTip,
  };
};

