ある地点を寒冷前線が通過した。通過の前後で、天気・気温・風向はどのように変化するか説明せよ。

【解答】
・天気：前線の通過時に積乱雲が発達し、短時間の激しい雨・雷が降る。通過後は急速に晴れる。
・気温：冷たい空気におおわれるため、通過後は気温が急に下がる。
・風向：前線通過にともなって、南寄りの風から北寄りの風に変わる。

