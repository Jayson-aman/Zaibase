// ふれはば amp、波の数 n、長さ len のぎざぎざ波
const wave = (x0: number, y0: number, amp: number, n: number, len: number, color: string) => {
  const half = len / (n * 2);
  const out = [];
  for (let i = 0; i < n * 2; i++) {
    const ya = y0 + (i % 2 === 0 ? -amp : amp);
    const yb = y0 + (i % 2 === 0 ? amp : -amp);
    out.push(ln(x0 + i * half, ya, x0 + (i + 1) * half, yb, color, false, 2));
  }
  return out;
};

