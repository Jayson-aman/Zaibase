// 下の帯（最下部）に、そのスライドのひとことを出す。\n で改行できる。
const cap = (t: string, c: Col = BLUE, size = 12): DiagramElement => {
  const h = 12 + 16 * t.split('\n').length;
  return bx(10, 232 - h, 300, h, t, c[0], c[1], size);
};
const S = (note: string, top: DiagramElement[], capText: string, c: Col = BLUE, size = 12) => ({
  note,
  add: fresh(...top, cap(capText, c, size)),
});
// 「なぜ？」の問い → 答え、の1組（答えの箱は高さ aH）
const qa = (q: string, a: string, c: Col = BLUE, aSize = 13, aH = 112): DiagramElement[] => [
  bx(10, 6, 300, 38, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12),
  ar(160, 46, 160, 58, PURPLE[0]),
  bx(10, 60, 300, aH, a, c[0], c[1], aSize),
];
const B = (x: number, y: number, w: number, h: number, t: string, c: Col, size = 12) => bx(x, y, w, h, t, c[0], c[1], size);
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44, gap = 14): DiagramElement[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap }).flat();
const col = (labels: string[], x: number, w: number, y0: number, c: Col = MAIN, size = 12, h = 26, gap = 12): DiagramElement[] =>
  stack(labels, x, w, y0, { h, gap, color: c[0], fill: c[1], size }).flat();
// 表（先頭行が見出し）
const tbl = (x: number, y: number, cws: number[], rh: number, rows: string[][], c: Col = BLUE, size = 11): DiagramElement[] =>
  rows.flatMap((r, i) => {
    let cx = x;
    return r.map((t, j) => {
      const e = bx(cx, y + i * rh, cws[j], rh, t, i === 0 ? c[0] : C.gray, i === 0 ? c[1] : '#FFFFFF', size);
      cx += cws[j];
      return e;
    });
  });
// 楕円の弧（矢印つき）。a0→a1 は度（右が0、上が90）。ry を負にすると下向きの弧。
const arc = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, color: string = C.blue, n = 10): DiagramElement[] => {
  const p: [number, number][] = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    p.push([cx + rx * Math.cos(a), cy - ry * Math.sin(a)]);
  }
  const out: DiagramElement[] = [];
  for (let i = 0; i < n - 1; i++) out.push(ln(p[i][0], p[i][1], p[i + 1][0], p[i + 1][1], color));
  out.push(ar(p[n - 1][0], p[n - 1][1], p[n][0], p[n][1], color));
  return out;
};
const T = (x: number, y: number, t: string, size = 12, color: string = C.ink, bold = true) => lb(x, y, t, size, color, 'middle', bold);

