// 波の線（山と谷）。x0 から幅 w、振幅 amp、cyc 個ぶんの山。
const wave = (x0: number, y0: number, w: number, amp: number, cyc: number, color: string = C.blue, n = 28): DiagramElement[] => {
  const out: DiagramElement[] = [];
  let px = x0;
  let py = y0;
  for (let i = 1; i <= n; i++) {
    const x = x0 + (w * i) / n;
    const y = y0 - amp * Math.sin((2 * Math.PI * cyc * i) / n);
    out.push(ln(px, py, x, y, color, false, 2));
    px = x;
    py = y;
  }
  return out;
};

