/** 下の帯に、ひとことを書く（前の帯はおおって消す）。 */
const say = (t: string, color: string = C.ink, size = 13): DiagramElement[] => band(150, lb(160, 185, t, size, color, 'middle', true));
const say2 = (a: string, b: string, color: string = C.ink): DiagramElement[] =>
  band(150, lb(160, 170, a, 13, color, 'middle', true), lb(160, 198, b, 12, C.gray, 'middle'));
/** 円を横にならべる。colorOf で色分けする。 */
const row = (n: number, x0: number, y: number, gap: number, r: number, fn: (i: number) => { c: string; f: string; t?: string }): DiagramElement[] =>
  Array.from({ length: n }, (_, i) => {
    const o = fn(i);
    return ci(x0 + i * gap, y, r, o.t, o.c, o.f, 9);
  });

