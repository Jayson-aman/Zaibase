const bobAt = (px: number, len: number, deg: number) => {
  const a = (deg * Math.PI) / 180;
  return { x: px + len * Math.sin(a), y: 12 + len * Math.cos(a) };
};
/** 振り子1本（支点 px, ひもの長さ len, ふれの角度 deg, おもりの大きさ r）。 */
const pend = (px: number, len: number, deg: number, r: number, text?: string, color: string = C.main, dashed = false): DiagramElement[] => {
  const p = bobAt(px, len, deg);
  return [ln(px, 12, p.x, p.y, dashed ? C.gray : color, dashed), ci(p.x, p.y, r, text, color, dashed ? '#FFFFFF' : FILL.warm, 9)];
};
