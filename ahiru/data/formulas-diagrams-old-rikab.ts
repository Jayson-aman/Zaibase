/** 小さな粒をばらまく（決まった並びなので毎回同じ）。 */
const scatter = (n: number, x0: number, y0: number, w: number, h: number, seed = 7, r = 2.5, color: string = C.main, fill: string = FILL.warm): DiagramElement[] => {
  let s = seed;
  const rnd = () => {
    s = (s * 1103515245 + 12345) % 2147483648;
    return s / 2147483648;
  };
  const out: DiagramElement[] = [];
  for (let i = 0; i < n; i++) out.push(ci(x0 + rnd() * w, y0 + rnd() * h, r, undefined, color, fill));
  return out;
};

