const P = (cx: number, cy: number, r: number, deg: number): Pt => [cx + r * Math.cos((deg * Math.PI) / 180), cy - r * Math.sin((deg * Math.PI) / 180)];
const poly = (pts: Pt[], color: string = C.ink, fill?: string, w = 2.5): E[] => (fill ? [pg(pts, color, fill)] : []).concat(pts.map((p, i) => ln(p[0], p[1], pts[(i + 1) % pts.length][0], pts[(i + 1) % pts.length][1], color, false, w)));
const dot = (p: Pt, color: string = C.red, r = 3): E => ci(p[0], p[1], r, undefined, color, color);
const arc = (cx: number, cy: number, r: number, from: number, to: number, color: string = C.ink, w = 3): E[] => {
  const n = Math.max(4, Math.round(Math.abs(to - from) / 8));
  const out: E[] = [];
  for (let i = 0; i < n; i++) {
    const a = P(cx, cy, r, from + ((to - from) * i) / n);
    const b = P(cx, cy, r, from + ((to - from) * (i + 1)) / n);
    out.push(ln(a[0], a[1], b[0], b[1], color, false, w));
  }
  return out;
};

