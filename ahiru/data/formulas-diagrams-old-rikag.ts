const zz = (x: number, y0: number, len: number, color: string = C.gray): DiagramElement[] => {
  const n = 10;
  const out: DiagramElement[] = [];
  const step = len / n;
  for (let i = 0; i < n; i++) {
    const xa = x + (i === 0 ? 0 : i % 2 === 1 ? -7 : 7);
    const xb = x + (i === n - 1 ? 0 : i % 2 === 0 ? -7 : 7);
    out.push(ln(xa, y0 + i * step, xb, y0 + (i + 1) * step, color, false, 2));
  }
  return out;
};

