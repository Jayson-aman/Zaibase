// 座標は 320×240 の内部座標。上（y<142）に図、下の帯（y≧146）に式。
import type { DiagramElement, Figure } from './figures';
import { C, FILL, bx, lb, ar, ln, ci, pg, show, band, fresh } from './diagram-kit';
import type { Slide } from './diagram-kit';

type E = DiagramElement;
const tx = (x: number, y: number, t: string, size = 12, color: string = C.ink, bold = true, anchor: 'start' | 'middle' | 'end' = 'middle'): E => lb(x, y, t, size, color, anchor, bold);

// 文字が箱に収まるまで、文字の大きさを小さくする箱
const cw = (c: string, s: number) => (/[\x20-\x7e]/.test(c) ? (c === ' ' ? 0.3 : /[0-9]/.test(c) ? 0.58 : /[A-Z]/.test(c) ? 0.66 : 0.52) * s : s);
const tw = (t: string, s: number) => Math.max(...t.split('\n').map((l) => [...l].reduce((a, c) => a + cw(c, s), 0)));
const fb = (x: number, y: number, w: number, h: number, t: string, col: string, fill: string, size = 13): E => {
  let s = size;
  while (s > 7 && (tw(t, s) > w - 5 || t.split('\n').length * s * 1.2 > h - 2)) s -= 0.5;
  return bx(x, y, w, h, t, col, fill, s);
};

// 下の帯：先頭文字で色（=緑 / ~赤 / *紫 / それ以外は青）。1行で先頭が「=答え」なら大きく。
const tone = (s: string): [string, string, string] => {
  const c = s[0];
  if (c === '=') return [s.slice(1), C.green, FILL.green];
  if (c === '~') return [s.slice(1), C.red, FILL.red];
  if (c === '*') return [s.slice(1), C.purple, FILL.purple];
  return [s, C.blue, FILL.blue];
};
const B = (lines: string[]): E[] => {
  if (lines.length === 1) {
    const [t, col, fill] = tone(lines[0]);
    const big = t.startsWith('答え');
    return band(146, fb(20, big ? 158 : 166, 280, big ? 42 : 36, t, col, fill, big ? 18 : 15));
  }
  const h = lines.length === 2 ? 36 : 27;
  const gap = lines.length === 2 ? 40 : 30;
  const y0 = lines.length === 2 ? 154 : 150;
  return band(146, ...lines.map((s, i) => {
    const [t, col, fill] = tone(s);
    return fb(20, y0 + i * gap, 280, h, t, col, fill, lines.length === 2 ? 14 : 13);
  }));
};
const SF = (note: string, lines: string[], draw: E[]): Slide => ({ note, add: [...fresh(...draw), ...B(lines)] });
const S = (note: string, lines: string[], add: E[] = []): Slide => ({ note, add: [...add, ...B(lines)] });
// 縦に並べた行（箱）。先頭文字で色。
const rows = (items: string[], y0 = 12, step = 30, h = 26, size = 12): E[] => items.map((s, i) => { const [t, col, fill] = tone(s); return fb(20, y0 + i * step, 280, h, t, col, fill, size); });
// 行だけのスライド（まっさらな画面に、行を並べる）
const RW = (note: string, lines: string[], items: string[], size = 12): Slide => {
  const n = items.length;
  const step = n <= 3 ? 36 : n === 4 ? 30 : 25;
  const h = n <= 3 ? 30 : n === 4 ? 25 : 21;
  const y0 = n <= 3 ? 14 : 10;
  return SF(note, lines, rows(items, y0, step, h, size));
};
type R3 = [string, string[], string[]];
const mk = (first: Slide, rest: (R3 | Slide)[], caption: string): Figure =>
  show([first, ...rest.map((r) => (Array.isArray(r) ? RW(r[0], r[1], r[2]) : r))], caption);
const L = (x: number, y: number, t: string, col: string = C.ink, size = 11): E => tx(x, y, t, size, col);
// 年表：left から順に upto 個ぶんの出来事を、年と名前つきで並べる。
const tline = (evs: [string, string][], upto: number, y = 66): E[] => {
  const out: E[] = [ln(20, y, 300, y, C.gray, false, 3)];
  const n = evs.length;
  evs.slice(0, upto).forEach(([name, yr], i) => {
    const x = n === 1 ? 160 : 44 + i * (232 / (n - 1));
    out.push(ci(x, y, 6, undefined, C.blue, FILL.blue));
    out.push(tx(x, y - 16, yr, 12, C.red));
    out.push(fb(x - 34, y + 14, 68, 40, name, C.blue, FILL.blue, 11));
  });
  return out;
};

