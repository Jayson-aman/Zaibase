const P = (cx: number, cy: number, r: number, deg: number): [number, number] => [cx + r * Math.cos((deg * Math.PI) / 180), cy - r * Math.sin((deg * Math.PI) / 180)];
// 頂点 V で、V→P と V→Q のあいだの角の二等分線上、距離 d の点
const bis = (V: [number, number], Pp: [number, number], Q: [number, number], d: number): [number, number] => {
  const a1 = Math.atan2(Pp[1] - V[1], Pp[0] - V[0]);
  const a2 = Math.atan2(Q[1] - V[1], Q[0] - V[0]);
  let m = (a1 + a2) / 2;
  if (Math.abs(a1 - a2) > Math.PI) m += Math.PI;
  return [V[0] + d * Math.cos(m), V[1] + d * Math.sin(m)];
};
const outer = (V: [number, number], O: [number, number], d: number): [number, number] => {
  const dx = V[0] - O[0], dy = V[1] - O[1], L = Math.hypot(dx, dy);
  return [V[0] + (dx / L) * d, V[1] + (dy / L) * d];
};
