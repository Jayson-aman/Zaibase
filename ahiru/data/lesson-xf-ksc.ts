// 下の帯（y=198 から）に、そのスライドのひとことを出す。\n で改行できる。
const bar = (t: string, c: Col = BLUE, size = 12): E => bx(8, 198, 304, 34, t, c[0], c[1], size);
// 1枚のスライド＝まっさらな図＋下の帯
const S = (note: string, top: E[], cap: string, c: Col = BLUE) => ({ note, add: fresh(...top, bar(cap, c)) });
// 「なぜ？」の問い
const Q = (q: string): E => bx(8, 6, 304, 28, 'なぜ？ ' + q, PURPLE[0], PURPLE[1], 12);
// 文字を縦にならべる（中央ぞろえ）
const ls = (lines: string[], y: number, o: { x?: number; dy?: number; size?: number; color?: string; anchor?: 'start' | 'middle' | 'end'; bold?: boolean } = {}): E[] =>
  lines.map((t, i) => lb(o.x ?? 160, y + i * (o.dy ?? 20), t, o.size ?? 13, o.color ?? C.ink, o.anchor ?? 'middle', o.bold));
// 箱を矢印でつないだ横一列
const row = (labels: string[], y: number, c: Col = MAIN, size = 12, h = 44): E[] =>
  flow(labels, y, { h, color: c[0], fill: c[1], size, gap: 14 }).flat();
// 表（先頭行を見出し色にする）
const tbl = (x: number, y: number, cw: number[], rh: number, rows: string[][], c: Col = BLUE, size = 12): E[] => {
  const out: E[] = [];
  rows.forEach((r, i) => {
    let xx = x;
    r.forEach((t, j) => {
      out.push(bx(xx, y + i * rh, cw[j], rh, t, i === 0 ? c[0] : C.gray, i === 0 ? c[1] : '#FFFFFF', size));
      xx += cw[j];
    });
  });
  return out;
};
// 座標平面（原点の位置 ox,oy と 1目もりのピクセル数 sx,sy）
const GR = (ox: number, oy: number, sx: number, sy: number) => {
  const X = (v: number) => ox + v * sx;
  const Y = (v: number) => oy - v * sy;
  return {
    X, Y,
    axes: (xmin: number, xmax: number, ymin: number, ymax: number): E[] => [
      ln(X(xmin), Y(0), X(xmax), Y(0), C.gray, false, 1.4),
      ln(X(0), Y(ymax), X(0), Y(ymin), C.gray, false, 1.4),
      lb(X(xmax) - 2, Y(0) + 11, 'x', 11, C.gray, 'end'),
      lb(X(0) + 8, Y(ymax) + 6, 'y', 11, C.gray, 'start'),
      lb(X(0) - 5, Y(0) + 10, 'O', 10, C.gray, 'end'),
    ],
    line: (x1: number, y1: number, x2: number, y2: number, col: string = C.blue, dashed = false, w = 2.2): E => ln(X(x1), Y(y1), X(x2), Y(y2), col, dashed, w),
    pt: (x: number, y: number, col: string = C.red, r = 3.5): E => ci(X(x), Y(y), r, undefined, col, col),
    t: (x: number, y: number, text: string, dx = 0, dy = 0, size = 11, col: string = C.ink, anchor: 'start' | 'middle' | 'end' = 'middle'): E => lb(X(x) + dx, Y(y) + dy, text, size, col, anchor, true),
    curve: (f: (x: number) => number, xs: number[], col: string = C.blue): E[] => {
      const out: E[] = [];
      for (let i = 0; i + 1 < xs.length; i++) out.push(ln(X(xs[i]), Y(f(xs[i])), X(xs[i + 1]), Y(f(xs[i + 1])), col, false, 2.2));
      return out;
    },
  };
};
const rng = (a: number, b: number, n: number): number[] => Array.from({ length: n + 1 }, (_, i) => a + ((b - a) * i) / n);

