// 「なぜ？」の連鎖で、7枚以上。上半分に図、下の帯（band）にそのスライドのひとこと。
import type { DiagramFigure } from './figures';
import { show, bx, lb, ar, ln, ci, band, fresh, C, FILL } from './diagram-kit';

const K = {
  b: [C.blue, FILL.blue],
  g: [C.green, FILL.green],
  r: [C.red, FILL.red],
  m: [C.main, FILL.warm],
  p: [C.purple, FILL.purple],
  y: [C.gray, FILL.gray],
  w: [C.ink, '#FFFFFF'],
} as const;
type KK = keyof typeof K;
const B = (x: number, y: number, w: number, h: number, t: string, k: KK = 'm', s = 12) => {
  // 幅のせまい箱で「見出し　説明」が1行に入っているときは、2行に分けて文字が小さくなりすぎないようにする
  let tt = t;
  let ss = s;
  if (w < 170 && h >= 28 && !t.includes('\n') && t.indexOf('　') > 2 && t.length > 9) {
    tt = t.replace('　', '\n');
    ss = Math.min(s, 10);
  }
  return bx(x, y, w, h, tt, K[k][0], K[k][1], ss);
};
const T = (x: number, y: number, t: string, s = 12, c: string = C.ink) => lb(x, y, t, s, c, 'middle', true);
const row = (y: number, h: number, ts: string[], ks: string, s = 12, gap = 10, x0 = 8, wTot = 304) => {
  const n = ts.length;
  const w = (wTot - gap * (n - 1)) / n;
  return ts.map((t, i) => B(x0 + i * (w + gap), y, w, h, t, (ks[i] ?? ks[0]) as KK, s));
};
const dn = (x: number, y1: number, y2: number, c: string = C.main) => ar(x, y1, x, y2, c);
const cap = (t: string, c: string = C.ink) => band(150, lb(160, 190, t, 12, c, 'middle', true));
const F = (note: string, capt: string, els: ReturnType<typeof bx>[], c: string = C.ink) => ({ note, add: [...fresh(...els), ...cap(capt, c)] });
const A = (note: string, capt: string, els: ReturnType<typeof bx>[], c: string = C.ink) => ({ note, add: [...els, ...cap(capt, c)] });

